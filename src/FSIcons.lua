--[[
  FSIcons.lua  -  "FS Icons": FireSystem's button icons on the other FS tools' layouts
  ------------------------------------------------------------------------
  One of the single-purpose FireSystem tools. Run it (click it in the Plugins pool) after the other
  tools: it goes through their layouts ("FS DF Dimmer FX", "FS PP Position Picker" ...) and gives
  every button that FireSystem draws with an icon (forms, levels, pans, tilts, position FX, Off,
  Rnd, Strobe, Iris, Zoom, Gobo, Prism ...) a nicer appearance:

    FireSystem look (default)  FireSystem's round icon discs (Appearances 2001+) and orange number
                               discs for 0 / 50 / 100 % (4001+): dark when off, lit when on. The
                               button's text goes (the icon says it).
    Keep colour and text       the button keeps its colours and its text and gets FireSystem's
                               square icon on top ("FS IC ..." appearances, 3001+).

  Buttons FireSystem has no icon for get the minis' own (MINI below, Appearances 9101+): Fade,
  Delay, Wings, Phase, Blocks, Speed, Groups, Steps, Part, Master ... get a small icon at the top
  and keep their text (it shows the value), the extra tilts, FX sizes, Normal / Pastel / Dark and the
  LOS bumps get a full disc. Colour swatches, STEP colours and group buttons are left as they are. Appearance
  slots that hold something that isn't FireSystem's ("FS ...") are left alone: that button keeps
  its text.

  The images are in this plugin (a copy of FireSystem's FireSystemIcons.lua plus the mini icons,
  nothing else to import) and go into FireSystem's own image slots (the mini icons into 3.3101+),
  so a show that has FireSystem shares them. To go back to plain buttons, build that tool again.
  The show doesn't need the plugin afterwards.

  ONE FILE, NO OTHER PLUGIN NEEDED: plugins/FSIcons.lua is generated by tools/make_tools.py from
  this source, the shared tool code in src/lib/, a copy of the FireSystem module files and the
  images (firesystem/FireSystemIcons.lua and icons/mini/, drawn by tools/make_mini_icons.py).
--]]

local TITLE = "FS Icons"
local TAG = "IC"       -- this tool's appearances: "FS IC <icon> <r>.<g>.<b>"
local VARP = "FSIC_"   -- this tool's global variables

