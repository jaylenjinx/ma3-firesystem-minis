--[[
  FSIcons.lua  -  "FS Icons": FireSystem's button icons on the other FS tools' layouts
  ------------------------------------------------------------------------
  One of the single-purpose FireSystem tools. Run it (click it in the Plugins pool) after the other
  tools: it goes through their layouts ("FS DF Dimmer FX", "FS PP Position Picker" ...) and gives
  their buttons nicer appearances:

    FireSystem look (default)  round icon discs, dark when off and lit when on, and the button's text
                               goes (the icon says it): FireSystem's own (Appearances 2001+, number
                               discs 4001+) and this tool's for what FireSystem has none for (extra
                               tilts, sizes, LOS bumps, colour swatches, tints, step counts ...,
                               Images 3.3101+, Appearances 9101+)
    Keep colour and text       the button keeps its colours and its text and gets the square icon
                               on top ("FS IC ..." appearances, 9501+)

  Value buttons (Wings, Blocks, Groups, Phase, Delay, Fade, Speed, Sym, Part, Hold, Out, Edit Step,
  STEP 1-5, Step Count, FS LOS's timing) keep their text, which changes, with an icon above it in
  the button's own colours (FireSystem look: on black where the button was grey). Icon buttons lose
  their border. Buttons that light one of a set (Normal / Pastel / Dark, 2 / 3 Steps, Small / Mid /
  Big, FS LOS's colours) get their macro lines pointed at the icons, so a tap keeps them. Group buttons keep their text. Appearance slots that hold something that
  isn't FireSystem's ("FS ...") are left alone: that button keeps its text.

  The images are inside this plugin (FireSystem's, as its FireSystemIcons.lua has them, and this
  tool's own from icons/mini/, made by tools/make_icons.py). FireSystem's go into FireSystem's own
  image slots, so a show that has FireSystem shares them. To go back to plain buttons, build that
  tool again. The show doesn't need the plugin afterwards.

  ONE FILE, NO OTHER PLUGIN NEEDED: plugins/FSIcons.lua is generated by tools/make_tools.py from
  this source, the shared tool code in src/lib/ and a copy of the FireSystem module files.
--]]

local TITLE = "FS Icons"
local TAG = "IC"       -- this tool's appearances: "FS IC <icon> <r>.<g>.<b>"
local VARP = "FSIC_"   -- this tool's global variables

--@INCLUDE common@

-- the images (generated): ICON_DATA[file] = base64 PNG, FireSystem's and this tool's own;
-- MINI_FILES = this tool's own, in the order of their image numbers
--@ICONDATA@

local KEEP = "Keep each button's colour and text"
local KEEP_AP_FROM = 9501                      -- keep-look and top-icon appearances (made as needed)
local MINI_IMAGE_BASE, MINI_AP_BASE = 3101, 9101   -- this tool's images / their disc appearances
local MINI_IDX = {}
for i, f in ipairs(MINI_FILES) do MINI_IDX[f] = i end
-- the tools whose layouts get icons (their tags: "FS <tag> ...")
local TOOL_TAGS = {DF = true, CF = true, PP = true, BS = true, GB = true, CP = true, LO = true}
-- value buttons: FireSystem's orange number discs
local NUMBERS = {["0%"] = "0", ["50%"] = "50", ["100%"] = "100"}
-- value buttons that keep their text (it changes: "Wings 2", "Fade 0.5" ...): an icon at the top,
-- the text under it. {pattern on the text (or the object's name), top icon}
local TOPS = {
  {"^Wings", "wings"}, {"^Blocks", "block"}, {"^Groups", "group"}, {"^Phase", "phase"},
  {"^Delay", "delay"}, {"^Fade", "fade"}, {"^Speed", "speed"}, {"^Sym", "sym"}, {"^Part", "part"},
  {"^Hold", "hold"}, {"^Out", "fadeout"}, {"^Edit Step", "edit"},
  {"^STEP 1", "step1"}, {"^STEP 2", "step2"}, {"^STEP 3", "step3"}, {"^STEP 4", "step4"}, {"^STEP 5", "step5"},
}
-- FS LOS's timing buttons, by their names ("FS LO LOS1 Off input", "... Fade 0", "... Blocks")
local LOS_TOPS = {Fade = "fade", Delay = "delay", Off = "offtime", Wings = "wings", Blocks = "block"}

local function gvar(k) local v = GetVar(GlobalVars(), VARP .. k) return v end
local function svar(k, v) SetVar(GlobalVars(), VARP .. k, tostring(v)) end

-- An icon is "name" (one of FireSystem's: its round discs, or its square icon), "m:name" (one of
-- this tool's discs), "sw:name" (a colour swatch disc) or "t:name" (a top icon, the text stays).
local function known(E, icon)
  local k, n = icon:match("^(%a+):(.+)$")
  if not k then return E.ICON_IDX[icon] ~= nil end
  if k == "m" then return MINI_IDX["fs_m_" .. n .. "_i.png"] ~= nil end
  if k == "sw" then return MINI_IDX["fs_sw_" .. n .. "_i.png"] ~= nil end
  return MINI_IDX["fs_t_" .. n .. ".png"] ~= nil
end

-- button text -> icon: {static = {...}, fx = {...}} (a pan and a pan FX can share a name:
-- the FX's sequences and macros are named "... FX")
local function iconMaps(E)
  local m = {["0%"] = "bulb_off", ["50%"] = "bulb_half", ["100%"] = "bulb_full", Off = "power",
             Bump = "bulb_full", ["Bump All"] = "bulb_full", Rnd = "random", ["Rnd All"] = "random",
             Strobe = "strobe", ["Strobe All"] = "strobe", Iris = "iris", Zoom = "cone", Gobo = "gobo",
             ["Gobo 1"] = "gobo", ["Gobo 2"] = "gobo", ["Gobo Spin"] = "gobo", Prism = "prism",
             ["Prism Spin"] = "prism", Dim = "bulb_half", Pos = "fan", Shutter = "strobe",
             -- this tool's own
             Small = "m:size_s", Mid = "m:size_m", Big = "m:size_b",
             ["All >"] = "m:los_right", ["All <"] = "m:los_left", Odd = "m:los_odd", Even = "m:los_even",
             ["1/3"] = "m:los_third1", ["2/3"] = "m:los_third2", ["3/3"] = "m:los_third3", Chase = "m:los_chase",
             Steps = "m:steps", ["Steps All"] = "m:steps", Master = "m:master", Color = "m:palette",
             Focus = "m:focus", Frost = "m:frost",
             Normal = "m:tint_normal", Pastel = "m:tint_pastel", Dark = "m:tint_dark",
             ["2 Steps"] = "m:steps2", ["3 Steps"] = "m:steps3", ["4 Steps"] = "m:steps4", ["5 Steps"] = "m:steps5"}
  for _, deg in ipairs({-90, -60, -45, -30, -10, 10, 20, 75}) do
    m["Tilt " .. deg] = "m:tilt_" .. (deg < 0 and "m" or "") .. math.abs(deg)
  end
  for _, c in ipairs(E.CFG.COLORS or {}) do m[c[1]] = "sw:" .. c[1]:lower():gsub(" ", "_") end
  for k, v in pairs(E.FN.ICON_BY_LABEL or {}) do m[k] = m[k] or v end
  for _, f in ipairs(E.DIM_FORMS or {}) do
    if f[2] and E.FN.ICON_BY_LABEL[f[1]] then m[f[2]] = E.FN.ICON_BY_LABEL[f[1]] end
  end
  for i, p in ipairs(E.PANS or {}) do if p[2] then m[p[2]] = "pan" .. i end end
  for i, t in ipairs(E.TILTS or {}) do if t[2] then m[t[2]] = "tilt" .. i end end
  local fx, mv = {}, (E.TC and E.TC.MOVE_ICON) or {}
  for i, f in ipairs(E.PAN_FX or {}) do if f[2] and mv.pan and mv.pan[i] then fx[f[2]] = mv.pan[i] end end
  for i, f in ipairs(E.TILT_FX or {}) do if f[2] and mv.tilt and mv.tilt[i] then fx[f[2]] = mv.tilt[i] end end
  local function only(t) for k, v in pairs(t) do if not known(E, v) then t[k] = nil end end return t end
  return {static = only(m), fx = only(fx)}
end

-- the button's icon: returns label, icon. The label is its text, or (once a disc hid the text)
-- the end of its object's name.
local function iconOf(E, maps, kind, text, name)
  -- FS LOS's timing buttons (their text is the typed value)
  local word = name:match("^" .. E.CFG.PREFIX .. " LO .- (%a+) input$") or name:match("^" .. E.CFG.PREFIX .. " LO .- (%a+) %d$")
    or name:match("^" .. E.CFG.PREFIX .. " LO .- (Blocks)$")
  if word and LOS_TOPS[word] then return text, "t:" .. LOS_TOPS[word] end
  local isFx = name:find(" FX$") ~= nil
  local t = isFx and maps.fx or maps.static
  local label = (text or ""):gsub("^LOS%d+ ", "")
  -- FS Bumps' Step Count (a cycling sequence: "1 Step", "2 Steps" ...)
  if kind == "Sequence" and label:match("^%d+ Steps?$") then return text, known(E, "t:stepcount") and "t:stepcount" or nil end
  if label ~= "" then
    if t[label] then return label, t[label] end
    for _, r in ipairs(TOPS) do if label:find(r[1]) and known(E, "t:" .. r[2]) then return text, "t:" .. r[2] end end
    return label, nil
  end
  local base, best = isFx and name:sub(1, -4) or name, nil
  for k in pairs(t) do
    if (base:sub(-#k - 1) == " " .. k) and (not best or #k > #best) then best = k end
  end
  return best, best and t[best]
end

-- someone else's appearance in that slot (then it's left alone)
local function foreign(E, no)
  local h = E.obj("Appearance " .. no)
  if not h then return false end
  local name = tostring(E.objName(h) or "")
  return name ~= "" and name:sub(1, #E.CFG.PREFIX + 1) ~= E.CFG.PREFIX .. " "
end

-- one of this tool's images: its number (imported once), or nil
local function miniImage(E, file)
  local i = MINI_IDX[file]
  if not i then return nil end
  local no = MINI_IMAGE_BASE + i - 1
  return E.importImage(no, file) and no or nil
end

-- FireSystem look: the disc for state k ("idle" / "on"), or nil
local function discAp(E, k, icon, text)
  local si = E.ROUND_STATE[k]
  local kk, n = icon:match("^(%a+):(.+)$")
  if kk == "m" or kk == "sw" then
    local file = string.format("fs_%s_%s_%s.png", kk, n, k == "idle" and "i" or "o")
    local i = MINI_IDX[file]
    if not i or foreign(E, MINI_AP_BASE + i - 1) then return nil end
    local img = miniImage(E, file)
    return img and E.makeImageAp(MINI_AP_BASE + i - 1, "ic " .. file:sub(4, -5), img) or nil
  end
  local num = NUMBERS[text]
  if num then
    local ni = E.ICN.NUM[num .. "|orange"]
    if not ni then return nil end
    local slot = ni > 80 and (E.CFG.NUM2_AP_BASE + (ni - 81) * 3 + si) or (E.CFG.NUM_AP_BASE + (ni - 1) * 3 + si)
    if foreign(E, slot) then return nil end
    return E.ICN.numAp(k, num, "orange")
  end
  local ii = E.ICON_IDX[icon]
  if not ii or foreign(E, E.CFG.ROUND_AP_BASE + (ii - 1) * 3 + si) then return nil end
  return E.FN.roundIconAp(k, icon)
end

-- the colour of an object's appearance ({r, g, b}), or nil
local function colourOf(E, addr)
  local rgb
  pcall(function()
    local ap = E.obj(addr).Appearance
    if ap then
      local r, g, b = tonumber(ap.BackR), tonumber(ap.BackG), tonumber(ap.BackB)
      if r and g and b then rgb = {r, g, b} end
    end
  end)
  return rgb
end

-- a dark neutral grey (the tools' idle buttons)
local function darkGrey(rgb)
  return math.max(rgb[1], rgb[2], rgb[3]) < 128 and math.max(rgb[1], rgb[2], rgb[3]) - math.min(rgb[1], rgb[2], rgb[3]) <= 12
end

-- an appearance with this colour and an image on it (keep look, top icons), or nil. black = a dark
-- grey becomes black (FireSystem look: value buttons sit on black like the discs)
local function colourAp(E, made, icon, rgb, black)
  if not rgb then return nil end
  if black and darkGrey(rgb) then rgb = {0, 0, 0} end
  local kk, n = icon:match("^(%a+):(.+)$")
  if kk == "sw" then return nil end   -- (colour buttons already show their colour)
  local key = string.format("%s %d.%d.%d", icon, rgb[1], rgb[2], rgb[3])
  if made[key] ~= nil then return made[key] or nil end
  local img
  if kk == "m" then img = miniImage(E, "fs_m_" .. n .. ".png")
  elseif kk == "t" then img = miniImage(E, "fs_t_" .. n .. ".png")
  else
    img = E.CFG.ICON_IMAGE_BASE + E.ICON_IDX[icon] - 1
    if not E.importImage(img, "fs_" .. icon .. ".png") then img = nil end
  end
  if not img then made[key] = false return nil end
  local want = E.fs(TAG .. " " .. key)
  local no
  local l = ObjectList('Appearance "' .. want .. '"')
  if l and l[1] then pcall(function() no = tonumber(l[1].no) end) end
  if not no then
    no = KEEP_AP_FROM
    while E.obj("Appearance " .. no) and no < 9999 do no = no + 1 end
  end
  E.imageAp(no, want, rgb, img)
  made[key] = no
  return no
end

-- an appearance's colour ({r, g, b}), or nil
local function apColour(E, no)
  local rgb
  pcall(function()
    local ap = E.obj("Appearance " .. no)
    local r, g, b = tonumber(ap.BackR), tonumber(ap.BackG), tonumber(ap.BackB)
    if r and g and b then rgb = {r, g, b} end
  end)
  return rgb
end

-- does this appearance mean off ("idle") or on? By its name (the tools' "... idle", "... off",
-- "... dim"; the discs' "... idle" / "_i"), else by how bright it is
local function apState(E, no)
  local name = ""
  pcall(function() name = tostring(E.objName(E.obj("Appearance " .. no)) or "") end)
  if name:find("idle$") or name:find(" off$") or name:find(" dim$") or name:find("_i$") then return "idle" end
  if name:find(" on$") or name:find(" lit$") or name:find("_o$") then return "on" end
  local rgb = apColour(E, no)
  return (rgb and math.max(rgb[1], rgb[2], rgb[3]) < 128) and "idle" or "on"
end

-- the tools' layouts: {{no, handle}, ...}
local function toolLayouts(E)
  local found, seen = {}, {}
  local function add(h)
    local no, name
    pcall(function() no = tonumber(h.no) or tonumber(h.No) end)
    pcall(function() name = tostring(E.objName(h) or "") end)
    local tag = name and name:match("^" .. E.CFG.PREFIX .. " (%u%u) ")
    if no and tag and TOOL_TAGS[tag] and not seen[no] then seen[no] = true found[#found + 1] = {no, h} end
  end
  pcall(function() for _, h in ipairs(DataPool().Layouts:Children()) do add(h) end end)
  local ok, list = pcall(ObjectList, 'Layout "' .. E.CFG.PREFIX .. ' "*')
  for _, h in ipairs(ok and type(list) == "table" and list or {}) do add(h) end
  table.sort(found, function(a, b) return a[1] < b[1] end)
  return found
end

-- one button: returns true when it got its icon
local function iconButton(E, maps, made, keep, e, iconed)
  local o, text
  pcall(function() o = e.Object end)
  pcall(function() text = e.CustomTextText end)
  if not o then return nil end
  local kind, no, name
  pcall(function() kind = tostring(o:GetClass()) end)
  pcall(function() no = tonumber(o.no) or tonumber(o.No) end)
  pcall(function() name = tostring(E.objName(o) or "") end)
  if not (kind == "Sequence" or kind == "Macro") or not no or not name then return nil end
  if name:sub(1, #E.CFG.PREFIX + 1) ~= E.CFG.PREFIX .. " " then return nil end
  local label, icon = iconOf(E, maps, kind, text and tostring(text) or "", name)
  if not icon then return nil end
  local top = icon:sub(1, 2) == "t:"
  if keep and icon:sub(1, 3) == "sw:" then return nil end   -- (colour buttons keep their look)
  local own = keep or top          -- the button's own colours, with the icon on them
  local addr = kind .. " " .. no
  local done = false
  if kind == "Sequence" then
    -- discs: both or neither (a button half dark disc, half old look is no use)
    local idle, lit
    if not own then
      idle, lit = discAp(E, "idle", icon, label), discAp(E, "on", icon, label)
      if not (idle and lit) then return false end
    end
    local off = own and colourAp(E, made, icon, colourOf(E, addr), not keep) or idle
    if off then E.C("Assign Appearance %d At %s", off, addr) done = true end
    for k = 1, 99 do
      local cue = string.format("%s Cue %d", addr, k)
      if not E.obj(cue) then break end
      -- (a picker's "Off" step: the dark disc)
      local on = own and colourAp(E, made, icon, colourOf(E, cue), not keep) or (E.objName(E.obj(cue)) == "Off" and idle or lit)
      if on then
        E.C("Assign Appearance %d At %s", on, cue)
        E.Cany({ string.format("Assign Appearance %d At %s Part 0", on, cue) })
        done = true
      end
    end
  else
    -- macros: dark or lit as their look was (Off dark); the radio buttons' lines that switch
    -- looks are pointed at these icons afterwards (fixLines)
    local cur
    pcall(function() cur = tonumber(E.obj(addr).Appearance.no) end)
    local k = (label == "Off" or (cur and apState(E, cur) == "idle")) and "idle" or "on"
    local ap = own and colourAp(E, made, icon, colourOf(E, addr), not keep) or (not own and discAp(E, k, icon, label))
    if ap then E.C("Assign Appearance %d At %s", ap, addr) done = true end
    if done and iconed then iconed[no] = {icon = icon, label = label, own = own} end
  end
  if done then pcall(function() e.VisibilityBorder = false end) end
  if done and top then pcall(function() e.CustomTextAlignmentV = "Bottom" end)
  elseif done and not keep then pcall(function() e.CustomTextText = "" end) end
  return done
end

-- "5", "5 Thru 8 + 10" -> {5, 6, 7, 8, 10}, or nil
local function expandList(s)
  local l = {}
  for part in s:gmatch("[^+]+") do
    local a, b = part:match("^%s*(%d+) Thru (%d+)%s*$")
    if a then for k = tonumber(a), tonumber(b) do l[#l + 1] = k end
    else
      local n = tonumber(part:match("^%s*(%d+)%s*$") or "")
      if not n then return nil end
      l[#l + 1] = n
    end
  end
  return l
end

-- one "Assign Appearance <aps> At Macro <list>" command with the icon macros' appearances swapped
-- for their icons (an idle look -> the dark disc, a lit one -> the lit disc; keep look: the square
-- icon on that colour). Anything else comes back as it was.
local function fixCommand(E, made, keep, iconed, c)
  local aps, ms = c:match("^%s*Assign Appearance (.-) At Macro (.-)%s*$")
  local A, M = aps and expandList(aps), ms and expandList(ms)
  if not (A and M) or not (#A == 1 or #A == #M) then return c end
  local groups, order, changed = {}, {}, false
  for i, m in ipairs(M) do
    local a = #A == 1 and A[1] or A[i]
    local ic = iconed[m]
    if ic then
      local new = ic.own and colourAp(E, made, ic.icon, apColour(E, a), not keep) or (not ic.own and discAp(E, apState(E, a), ic.icon, ic.label))
      if new and new ~= a then a = new changed = true end
    end
    if not groups[a] then groups[a] = {} order[#order + 1] = a end
    table.insert(groups[a], m)
  end
  if not changed then return c end
  local out = {}
  for _, a in ipairs(order) do out[#out + 1] = string.format("Assign Appearance %d At Macro %s", a, E.rangeList(groups[a])) end
  return table.concat(out, "; ")
end

-- the macros on the layouts whose lines switch looks (Normal / Pastel / Dark, 2 / 3 Steps, Small /
-- Mid / Big, FS LOS's colours): their lines now switch between the icons, not the old looks
local function fixLines(E, made, keep, iconed, macros)
  for _, M in ipairs(macros) do
    local h = E.obj("Macro " .. M)
    local n = 0
    pcall(function() n = h:Count() end)
    for i = 1, n do
      local line, cmd
      pcall(function() line = h[i] cmd = tostring(line.Command or "") end)
      if cmd and cmd:find("Assign Appearance", 1, true) then
        local parts = {}
        for c in (cmd .. ";"):gmatch("(.-);") do parts[#parts + 1] = fixCommand(E, made, keep, iconed, c) end
        local new = table.concat(parts, "; "):gsub("^%s+", "")
        if new ~= cmd and not pcall(function() line:Set("Command", new) end) then
          E.C('Set Macro %d.%d Property "Command" %s', M, i, E.q(new))
        end
      end
    end
  end
end

local function applyIcons(E, keep)
  E.failures = {}
  E.FireSystemIconData = ICON_DATA   -- (the modules' image import writes the PNGs from it)
  local maps, made = iconMaps(E), {}
  local layouts = toolLayouts(E)
  if #layouts == 0 then
    return {"No FS tool layouts in the show yet. Build FS Dimmer FX, FS Colour FX, FS Position Picker, FS Bumps ... first, then run " .. TITLE .. " again."}
  end
  local n, missed, used = 0, 0, 0
  local iconed, macros = {}, {}
  for _, l in ipairs(layouts) do
    local count, any = 0, false
    pcall(function() count = l[2]:Count() end)
    for i = 1, count do
      local e
      pcall(function() e = l[2][i] end)
      local r = e and iconButton(E, maps, made, keep, e, iconed)
      pcall(function()
        local o = e.Object
        if tostring(o:GetClass()) == "Macro" then macros[#macros + 1] = tonumber(o.no) or tonumber(o.No) end
      end)
      if r then n = n + 1 any = true elseif r == false then missed = missed + 1 end
    end
    if any then used = used + 1 end
  end
  fixLines(E, made, keep, iconed, macros)
  svar("keep", keep and "1" or "0")
  local lines = {}
  if n == 0 and missed > 0 then
    lines[1] = "No icon images could be imported (media/images not writable?). Run " .. TITLE .. " again, or import FireSystem's PNGs into media/images."
    return lines
  end
  lines[1] = string.format("%d buttons on %d layout%s got FireSystem icons%s.", n, used, used == 1 and "" or "s",
    keep and " in their own colours" or "")
  if missed > 0 then lines[#lines + 1] = string.format("%d buttons kept their text (no image, or an appearance slot that isn't FireSystem's).", missed) end
  lines[#lines + 1] = "To go back to plain buttons, build that tool again."
  return lines
end

local function main(displayHandle, argument)
  if not env then
    local ok, E = pcall(build)
    if not ok then return say(tostring(E)) end
    env = E
  end
  local E = env
  local r = MessageBox({
    title = TITLE,
    message = "Gives the FS tools' buttons FireSystem's icons (forms, levels, pans, tilts, position FX, Off,\n" ..
              "Rnd, Strobe, Iris, Zoom, Gobo, Prism ...): round discs, dark when off and lit when on, without text.\n" ..
              KEEP .. ": the buttons keep their colours and text and get the icon on top.\n" ..
              "Value buttons (Wings, Fade, Delay ...) keep their text, with an icon above it.",
    commands = {{value = 1, name = "Apply"}, {value = 0, name = "Cancel"}},
    states = {{name = KEEP, state = gvar("keep") == "1"}},
  })
  if not r or r.result ~= 1 then return end
  local keep = r.states and r.states[KEEP] == true
  local ok, lines = pcall(applyIcons, E, keep)
  if not ok then return say("Stopped: " .. tostring(lines)) end
  if #E.failures > 0 then
    lines[#lines + 1] = string.format("\n%d commands failed, first: %s", #E.failures, E.failures[1])
    for _, f in ipairs(E.failures) do Printf(TITLE .. ": " .. f) end
  end
  say(table.concat(lines, "\n"))
end

return rerunnable(main)
