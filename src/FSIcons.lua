-- their slots: Image 3.3101+ (3 discs each), 3.3501+ (the square icon), Appearance 9101+ (3 each)
local MINI_IMAGE_BASE, MINI_SQUARE_BASE, MINI_AP_BASE = 3101, 3501, 9101

local function gvar(k) local v = GetVar(GlobalVars(), VARP .. k) return v end
local function svar(k, v) SetVar(GlobalVars(), VARP .. k, tostring(v)) end

-- button text -> icon: {static = {...}, fx = {...}} (a pan and a pan FX can share a name:
-- the FX's sequences and macros are named "... FX")
local function iconMaps(E)
  local m = {["0%"] = "bulb_off", ["50%"] = "bulb_half", ["100%"] = "bulb_full", Off = "power",
             Bump = "bulb_full", ["Bump All"] = "bulb_full", Rnd = "random", ["Rnd All"] = "random",
             Strobe = "strobe", ["Strobe All"] = "strobe", Iris = "iris", Zoom = "cone", Gobo = "gobo",
             ["Gobo 1"] = "gobo", ["Gobo 2"] = "gobo", Prism = "prism", Dim = "bulb_half", Pos = "fan"}
  for k, v in pairs(E.FN.ICON_BY_LABEL or {}) do m[k] = m[k] or v end
  for _, f in ipairs(E.DIM_FORMS or {}) do
    if f[2] and E.FN.ICON_BY_LABEL[f[1]] then m[f[2]] = E.FN.ICON_BY_LABEL[f[1]] end
  end
  for i, p in ipairs(E.PANS or {}) do if p[2] then m[p[2]] = "pan" .. i end end
  for i, t in ipairs(E.TILTS or {}) do if t[2] then m[t[2]] = "tilt" .. i end end
  local fx, mv = {}, (E.TC and E.TC.MOVE_ICON) or {}
  for i, f in ipairs(E.PAN_FX or {}) do if f[2] and mv.pan and mv.pan[i] then fx[f[2]] = mv.pan[i] end end
  for i, f in ipairs(E.TILT_FX or {}) do if f[2] and mv.tilt and mv.tilt[i] then fx[f[2]] = mv.tilt[i] end end
  local function known(t) for k, v in pairs(t) do if not E.ICON_IDX[v] then t[k] = nil end end return t end
  return {static = known(m), fx = known(fx)}
end

-- the button's label: its text, or (once the icon hid the text) the end of its object's name
local function labelOf(maps, text, name)
  local isFx = name:find(" FX$") ~= nil
  local t = isFx and maps.fx or maps.static
  if text and text ~= "" then return text, t[text], isFx end
  local base, best = isFx and name:sub(1, -4) or name, nil
  for k in pairs(t) do
    if (base:sub(-#k - 1) == " " .. k) and (not best or #k > #best) then best = k end
  end
  return best, best and t[best], isFx
end

-- the images: FireSystem's (a copy of its FireSystemIcons.lua) and the mini icons, put into this
-- file by tools/make_tools.py as ICON_DATA (base64 by file name), read into this tool's copy of
-- the modules so their image import can write the PNGs out
--@ICONDATA@
local function loadIconPack(E)
  if E.FireSystemIconData then return true end
  if type(ICON_DATA) ~= "function" then return false end
  local ok, D = pcall(ICON_DATA)
  if ok and type(D) == "table" then E.FireSystemIconData = D return true end
  return false
end

-- someone else's appearance in that slot (then it's left alone)
local function foreign(E, no)
  local h = E.obj("Appearance " .. no)
  if not h then return false end
  local name = tostring(E.objName(h) or "")
  return name ~= "" and name:sub(1, #E.CFG.PREFIX + 1) ~= E.CFG.PREFIX .. " "
end

-- FireSystem look: the disc for state k ("idle" / "on"), or nil
local function discAp(E, k, icon, text)
  local si = E.ROUND_STATE[k]
  local num = NUMBERS[text]
  if num then
    local ni = E.ICN.NUM[num .. "|orange"]
    if not ni then return nil end
    local slot = ni > 80 and (E.CFG.NUM2_AP_BASE + (ni - 81) * 3 + si) or (E.CFG.NUM_AP_BASE + (ni - 1) * 3 + si)
    if foreign(E, slot) then return nil end
    return E.ICN.numAp(k, num, "orange")
  end
  local ii = E.ICON_IDX[icon]
  if not ii or foreign(E, E.CFG.ROUND_AP_BASE + (ii - 1) * 3 + si) then return nil end
  return E.FN.roundIconAp(k, icon)
end

-- the colour of an object's appearance ({r, g, b}), or nil
local function colourOf(E, addr)
  local rgb
  pcall(function()
    local ap = E.obj(addr).Appearance
    if ap then
      local r, g, b = tonumber(ap.BackR), tonumber(ap.BackG), tonumber(ap.BackB)
      if r and g and b then rgb = {r, g, b} end
    end
  end)
  return rgb
end

-- Keep look: an appearance with this colour and the square icon, or nil
local function keepAp(E, made, icon, rgb, img)
  if not rgb then return nil end
  local key = string.format("%s %d.%d.%d", icon, rgb[1], rgb[2], rgb[3])
  if made[key] ~= nil then return made[key] or nil end
  if not E.importImage(img, "fs_" .. icon .. ".png") then made[key] = false return nil end
  local want = E.fs(TAG .. " " .. key)
  local no
  local l = ObjectList('Appearance "' .. want .. '"')
  if l and l[1] then pcall(function() no = tonumber(l[1].no) end) end
  if not no then
    no = KEEP_AP_FROM
    while E.obj("Appearance " .. no) and no < 9999 do no = no + 1 end
  end
  E.imageAp(no, want, rgb, img)
  made[key] = no
  return no
end

-- the mini icon for a button of tool tag (its place in MINI), or nil: the longest name ending wins
local function miniFor(tag, name)
  local best, len
  for i, m in ipairs(MINI) do
    if tag and (" " .. m[4] .. " "):find(" " .. tag .. " ", 1, true) then
      for _, ending in ipairs(m[5]) do
        if name:sub(-#ending) == ending and (not len or #ending > len) then best, len = i, #ending end
      end
    end
  end
  return best
end

-- FireSystem look, mini icon i: its disc for state k, or nil
local function miniAp(E, made, k, i)
  local si = E.ROUND_STATE[k]
  local key = "mi " .. i .. " " .. si
  if made[key] ~= nil then return made[key] or nil end
  local slot, ap = MINI_AP_BASE + (i - 1) * 3 + si, false
  if not foreign(E, slot) then
    local img = MINI_IMAGE_BASE + (i - 1) * 3 + si
    if E.importImage(img, string.format("fs_r_mi_%s_%s.png", MINI[i][1], E.ROUND_SUFFIX[si])) then
      ap = E.makeImageAp(slot, "r mi_" .. MINI[i][1] .. " " .. k, img) or false
    end
  end
  made[key] = ap
  return ap or nil
end

-- the tools' layouts: {{no, handle}, ...}
local function toolLayouts(E)
  local found, seen = {}, {}
  local function add(h)
    local no, name
    pcall(function() no = tonumber(h.no) or tonumber(h.No) end)
    pcall(function() name = tostring(E.objName(h) or "") end)
    local tag = name and name:match("^" .. E.CFG.PREFIX .. " (%u%u) ")
    if no and tag and TOOL_TAGS[tag] and not seen[no] then seen[no] = true found[#found + 1] = {no, h} end
  end
  pcall(function() for _, h in ipairs(DataPool().Layouts:Children()) do add(h) end end)
  local ok, list = pcall(ObjectList, 'Layout "' .. E.CFG.PREFIX .. ' "*')
  for _, h in ipairs(ok and type(list) == "table" and list or {}) do add(h) end
  table.sort(found, function(a, b) return a[1] < b[1] end)
  return found
end

-- one button: returns true when it got its icon
local function iconButton(E, maps, made, keep, e)
  local o, text
  pcall(function() o = e.Object end)
  pcall(function() text = e.CustomTextText end)
  if not o then return nil end
  local kind, no, name
  pcall(function() kind = tostring(o:GetClass()) end)
  pcall(function() no = tonumber(o.no) or tonumber(o.No) end)
  pcall(function() name = tostring(E.objName(o) or "") end)
  if not (kind == "Sequence" or kind == "Macro") or not no or not name then return nil end
  if name:sub(1, #E.CFG.PREFIX + 1) ~= E.CFG.PREFIX .. " " then return nil end
  -- the mini tools' own icon (by the object's name), else FireSystem's (by the button's text)
  local mi = miniFor(name:match("^" .. E.CFG.PREFIX .. " (%u%u) "), name)
  local top = mi and MINI[mi][2] == "top"
  local label, disc, square
  if mi then
    local icon = "mi_" .. MINI[mi][1]
    disc = function(k) return miniAp(E, made, k, mi) end
    square = function(rgb) return keepAp(E, made, icon, rgb, MINI_SQUARE_BASE + mi - 1) end
  else
    local icon
    label, icon = labelOf(maps, text and tostring(text) or "", name)
    if not icon then return nil end
    disc = function(k) return discAp(E, k, icon, label) end
    square = function(rgb) return keepAp(E, made, icon, rgb, E.CFG.ICON_IMAGE_BASE + E.ICON_IDX[icon] - 1) end
  end
  local addr = kind .. " " .. no
  local done = false
  if kind == "Sequence" then
    -- FireSystem look: both discs or neither (a button half dark disc, half old look is no use)
    local idle, lit
    if not keep then
      idle, lit = disc("idle"), disc("on")
      if not (idle and lit) then return false end
    end
    local off = keep and square(colourOf(E, addr)) or idle
    if off then E.C("Assign Appearance %d At %s", off, addr) done = true end
    for k = 1, 99 do
      local cue = string.format("%s Cue %d", addr, k)
      if not E.obj(cue) then break end
      -- (a picker's "Off" cue looks off)
      local isOff = false
      pcall(function() isOff = tostring(E.objName(E.obj(cue)) or "") == "Off" end)
      local on = keep and square(colourOf(E, cue)) or (isOff and idle or lit)
      if on then
        E.C("Assign Appearance %d At %s", on, cue)
        E.Cany({ string.format("Assign Appearance %d At %s Part 0", on, cue) })
        done = true
      end
    end
  else
    -- macros: the ALL row's lit; Off and the value buttons (inputs, resets) dark
    local k = (label == "Off" or top) and "idle" or "on"
    local ap = keep and square(colourOf(E, addr)) or (not keep and disc(k))
    if ap then E.C("Assign Appearance %d At %s", ap, addr) done = true end
  end
  if done and top then
    pcall(function() e.CustomTextAlignmentV = "Bottom" end)   -- (the icon is at the top)
  elseif done and not keep then
    pcall(function() e.CustomTextText = "" end)
  end
  return done
end

local function applyIcons(E, keep)
  E.failures = {}
  local pack = loadIconPack(E)
  local maps, made = iconMaps(E), {}
  local layouts = toolLayouts(E)
  if #layouts == 0 then
    return {"No FS tool layouts in the show yet. Build FS Dimmer FX, FS Colour FX, FS Position Picker, FS Bumps ... first, then run " .. TITLE .. " again."}
  end
  local n, missed, used = 0, 0, 0
  for _, l in ipairs(layouts) do
    local count, any = 0, false
    pcall(function() count = l[2]:Count() end)
    for i = 1, count do
      local e
      pcall(function() e = l[2][i] end)
      local r = e and iconButton(E, maps, made, keep, e)
      if r then n = n + 1 any = true elseif r == false then missed = missed + 1 end
    end
    if any then used = used + 1 end
  end
  svar("keep", keep and "1" or "0")
  local lines = {}
  if n == 0 and missed > 0 then
    lines[1] = "No icon images could be imported" .. (pack and "" or " (this copy of " .. TITLE .. " has no images in it)") ..
      ". MA writes them to the show's media/images folder first: check that folder can be written, then run " .. TITLE .. " again."
    return lines
  end
  lines[1] = string.format("%d buttons on %d layout%s got FireSystem icons%s.", n, used, used == 1 and "" or "s",
    keep and string.format(" in their own colours (Appearances %d+)", KEEP_AP_FROM) or "")
  if missed > 0 then lines[#lines + 1] = string.format("%d buttons kept their text (no image, or an appearance slot that isn't FireSystem's).", missed) end
  lines[#lines + 1] = "To go back to plain buttons, build that tool again."
  return lines
end

local function main(displayHandle, argument)
  if not env then
    local ok, E = pcall(build)
    if not ok then return say(tostring(E)) end
    env = E
  end
  local E = env
  local r = MessageBox({
    title = TITLE,
    message = "Gives the FS tools' buttons FireSystem's icons (forms, levels, pans, tilts, position FX, Off,\n" ..
              "Rnd, Strobe, Iris, Zoom, Gobo, Prism ...): round discs, dark when off and lit when on, without text.\n" ..
              "Fade, Delay, Wings, Steps, Part ... get a small icon on top and keep their text (the value).\n" ..
              KEEP .. ": the buttons keep their colours and text and get the icon on top.",
    commands = {{value = 1, name = "Apply"}, {value = 0, name = "Cancel"}},
    states = {{name = KEEP, state = gvar("keep") == "1"}},
  })
  if not r or r.result ~= 1 then return end
  local keep = r.states and r.states[KEEP] == true
  local ok, lines = pcall(applyIcons, E, keep)
  if not ok then return say("Stopped: " .. tostring(lines)) end
  if #E.failures > 0 then
    lines[#lines + 1] = string.format("\n%d commands failed, first: %s", #E.failures, E.failures[1])
    for _, f in ipairs(E.failures) do Printf(TITLE .. ": " .. f) end
  end
  say(table.concat(lines, "\n"))
end

return main
