--[[
  FSMasters.lua  -  "FS Masters": FireSystem's executor page 1, nothing else
  ------------------------------------------------------------------------
  One of the single-purpose FireSystem tools. Run it (click it in the Plugins pool) and it asks for
  the groups (up to 8) and the page, then fills that page the way FireSystem's page 1 is laid out
  (columns 1-8 = the groups):

    401-408  Rnd strobe keys     (FS Bumps "Rnd", Flash)
    301-308  Strobe keys         (FS Bumps "Strobe", Flash)
    201-208  Group masters       (the group itself on the fader, at 100 % when newly assigned)
    101-108  Bump keys           (FS Bumps "Bump", Temp)
    191-198  X-keys              (FS LOS bank 1's 8 bumps, Temp; bank 2 on the next page's
                                  X-keys, and so on)
    110      Strobe All          (FS Bumps "ALL Strobe", Temp)
    210 / 209 / 409 / 410 / 211  Speed masters 1-5 (DimFX, PosFX, ColorFX, Bump speed, Bump rate)
    next page 209 / 210          Playback masters 1 / 2 (DimFX level, Bump level)

  The keys are FS Bumps' and FS LOS's own sequences, found by name ("FS BS <group name> Bump",
  "FS LO LOS1 All >" ...), so run those first; this tool only places them. The masters get FireSystem's names. An executor that
  holds something that isn't FireSystem's ("FS ..." or one of the groups) is left alone and listed.
  The show doesn't need the plugin afterwards.

  ONE FILE, NO OTHER PLUGIN NEEDED: plugins/FSMasters.lua is generated by tools/make_tools.py from
  this source, the shared tool code in src/lib/ and a copy of the FireSystem module files.
--]]

local TITLE = "FS Masters"
local TAG = "MS"       -- (this tool names nothing of its own; kept for the shared code)
local VARP = "FSMS_"   -- this tool's global variables

--@INCLUDE common@
--@INCLUDE picker@

-- FS Bumps' keys: {its key name, executor base, executor key}
local ROWS = {
  {"Rnd", 400, "Flash"},
  {"Strobe", 300, "Flash"},
  {"Bump", 100, "Temp"},
}
-- FS LOS's bumps per bank, on the X-keys (bank b on page + b - 1)
local LOS = {"All >", "All <", "Odd", "Even", "1/3", "2/3", "3/3", "Chase"}
local LOS_BASE, LOS_BANKS = 190, 4
local STROBE_ALL = {"ALL Strobe", 110, "Temp"}
local GROUP_BASE = 200
-- {executor, kind, number, page offset}: as FireSystem's CFG.MASTER_EXECS
local MASTERS = {
  {210, "Speed", 1, 0}, {209, "Speed", 2, 0}, {409, "Speed", 3, 0}, {410, "Speed", 4, 0}, {211, "Speed", 5, 0},
  {209, "Playback", 1, 1}, {210, "Playback", 2, 1},
}

-- the executor's handle (ObjectList("Page 1.101") finds nothing: look it up under its page)
local function execHandle(pg, ex)
  local h
  pcall(function()
    local page = DataPool().Pages[pg]
    if not page then return end
    for _, c in ipairs(page:Children()) do
      if tonumber(c.No) == ex or tonumber(c.no) == ex then h = c return end
    end
  end)
  return h
end

-- what the executor holds: nil (empty), or {class, no, name}
local function holds(pg, ex)
  local h, r = execHandle(pg, ex), nil
  if h then
    pcall(function()
      local o = h.Object
      if o then r = {tostring(o:GetClass()), tonumber(o.No), tostring(o.Name)} end
    end)
  end
  return r
end

local function buildMasters(E, groups, pg)
  E.failures = {}
  local names = {}
  for gi, g in ipairs(groups) do names[gi] = tostring(E.objName(E.obj("Group " .. g)) or ("G" .. gi)) end
  local isGroup = {}
  for _, g in ipairs(groups) do isGroup[g] = true end
  local skipped, missing, placed = {}, {}, 0
  for _, p in ipairs({pg, pg + 1}) do if not E.obj("Page " .. p) then E.C("Store Page %d", p) end end

  -- an executor we may fill: empty, already FireSystem's, or one of the groups
  local function free(p, ex, wantClass, wantNo)
    local o = holds(p, ex)
    if not o then return true end
    if o[1] == wantClass and o[2] == wantNo then return true end
    if o[3]:sub(1, #E.CFG.PREFIX + 1) == E.CFG.PREFIX .. " " or (o[1] == "Group" and isGroup[o[2]]) then
      E.C("Delete Page %d.%d /NC", p, ex)
      return true
    end
    skipped[#skipped + 1] = string.format("Page %d.%d (%s %s '%s')", p, ex, o[1], tostring(o[2]), o[3])
    return false
  end
  local function setKey(p, ex, key)
    local h, ok = execHandle(p, ex), false
    if h then pcall(function() h.Key = key ok = tostring(h.Key) == key end) end
    if not ok then E.C('Set Page %d.%d Property "Key" "%s"', p, ex, key) end
  end
  local function seqNamed(name)
    local h, no = E.obj(string.format('Sequence "%s"', name)), nil
    if h then pcall(function() no = tonumber(h.no) end) end
    if h and not no then pcall(function() no = tonumber(h.No) end) end
    return no
  end
  local function put(no, p, ex, k)
    if not free(p, ex, "Sequence", no) then return end
    E.C("Assign Sequence %d At Page %d.%d", no, p, ex)
    setKey(p, ex, k)
    placed = placed + 1
  end
  local function key(label, ex, k)
    local no = seqNamed(E.CFG.PREFIX .. " BS " .. label)
    if not no then missing[#missing + 1] = label return end
    put(no, pg, ex, k)
  end

  for gi, g in ipairs(groups) do
    for _, r in ipairs(ROWS) do key(names[gi] .. " " .. r[1], r[2] + gi, r[3]) end
    -- group master: the group itself; the fader goes to 100 % only when newly assigned
    local ex = GROUP_BASE + gi
    local was = holds(pg, ex)
    if free(pg, ex, "Group", g) then
      if not (was and was[1] == "Group" and was[2] == g) then
        E.C("Assign Group %d At Page %d.%d", g, pg, ex)
        E.Cany({ string.format("Fader Page %d.%d At 100", pg, ex), string.format("Page %d.%d At 100", pg, ex) })
      end
      placed = placed + 1
    end
  end
  key(STROBE_ALL[1], STROBE_ALL[2], STROBE_ALL[3])

  -- the X-keys: FS LOS's bumps, a bank per page
  local banks = 0
  for b = 1, LOS_BANKS do
    local nos = {}
    for i, name in ipairs(LOS) do nos[i] = seqNamed(string.format("%s LO LOS%d %s", E.CFG.PREFIX, b, name)) end
    if not nos[1] then break end
    banks = b
    local p = pg + b - 1
    if not E.obj("Page " .. p) then E.C("Store Page %d", p) end
    for i = 1, #LOS do if nos[i] then put(nos[i], p, LOS_BASE + i, "Temp") end end
  end

  -- the masters, with FireSystem's names
  for _, m in ipairs(MASTERS) do
    local p, ex = pg + m[4], m[1]
    local o = holds(p, ex)
    if o then
      skipped[#skipped + 1] = string.format("Page %d.%d (%s %s '%s')", p, ex, o[1], tostring(o[2]), o[3])
    else
      E.Cany({ string.format('Assign Master "%s".%d At Page %d.%d', m[2], m[3], p, ex),
               string.format("Assign Master %s.%d At Page %d.%d", m[2], m[3], p, ex),
               string.format("Assign %sMaster %d At Page %d.%d", m[2], m[3], p, ex) })
      placed = placed + 1
    end
  end
  for mk, list in pairs(E.CFG.MASTER_NAMES) do
    for n, name in ipairs(list) do
      local ok = pcall(function() ShowData().Masters[mk][n].name = name end)
      pcall(function() ok = ShowData().Masters[mk][n].name == name end)
      if not ok then
        E.Cany({ string.format('Label Master "%s".%d %s', mk, n, E.q(name)),
                 string.format("Label Master %s.%d %s", mk, n, E.q(name)) })
      end
    end
  end

  svar("groups", E.rangeList({table.unpack(groups)})) svar("page", pg)
  local lines = {string.format("Page %d: %d executors for %d groups (playback masters on page %d).", pg, placed, #groups, pg + 1)}
  if banks > 0 then
    lines[#lines + 1] = string.format("X-keys: FS LOS bank%s 1%s on page%s %d%s.", banks > 1 and "s" or "",
      banks > 1 and ("-" .. banks) or "", banks > 1 and "s" or "", pg, banks > 1 and ("-" .. (pg + banks - 1)) or "")
  else
    lines[#lines + 1] = "\nNo FS LOS bumps in the show yet: run FS LOS, then run " .. TITLE .. " again to put them on the X-keys."
  end
  if #missing > 0 then
    lines[#lines + 1] = string.format("\n%d FS Bumps keys aren't in the show yet (first: %s). Run FS Bumps for these groups, then run %s again.",
      #missing, missing[1], TITLE)
  end
  if #skipped > 0 then
    lines[#lines + 1] = "\nIn use by something else (left as it is):"
    for i = 1, math.min(#skipped, 8) do lines[#lines + 1] = "  " .. skipped[i] end
  end
  return lines
end

local function main(displayHandle, argument)
  if not env then
    local ok, E = pcall(build)
    if not ok then return say(tostring(E)) end
    env = E
  end
  local E = env
  local r = MessageBox({
    title = TITLE,
    message = "Groups for columns 1-8 (up to 8), e.g. 1 Thru 8, and the executor page to fill (FireSystem uses page 1;\n" ..
              "the playback masters go on the page after it). The keys are FS Bumps' sequences and the X-keys FS LOS's bumps:\n" ..
              "run those first.",
    commands = {{value = 1, name = "Build"}, {value = 0, name = "Cancel"}},
    inputs = {
      {name = "Groups", value = defaultGroups(E, VARP .. "groups"), whiteFilter = "0123456789 ,+-ThruTHRU"},
      {name = "Page", value = tostring(gvar("page") or "1"), whiteFilter = "0123456789"},
    },
  })
  if not r or r.result ~= 1 then return end
  local i = r.inputs or {}
  local groups, pg = parseGroups(i["Groups"]), tonumber(i["Page"] or "")
  local good = {}
  for _, g in ipairs(groups) do if E.obj("Group " .. g) then good[#good + 1] = g end end
  if #good == 0 then return say("None of those groups exist yet. Store your groups first, then run " .. TITLE .. " again.") end
  if #good > 8 then return say("Pick up to 8 groups.") end
  if not pg or pg < 1 then return say("Fill in the page number.") end
  local ok, lines = pcall(buildMasters, E, good, pg)
  if not ok then return say("Stopped: " .. tostring(lines)) end
  if #good < #groups then lines[#lines + 1] = "Skipped groups that don't exist." end
  if #E.failures > 0 then
    lines[#lines + 1] = string.format("\n%d commands failed, first: %s", #E.failures, E.failures[1])
    for _, f in ipairs(E.failures) do Printf(TITLE .. ": " .. f) end
  end
  say(table.concat(lines, "\n"))
end

return main
