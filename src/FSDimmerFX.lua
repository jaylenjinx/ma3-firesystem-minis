--[[
  FSDimmerFX.lua  -  "FS Dimmer FX": builds a dimmer FX picker layout, nothing else
  ------------------------------------------------------------------------
  One of the single-purpose FireSystem tools. Run it (click it in the Plugins pool) and it asks for
  the groups and the pool numbers, then builds a layout with an ALL row and one row per group:

    [group] [0% / 50% / 100%] [Sine 1 3 4] [Square 1 3 4] [Ramp Up 1 3 4] [Ramp Down 1 3 4] [6 MAtricks]

  Built the same way as FS Position Picker: every group button is a sequence with a recipe cue
  (Group At the FS Presets preset), Prefer Cue Appearance and a Toggle action. Every button of a row
  sets the dimmer, so its cue switches the rest of the row off (one look per group). The FX are
  linked to a speed master (Speed 1 by default, as in FireSystem). Each group row has its own
  MAtricks pool object that all its recipe lines point at; the MAtricks buttons (Wings, Groups,
  Blocks, Phase, Fade, Delay) are cycling sequences whose cues set it, and the ALL row's MAtricks
  buttons step every row to the same value. ALL buttons are macros that start the same button on
  every row. The show doesn't need the plugin afterwards.

  The presets are FS Presets' own (Dimmer 1.x for the levels, Dimmer FX in the All pool), made
  here if they're missing, so FS Presets and the pickers can be run in any order.

  ONE FILE, NO OTHER PLUGIN NEEDED: plugins/FSDimmerFX.lua is generated by tools/make_tools.py
  from this source, the shared tool code in src/lib/ and a copy of the FireSystem
  module files. Edit those, then run `python3 tools/make_tools.py`.
--]]

local TITLE = "FS Dimmer FX"
local TAG = "DF"       -- names: "FS DF ..." (what a rebuild may replace)
local VARP = "FSDF_"   -- this tool's global variables

--@INCLUDE common@
--@INCLUDE presets@
--@INCLUDE picker@

local LEVELS = {"0%", "50%", "100%"}   -- FS Presets' Dimmer pool labels
local AP_N = 6                         -- appearances: level off / on, FX off / on, MAtricks idle / lit
local MXL = mxList("Wings", "Groups", "Blocks", "Phase", "Fade", "Delay", "Speed")

-- the buttons: FS Presets' plan gives the preset numbers (made here when missing)
local function dimmerPresets(E)
  local made, foreign, _, recs = buildPresets(E, E.CFG.GROUPS, {dim = true}, false)
  local bad = {}
  for _, f in ipairs(foreign) do bad[f:match("^(Preset %d+%.%d+)")] = true end
  local at = {}  -- "pool:label" -> preset address
  for _, r in ipairs(recs) do
    if not bad[string.format("Preset %d.%d", r.pool, r.no)] then at[r.pool .. ":" .. r.label] = r.pool .. "." .. r.no end
  end
  local levels, fx = {}, {}
  for _, l in ipairs(LEVELS) do
    if at["1:" .. l] then levels[#levels + 1] = {name = l, at = at["1:" .. l]} end
  end
  -- the FX in the main plugin's page order (sine, square, ramp up, ramp down), without the
  -- bulbs (Full / Half: the levels above) and the fan (it needs its own frozen MAtricks)
  for _, i in ipairs(E.DIM_FORMS.order) do
    local f = E.DIM_FORMS[i]
    if f[3] ~= "full" and f[3] ~= "half" and f[3] ~= "fan" and at["21:" .. f[2]] then
      fx[#fx + 1] = {name = f[2], at = at["21:" .. f[2]], form = f[3]}
    end
  end
  return levels, fx, made, foreign
end

local NMX = #MXL  -- MAtricks buttons per row

local function ask(E, nBtn)
  local groups = defaultGroups(E, VARP .. "groups")
  local rows = #parseGroups(groups)
  local function def(k, kind, n, from)
    local v = tonumber(gvar(k) or "")
    return tostring(v or freeBlock(E, kind, n, from))
  end
  local r = MessageBox({
    title = TITLE,
    message = "Groups for the picker rows (up to 20), e.g. 1 Thru 8 or 1,2,5. An ALL row goes on top.\n" ..
              "The numbers below are where the layout, its button sequences, macros, appearances and MAtricks go\n" ..
              string.format("(%d sequences per group row + %d for ALL, %d macros, %d appearances, one MAtricks per group row).\n",
                            nBtn + NMX, NMX, nBtn, AP_N) ..
              "Speed master: the one the FX follow (0 = none).",
    commands = {{value = 1, name = "Build"}, {value = 0, name = "Cancel"}},
    states = {{name = ICON_BOX, state = gvar("icons") == "1"}},
    inputs = {
      {name = "Groups", value = groups, whiteFilter = "0123456789 ,+-ThruTHRU"},
      {name = "Layout", value = def("layout", "Layout", 1, 1), whiteFilter = "0123456789"},
      {name = "First sequence", value = def("seq", "Sequence", rows * (nBtn + NMX) + NMX, 101), whiteFilter = "0123456789"},
      {name = "First macro", value = def("macro", "Macro", nBtn, 101), whiteFilter = "0123456789"},
      {name = "First appearance", value = def("ap", "Appearance", AP_N, 101), whiteFilter = "0123456789"},
      {name = "First MAtricks", value = def("mtx", "MAtricks", rows, 1), whiteFilter = "0123456789"},
      {name = "Speed master", value = tostring(tonumber(gvar("speed") or "") or 1), whiteFilter = "0123456789"},
    },
  })
  if not r or r.result ~= 1 then return nil end
  local i = r.inputs or {}
  local function n(k) return tonumber(i[k] or "") end
  return parseGroups(i["Groups"]), {icons = (r.states or {})[ICON_BOX] and true or false, L = n("Layout"), seq0 = n("First sequence"), M0 = n("First macro"),
    ap0 = n("First appearance"), mx0 = n("First MAtricks"), speed = n("Speed master") or 0}
end

local function buildPicker(E, groups, o)
  local L, seq0, M0, ap0, mx0 = o.L, o.seq0, o.M0, o.ap0, o.mx0
  E.failures = {}
  E.CFG.GROUPS = groups
  local levels, fx, madeP, foreign = dimmerPresets(E)
  -- the columns: {kind, item, col}
  local cols, c = {}, 1
  for _, l in ipairs(levels) do cols[#cols + 1] = {kind = "lvl", item = l, col = c} c = c + 1 end
  local lastForm
  for _, f in ipairs(fx) do
    if f.form ~= lastForm then c = c + 0.25 lastForm = f.form end  -- a small gap between the forms
    cols[#cols + 1] = {kind = "fx", item = f, col = c} c = c + 1
  end
  local mxCol = c + 0.25
  local nB = #cols
  local names = {}
  for gi, g in ipairs(groups) do names[gi] = tostring(E.objName(E.obj("Group " .. g)) or ("Group " .. g)) end
  -- refuse to overwrite anything that isn't ours
  local clash = {}
  if not mine(E, "Layout", L) then clash[#clash + 1] = "Layout " .. L end
  local nSeq = #groups * nB + (#groups + 1) * NMX
  for k = seq0, seq0 + nSeq - 1 do if not mine(E, "Sequence", k) then clash[#clash + 1] = "Sequence " .. k end end
  for k = M0, M0 + nB - 1 do if not mine(E, "Macro", k) then clash[#clash + 1] = "Macro " .. k end end
  for k = ap0, ap0 + AP_N - 1 do if not mine(E, "Appearance", k) then clash[#clash + 1] = "Appearance " .. k end end
  for k = mx0, mx0 + #groups - 1 do if not mine(E, "MAtricks", k) then clash[#clash + 1] = "MAtricks " .. k end end
  if #clash > 0 then
    return nil, "These are already used by something else:\n  " .. table.concat(clash, "\n  ", 1, math.min(#clash, 10)) ..
      (#clash > 10 and "\n  ..." or "") .. "\n\nPick other numbers and run it again."
  end
  local P = E.CFG.PREFIX .. " " .. TAG .. " "
  local AP = {lvlOff = ap0, lvlOn = ap0 + 1, fxOff = ap0 + 2, fxOn = ap0 + 3, idle = ap0 + 4, lit = ap0 + 5}
  appearance(E, AP.lvlOff, P .. "level off", {64, 56, 32})
  appearance(E, AP.lvlOn, P .. "level on", {255, 210, 90})
  appearance(E, AP.fxOff, P .. "FX off", {64, 40, 24})
  appearance(E, AP.fxOn, P .. "FX on", {255, 140, 40})
  appearance(E, AP.idle, P .. "MAtricks idle", {60, 60, 60})
  appearance(E, AP.lit, P .. "MAtricks lit", {220, 220, 220})
  -- the layout: emptied and refilled on a rebuild
  if not E.obj("Layout " .. L) then E.C("Store Layout %d", L) end
  pcall(function() local lh = E.obj("Layout " .. L) for i = lh:Count(), 1, -1 do lh:Delete(i) end end)
  E.C("Label Layout %d %s", L, E.q(P .. "Dimmer FX"))
  for gi = 1, #groups do makeMatricks(E, mx0 + gi - 1, P .. names[gi]) end
  local seq, bySeq, rowFx = seq0, {}, {}
  for gi, g in ipairs(groups) do
    local rowSeq0 = seq
    local mtx = mx0 + gi - 1
    place(E, L, "Group " .. g, 0, gi, names[gi])  -- the group itself, with its name: tap to select it
    for bi, b in ipairs(cols) do
      -- every button sets the dimmer: its cue switches the rest of the row off
      local others = {}
      for k = rowSeq0, rowSeq0 + nB - 1 do if k ~= seq then others[#others + 1] = k end end
      local off = #others > 0 and ("Off Sequence " .. E.rangeList(others)) or ""
      local lvl = b.kind == "lvl"
      buttonSeq(E, seq, P .. names[gi] .. " " .. b.item.name, g, lvl and AP.lvlOff or AP.fxOff,
                {{b.item.at, lvl and AP.lvlOn or AP.fxOn, off}}, mtx)
      if not lvl and o.speed > 0 then E.trySeqMaster(seq, "SpeedMaster", "Speed", o.speed) end
      if not lvl then rowFx[gi] = rowFx[gi] or {} table.insert(rowFx[gi], {seq, 1}) end
      place(E, L, "Sequence " .. seq, b.col, gi, b.item.name, true)
      bySeq[bi] = bySeq[bi] or {}
      table.insert(bySeq[bi], seq)
      seq = seq + 1
    end
  end
  -- the ALL row on top: macros that start each group row's button in that column
  local M = M0
  for bi, b in ipairs(cols) do
    local l = {}
    for _, sq in ipairs(bySeq[bi] or {}) do l[#l + 1] = "Goto Sequence " .. sq .. " Cue 1" end
    macro(E, M, P .. "ALL " .. b.item.name, l, b.kind == "lvl" and AP.lvlOn or AP.fxOn)
    place(E, L, "Macro " .. M, b.col, 0, b.item.name)
    M = M + 1
  end
  -- the MAtricks buttons (lib picker) at the end of each row
  seq = mxButtons(E, {L = L, n = #groups, names = names, mx0 = mx0, seq0 = seq, col = mxCol,
                      row = function(r) return r end, P = P, AP = AP, list = MXL,
                      rate = function(r) return rowFx[r] or {} end})
  E.C("ClearAll")
  svar("mtx", mx0) svar("speed", o.speed)
  svar("groups", E.rangeList({table.unpack(groups)})) svar("layout", L) svar("seq", seq0) svar("macro", M0) svar("ap", ap0)
  local lines = {string.format("Layout %d: ALL + %d group rows x (%d levels, %d FX) + MAtricks " ..
    "(Sequences %d-%d, Macros %d-%d, Appearances %d-%d, MAtricks %d-%d).", L, #groups, #levels, #fx,
    seq0, seq - 1, M0, M - 1, ap0, ap0 + AP_N - 1, mx0, mx0 + #groups - 1)}
  if o.speed > 0 then lines[#lines + 1] = string.format("The FX follow Speed master %d.", o.speed) end
  if madeP > 0 then lines[#lines + 1] = string.format("%d missing dimmer presets were made.", madeP) end
  if #foreign > 0 then
    lines[#lines + 1] = "\nSkipped buttons whose preset slot holds something else:"
    for i = 1, math.min(#foreign, 8) do lines[#lines + 1] = "  " .. foreign[i] end
  end
  return lines
end

local function main(displayHandle, argument)
  if not env then
    local ok, E = pcall(build)
    if not ok then return say(tostring(E)) end
    env = E
  end
  local E = env
  -- (3 levels + 12 FX: the count for the dialog; the build counts what it really finds)
  local groups, o = ask(E, 15)
  if not groups then return end
  local good = {}
  for _, g in ipairs(groups) do if E.obj("Group " .. g) then good[#good + 1] = g end end
  if #good == 0 then return say("None of those groups exist yet. Store your groups first, then run " .. TITLE .. " again.") end
  if #good > MAX_GROUPS then return say("Pick up to " .. MAX_GROUPS .. " groups.") end
  if not (o.L and o.seq0 and o.M0 and o.ap0 and o.mx0) then
    return say("Fill in the layout, first sequence, macro, appearance and MAtricks numbers.")
  end
  iconsStart(E, o.icons)
  local ok, lines, err = pcall(buildPicker, E, good, o)
  local iconNote = iconsFinish(E, ok and lines ~= nil)
  if iconNote and type(lines) == "table" then lines[#lines + 1] = iconNote end
  pcall(Cmd, "ClearAll")
  if not ok then return say("Stopped: " .. tostring(lines)) end
  if not lines then return say(err) end
  if #good < #groups then lines[#lines + 1] = "Skipped groups that don't exist." end
  if #E.failures > 0 then
    lines[#lines + 1] = string.format("\n%d commands failed, first: %s", #E.failures, E.failures[1])
    for _, f in ipairs(E.failures) do Printf(TITLE .. ": " .. f) end
  end
  say(table.concat(lines, "\n"))
  pcall(Cmd, "Select Layout " .. o.L)
end

return main
