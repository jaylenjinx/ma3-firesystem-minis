--[[
  FSLOS.lua  -  "FS LOS": Live Output System bumps, built the way MA's StartShow LOS works
  ------------------------------------------------------------------------
  One of the single-purpose FireSystem tools. Run it (click it in the Plugins pool) and it asks for
  the groups (up to 20), how many LOS banks (1-4) and the pool numbers, then builds a layout with one
  block per bank:

    [group toggles]                                         [Fade 0 / input]  [Wings 0 / 2]    [Blocks 0]
    [Dim] [Gobo] [Prism] [Iris] [Shutter] [Zoom] [Pos]      [Delay 0 / input] [Off 0 / input]  [Blocks input]
    [Color Off + 15 colours]
    [BUMPS: All >  All <  Odd  Even  1/3  2/3  3/3  Chase]   (sequences: put them on X-keys / executors)

  How it plays, as in MA's StartShow (read from MA_StartShow 2.5.1.1, Lyn 2026-11-17):
  - each bank has ONE All-pool preset ("FS LO LOS b") holding a recipe line per look family and
    group ("Dimmer G1", "Color G1", ...). A look button is a macro that points that family's lines at
    a preset (Assign Preset 4.x At Preset 21.P."Color"*); Off empties them. Gobo / prism / shutter
    choices come from each group's own fixture type (FS Presets' per-type presets);
  - the 8 bump sequences have one recipe line per group ("LOS G1"...) whose values are that LOS
    preset. A group button includes / excludes the group: its macro assigns the group to those lines
    (tap 1) or clears it (tap 2, the macro waits on a Go between the two halves);
  - each bump has its own MAtricks: All > / All < spread the Delay forwards / backwards, Odd / Even
    = X Group 2, 1/3 2/3 3/3 = X Group 3, Chase steps 1/3 > 2/3 > 3/3 (1 s per step). Fade, Wings and Blocks
    set every MAtricks of the bank; Off sets the bumps' OffCue fade (the release time).
  Change a look while a bump plays and the bump changes with it. The show doesn't need the plugin
  afterwards.

  ONE FILE, NO OTHER PLUGIN NEEDED: plugins/FSLOS.lua is generated by tools/make_tools.py from this
  source, the shared tool code in src/lib/ and a copy of the FireSystem module files.
--]]

local TITLE = "FS LOS"
local TAG = "LO"       -- names: "FS LO ..." (what a rebuild may replace)
local VARP = "FSLO_"   -- this tool's global variables

--@INCLUDE common@
--@INCLUDE presets@
--@INCLUDE picker@

local NB_MAX = 4
-- the bumps: {button text, MAtricks key per cue}; Chase has 3 cues
local BUMPS = { {"All >", {"A"}}, {"All <", {"B"}}, {"Odd", {"O"}}, {"Even", {"E"}},
                {"1/3", {"T1"}}, {"2/3", {"T2"}}, {"3/3", {"T3"}}, {"Chase", {"T1", "T2", "T3"}} }
local MXK = {"A", "B", "O", "E", "T1", "T2", "T3"}   -- MAtricks per bank
local MXN = {A = "All >", B = "All <", O = "Odd", E = "Even", T1 = "1 of 3", T2 = "2 of 3", T3 = "3 of 3"}
local MXSET = {O = {{"XGroup", "2"}, {"X", "1"}}, E = {{"XGroup", "2"}, {"X", "2"}},
               T1 = {{"XGroup", "3"}, {"X", "1"}}, T2 = {{"XGroup", "3"}, {"X", "2"}}, T3 = {{"XGroup", "3"}, {"X", "3"}}}
-- the look families: {line name, button text, kind, wheel}. "list" = the same presets for every
-- group (FS Presets' Dimmer 0-100 %, Iris, Zoom, Position pools), "typed" = each group's own
-- fixture-type presets of that wheel (by slot name), "colours" = the colour buttons. Every family
-- but Color is one Goto list button (Lyn 2026-11-17: room for every option)
local FAMS = {
  {"Dimmer",   "Dim",     "list"},
  {"Gobo",     "Gobo",    "typed", "gobo1"},
  {"Prism",    "Prism",   "typed", "prism"},
  {"Iris",     "Iris",    "list"},
  {"Shutter",  "Shutter", "typed", "shutter"},
  {"Zoom",     "Zoom",    "list"},
  {"Position", "Pos",     "list"},
  {"Color",    "",        "colours"},
}
local NPICK = #FAMS - 1   -- the Goto lists (all but Color)
local TIMING_COL = 9.25
local BLOCK_ROWS = 4.5

local function perBank(nG, nC) return {seq = #BUMPS + NPICK, mtx = #MXK, macro = nG + 1 + nC + 10} end

local function minePreset(E, no)
  local h = E.obj("Preset 21." .. no)
  if not h then return true end
  return tostring(E.objName(h) or ""):find("^" .. E.CFG.PREFIX .. " " .. TAG .. " ") ~= nil
end

local function ask(E, nC)
  local groups = defaultGroups(E, VARP .. "groups")
  local rows = #parseGroups(groups)
  local nb = tonumber(gvar("banks") or "") or 2
  local pb = perBank(rows, nC)
  local function def(k, kind, n, from)
    local v = tonumber(gvar(k) or "")
    return tostring(v or freeBlock(E, kind, n, from))
  end
  local pre = tonumber(gvar("preset") or "")
  if not pre then pre = 901 while pre < 9999 and not (minePreset(E, pre) and minePreset(E, pre + NB_MAX - 1)) do pre = pre + 1 end end
  local r = MessageBox({
    title = TITLE,
    message = "Groups the LOS can include (up to 20), e.g. 1 Thru 8, and how many LOS banks (1-4; each has its own\n" ..
              "8 bumps for X-keys). The numbers below are where the layout, sequences, macros, appearances,\n" ..
              string.format("MAtricks and the LOS presets (All pool) go. Per bank: %d sequences, %d macros, %d MAtricks, 1 preset.\n",
                            pb.seq, pb.macro, pb.mtx) ..
              "Speed / Rate master: the masters the LOS bumps follow (0 = none; FireSystem's bumps use 4 and 5).",
    commands = {{value = 1, name = "Build"}, {value = 0, name = "Cancel"}},
    inputs = {
      {name = "Groups", value = groups, whiteFilter = "0123456789 ,+-ThruTHRU"},
      {name = "LOS banks", value = tostring(nb), whiteFilter = "0123456789"},
      {name = "Layout", value = def("layout", "Layout", 1, 1), whiteFilter = "0123456789"},
      {name = "First sequence", value = def("seq", "Sequence", NB_MAX * pb.seq, 101), whiteFilter = "0123456789"},
      {name = "First macro", value = def("macro", "Macro", NB_MAX * pb.macro, 101), whiteFilter = "0123456789"},
      {name = "First appearance", value = def("ap", "Appearance", 5 + 2 * nC, 101), whiteFilter = "0123456789"},
      {name = "First MAtricks", value = def("mtx", "MAtricks", NB_MAX * pb.mtx, 1), whiteFilter = "0123456789"},
      {name = "First LOS preset (All pool 21)", value = tostring(pre), whiteFilter = "0123456789"},
      {name = "Speed master", value = tostring(tonumber(gvar("speed") or "") or 4), whiteFilter = "0123456789"},
      {name = "Rate master", value = tostring(tonumber(gvar("rate") or "") or 5), whiteFilter = "0123456789"},
    },
  })
  if not r or r.result ~= 1 then return nil end
  local i = r.inputs or {}
  local function n(k) return tonumber(i[k] or "") end
  return parseGroups(i["Groups"]), {nb = math.max(1, math.min(NB_MAX, n("LOS banks") or 2)), L = n("Layout"),
    seq0 = n("First sequence"), M0 = n("First macro"), ap0 = n("First appearance"), mx0 = n("First MAtricks"),
    pre = n("First LOS preset (All pool 21)"), speed = n("Speed master") or 0, rate = n("Rate master") or 0}
end

-- the presets the look lists point at: FS Presets' plan (made here when missing). Returns
-- lists[family] = {{name, at}, ...} (the same presets for every group), slots(wheel) = the slot
-- names any group has on that wheel, slotAt(group, wheel, slot) = that group's preset, and the colours
local function losPresets(E, groups)
  local made, foreign, _, recs = buildPresets(E, groups, {dim = true, pos = true, col = true, zoom = true, gobo = true, beam = true}, false)
  local bad = {}
  for _, f in ipairs(foreign) do bad[f:match("^(Preset %d+%.%d+)")] = true end
  local col4, typed = {}, {}   -- colour name -> "4.no"; group .. ":" .. wheel -> {slot -> at}
  local lists = {Dimmer = {}, Iris = {}, Zoom = {}, Position = {}}
  local order = {}             -- wheel -> slot names in plan order
  for _, r in ipairs(recs) do
    local a = r.pool .. "." .. r.no
    if not bad["Preset " .. a] then
      local into
      if r.pool == 4 then col4[r.label] = a
      elseif r.fam == "dim" and r.pool == 1 and r.label:match("^%d+%%$") then into = "Dimmer"
      elseif r.fam == "pos" and r.pool == 2 then into = "Position"
      elseif r.fam == "zoom" and r.pool == 6 and not r.label:find("^Focus") then into = "Zoom"
      elseif r.wheel == "iris" then into = "Iris" end
      if into then table.insert(lists[into], {name = r.label, at = a}) end
      if r.groups and r.wheel then
        order[r.wheel] = order[r.wheel] or {}
        local seen = false
        for _, x in ipairs(order[r.wheel]) do if x == r.slot then seen = true end end
        if not seen then table.insert(order[r.wheel], r.slot) end
        for _, g in ipairs(r.groups) do
          local k = g .. ":" .. r.wheel
          typed[k] = typed[k] or {}
          typed[k][r.slot] = typed[k][r.slot] or a
        end
      end
    end
  end
  local cols = {}
  for _, c in ipairs(E.CFG.COLORS) do
    if col4[c[1]] then cols[#cols + 1] = {name = c[1], at = col4[c[1]], rgb = c[3]} end
  end
  local function slotAt(g, wheel, slot) return (typed[tostring(g) .. ":" .. wheel] or {})[slot] end
  local function slots(wheel)
    local l = {}
    for _, sl in ipairs(order[wheel] or {}) do
      for _, g in ipairs(groups) do if slotAt(g, wheel, sl) then l[#l + 1] = sl break end end
    end
    return l
  end
  return lists, slots, slotAt, cols, made, foreign
end

-- a typed time in a command: $var on its own (MA doesn't expand a variable glued to other text,
-- so "0$var" broke the times). MA's command line reads ".5" as a stray dot (Lyn 2026-11-22: 0.5
-- works, .5 errors), so the input macro runs losFixDot's Lua line first: .5 -> 0.5, ,5 -> 0.5
local function losNum(var) return "$" .. var end
local function losFixDot(var)
  return string.format("Lua \"local g = GlobalVars() local v = tostring(GetVar(g, '%s') or ''):gsub('^%%s+', ''):gsub(',', '.') " ..
    "if v:sub(1, 1) == '.' then v = '0' .. v end SetVar(g, '%s', v)\"", var, var)
end

local function setWait(E, M, line, wait)
  local ok = pcall(function() E.obj("Macro " .. M)[line]:Set("Wait", wait) end)
  if not ok then E.Cany({ string.format('Set Macro %d.%d Property "Wait" "%s"', M, line, wait) }) end
end

local function buildLOS(E, groups, o)
  local L, seq0, M0, ap0, mx0, pre0, NB = o.L, o.seq0, o.M0, o.ap0, o.mx0, o.pre, o.nb
  E.failures = {}
  E.CFG.GROUPS = groups
  local lists, slots, slotAt, cols, madeP, foreign = losPresets(E, groups)
  local nC, nG = #cols, #groups
  local names = {}
  for gi, g in ipairs(groups) do names[gi] = tostring(E.objName(E.obj("Group " .. g)) or ("Group " .. g)) end
  local pb = perBank(nG, nC)
  local nAp = 5 + 2 * nC
  local clash = {}
  if not mine(E, "Layout", L) then clash[#clash + 1] = "Layout " .. L end
  for k = seq0, seq0 + NB * pb.seq - 1 do if not mine(E, "Sequence", k) then clash[#clash + 1] = "Sequence " .. k end end
  for k = M0, M0 + NB * pb.macro - 1 do if not mine(E, "Macro", k) then clash[#clash + 1] = "Macro " .. k end end
  for k = ap0, ap0 + nAp - 1 do if not mine(E, "Appearance", k) then clash[#clash + 1] = "Appearance " .. k end end
  for k = mx0, mx0 + NB * pb.mtx - 1 do if not mine(E, "MAtricks", k) then clash[#clash + 1] = "MAtricks " .. k end end
  for k = pre0, pre0 + NB - 1 do if not minePreset(E, k) then clash[#clash + 1] = "Preset 21." .. k end end
  if #clash > 0 then
    return nil, "These are already used by something else:\n  " .. table.concat(clash, "\n  ", 1, math.min(#clash, 10)) ..
      (#clash > 10 and "\n  ..." or "") .. "\n\nPick other numbers and run it again."
  end
  local P = E.CFG.PREFIX .. " " .. TAG .. " "
  -- appearances: idle, lit, group off, group on, bump; then each colour dim (idle) / full (picked)
  local AP = {idle = ap0, lit = ap0 + 1, gOff = ap0 + 2, gOn = ap0 + 3, bump = ap0 + 4}
  local function apC(ci, lit) return ap0 + 5 + (lit and nC or 0) + ci - 1 end
  appearance(E, AP.idle, P .. "idle", {50, 50, 50})
  appearance(E, AP.lit, P .. "lit", {235, 235, 235})
  appearance(E, AP.gOff, P .. "group off", {40, 40, 60})
  appearance(E, AP.gOn, P .. "group on", {120, 160, 255})
  appearance(E, AP.bump, P .. "bump", {200, 60, 40})
  for ci, c in ipairs(cols) do
    local on = {math.floor(c.rgb[1] * 2.55 + .5), math.floor(c.rgb[2] * 2.55 + .5), math.floor(c.rgb[3] * 2.55 + .5)}
    appearance(E, apC(ci, true), P .. c.name, on)
    appearance(E, apC(ci, false), P .. c.name .. " dim", {math.floor(on[1] * .35), math.floor(on[2] * .35), math.floor(on[3] * .35)})
  end
  if not E.obj("Layout " .. L) then E.C("Store Layout %d", L) end
  pcall(function() local lh = E.obj("Layout " .. L) for i = lh:Count(), 1, -1 do lh:Delete(i) end end)
  E.C("Label Layout %d %s", L, E.q(P .. "LOS"))

  local lines = {}
  for b = 1, NB do
    local s0, m0, x0, pre = seq0 + (b - 1) * pb.seq, M0 + (b - 1) * pb.macro, mx0 + (b - 1) * pb.mtx, pre0 + b - 1
    local R = (b - 1) * BLOCK_ROWS   -- the block's first layout row
    local B = "LOS" .. b .. " "
    local function V(k) return string.format("%sb%d_%s", VARP, b, k) end
    local mtxNo = {}
    for i, k in ipairs(MXK) do mtxNo[k] = x0 + i - 1 end

    -- MAtricks: nothing set, then each bump's own part of the group
    for _, k in ipairs(MXK) do
      local no = mtxNo[k]
      makeMatricks(E, no, P .. B .. MXN[k])
      for _, p in ipairs(MXSET[k] or {}) do E.C('Set MAtricks %d Property "%s" "%s"', no, p[1], p[2]) end
    end

    -- the LOS preset: a recipe line per family and group (values set by the look buttons)
    E.C("ClearAll")
    if E.obj("Preset 21." .. pre) then E.C("Delete Preset 21.%d /NC", pre) end
    E.C("Store Preset 21.%d /Overwrite", pre)
    E.C("Label Preset 21.%d %s", pre, E.q(P .. "LOS " .. b))
    local k = 0
    for _, f in ipairs(FAMS) do
      for gi, g in ipairs(groups) do
        k = k + 1
        local a = string.format("Preset 21.%d.%d", pre, k)
        E.C('Store Type "StandardRecipe" %s', a)
        E.C("Assign Group %d At %s", g, a)
        E.C('Set %s Property "Name" "%s G%d"', a, f[1], gi)
      end
    end

    -- the bumps: one recipe line per group, values = the LOS preset (groups switched in later)
    local cueList = {}  -- {seq, cue}
    for bi, bu in ipairs(BUMPS) do
      local seq = s0 + bi - 1
      if E.obj("Sequence " .. seq) then E.C("Delete Sequence %d /NC", seq) end
      for c, mk in ipairs(bu[2]) do
        E.C("ClearAll")
        E.C("Store Sequence %d Cue %d /Overwrite", seq, c)
        for gi = 1, nG do
          local a = string.format("Sequence %d Cue %d Part 0.%d", seq, c, gi)
          E.C('Store Type "StandardRecipe" %s', a)
          E.C("Assign Preset 21.%d At %s", pre, a)
          E.C("Assign MAtricks %d At %s", mtxNo[mk], a)
          E.C('Set %s Property "Name" "LOS G%d"', a, gi)
          E.C('Set %s Property "Enabled" "Yes"', a)
        end
        if #bu[2] > 1 then
          E.Cany({ string.format('Set Sequence %d Cue %d Property "TrigType" "Time"', seq, c),
                   string.format('Set Sequence %d Cue %d Property "Trig" "Time"', seq, c) })
          E.Cany({ string.format('Set Sequence %d Cue %d Property "TrigTime" 1', seq, c) })
        end
        cueList[#cueList + 1] = {seq, c}
      end
      E.C("Label Sequence %d %s", seq, E.q(P .. B .. bu[1]))
      setProp(E, "Sequence " .. seq, "OffWhenOverridden", "Yes")
      if #bu[2] > 1 then setProp(E, "Sequence " .. seq, "WrapAround", "Yes") end
      E.C("Assign Appearance %d At Sequence %d", AP.bump, seq)
      if (o.speed or 0) > 0 then E.trySeqMaster(seq, "SpeedMaster", "Speed", o.speed) end
      if (o.rate or 0) > 0 then E.trySeqMaster(seq, "RateMaster", "Speed", o.rate) end
    end
    local sAll = string.format("%d Thru %d", s0, s0 + #BUMPS - 1)

    -- the macros: made and placed first (their element numbers go into the input macros), filled after
    local btns, M = {}, m0
    local function btn(label, text, col, row, ap, fill, start)
      local b2 = {M = M, label = label, text = text, col = col, row = R + row, ap = ap, fill = fill, start = start}
      btns[#btns + 1] = b2
      M = M + 1
      return b2
    end
    -- group toggles: tap 1 = include (assign the group to the bumps' lines), tap 2 = leave out
    for gi, g in ipairs(groups) do
      btn(B .. "Group " .. gi, names[gi], gi - 1, 0, AP.gOff, function(me)
        local on, off = {}, {}
        for _, sc in ipairs(cueList) do
          on[#on + 1] = string.format('Assign Group %d At Sequence %d Cue %d Part 0."LOS G%d"', g, sc[1], sc[2], gi)
          off[#off + 1] = string.format('Set Sequence %d Cue %d Part 0."LOS G%d" Property "Selection" ""', sc[1], sc[2], gi)
        end
        return {string.format("Assign Appearance %d At Macro %d", AP.gOn, me.M), table.concat(on, "; "),
                string.format("Assign Appearance %d At Macro %d", AP.gOff, me.M), table.concat(off, "; ")}, {2}
      end)
    end
    -- the looks: a Goto list per family (a tap opens Off + every option), placed on row 1
    local picks = {}
    for _, f in ipairs(FAMS) do
      if f[3] ~= "colours" then
        local sq = s0 + #BUMPS + #picks
        picks[#picks + 1] = sq
        local items = {{name = "Off", ap = AP.idle, cmd = string.format('Set Preset 21.%d."%s"* Property "Values" ""', pre, f[1])}}
        if f[3] == "list" then
          for _, x in ipairs(lists[f[1]]) do
            items[#items + 1] = {name = x.name, ap = AP.lit, cmd = string.format('Assign Preset %s At Preset 21.%d."%s"*', x.at, pre, f[1])}
          end
        else
          -- each group its own fixture type's preset of that slot; none = that group's line left empty
          for _, sl in ipairs(slots(f[4])) do
            local parts = {}
            for gi, g in ipairs(groups) do
              local a = slotAt(g, f[4], sl)
              parts[#parts + 1] = a and string.format('Assign Preset %s At Preset 21.%d."%s G%d"', a, pre, f[1], gi)
                                    or string.format('Set Preset 21.%d."%s G%d" Property "Values" ""', pre, f[1], gi)
            end
            items[#items + 1] = {name = sl, ap = AP.lit, cmd = table.concat(parts, "; ")}
          end
        end
        if E.obj("Sequence " .. sq) then E.C("Delete Sequence %d /NC", sq) end
        E.C("Store Sequence %d Cue 1 /Overwrite", sq)
        place(E, L, "Sequence " .. sq, #picks - 1, R + 1, f[2], "Goto")
        listSeq(E, sq, P .. B .. f[2], items, AP.idle)
      end
    end
    -- the colours: a macro each (Off + every colour) on row 2
    local first = M
    local function swap(me, ci)
      -- every colour button back to dim, this one lit
      local l = {string.format("Assign Appearance %d At Macro %d", AP.idle, first)}
      if nC > 0 then l[2] = string.format("Assign Appearance %d Thru %d At Macro %d Thru %d", apC(1, false), apC(nC, false), first + 1, first + nC) end
      l[#l + 1] = string.format("Assign Appearance %d At Macro %d", ci and apC(ci, true) or AP.lit, me.M)
      return table.concat(l, "; ")
    end
    btn(B .. "Color Off", "Off", 0, 2, AP.idle, function(me)
      return {string.format('Set Preset 21.%d."Color"* Property "Values" ""', pre), swap(me)}
    end, true)
    for ci, c in ipairs(cols) do
      btn(B .. "Color " .. c.name, "", 0.25 + ci, 2, apC(ci, false), function(me)
        return {string.format('Assign Preset %s At Preset 21.%d."Color"*', c.at, pre), swap(me, ci)}
      end)
    end
    -- timing: Fade / Wings on every MAtricks of the bank, Delay spread forwards (All >) and
    -- backwards (All <), Off = the bumps' release time
    local mAll = string.format("%d Thru %d", x0, x0 + #MXK - 1)
    local TC0 = math.max(TIMING_COL, nG + 0.25)   -- right of the group toggles (up to 20)
    local function setAll(props) local l = {} for _, p in ipairs(props) do l[#l + 1] = string.format('Set MAtricks %s Property "%s" %s', mAll, p[1], p[2]) end return table.concat(l, "; ") end
    local function input(var, prompt, apply, idx)
      return {string.format('SetGlobalVariable "%s" (%s)', var, prompt), losFixDot(var), apply,
              idx and string.format('Set Layout %d.%d Property "CustomTextText" $%s', L, idx, var) or nil}
    end
    local fadeT, delayT, offT, blocksT
    btn(B .. "Fade 0", "Fade 0", TC0, 0, AP.idle, function() return {setAll({{"FadeFromX", '"None"'}, {"FadeToX", '"None"'}}),
      fadeT and string.format('Set Layout %d.%d Property "CustomTextText" "Fade"', L, fadeT.idx) or nil} end, true)
    fadeT = btn(B .. "Fade input", "Fade", TC0 + 1, 0, AP.idle, function(me)
      return input(V("fade"), "LOS " .. b .. " Fade", setAll({{"FadeFromX", losNum(V("fade"))}, {"FadeToX", losNum(V("fade"))}}), me.idx) end)
    btn(B .. "Wings 0", "Wings 0", TC0 + 2.25, 0, AP.idle, function() return {setAll({{"XWings", '"None"'}})} end, true)
    btn(B .. "Wings 2", "Wings 2", TC0 + 3.25, 0, AP.idle, function() return {setAll({{"XWings", '"2"'}})} end)
    -- Blocks: XBlock on every MAtricks of the bank (fixtures in blocks of n act as one)
    btn(B .. "Blocks 0", "Blocks 0", TC0 + 4.5, 0, AP.idle, function() return {setAll({{"XBlock", '"None"'}}),
      blocksT and string.format('Set Layout %d.%d Property "CustomTextText" "Blocks"', L, blocksT.idx) or nil} end, true)
    blocksT = btn(B .. "Blocks", "Blocks", TC0 + 4.5, 1, AP.idle, function(me)
      return input(V("blocks"), "LOS " .. b .. " Blocks", setAll({{"XBlock", "$" .. V("blocks")}}), me.idx) end)
    local A, Bm = mtxNo.A, mtxNo.B
    btn(B .. "Delay 0", "Delay 0", TC0, 1, AP.idle, function()
      return {string.format('Set MAtricks %d Thru %d Property "DelayFromX" "None" "DelayToX" "None"', A, Bm),
              delayT and string.format('Set Layout %d.%d Property "CustomTextText" "Delay"', L, delayT.idx) or nil} end, true)
    delayT = btn(B .. "Delay input", "Delay", TC0 + 1, 1, AP.idle, function(me)
      local v = losNum(V("delay"))
      return input(V("delay"), "LOS " .. b .. " Delay",
        string.format('Set MAtricks %d Property "DelayFromX" "0" "DelayToX" %s; Set MAtricks %d Property "DelayFromX" %s "DelayToX" "0"', A, v, Bm, v), me.idx) end)
    local chase = s0 + #BUMPS - 1
    btn(B .. "Off 0", "Off 0", TC0 + 2.25, 1, AP.idle, function()
      return {string.format("Set CueFade 0 Sequence %s Cue OffCue; Set CueFade 0 Sequence %d Cue 1 Thru 3", sAll, chase),
              offT and string.format('Set Layout %d.%d Property "CustomTextText" "Off"', L, offT.idx) or nil} end, true)
    offT = btn(B .. "Off input", "Off", TC0 + 3.25, 1, AP.idle, function(me)
      local v = losNum(V("off"))
      return input(V("off"), "LOS " .. b .. " Off Time",
        string.format("Set CueFade %s Sequence %s Cue OffCue; Set CueFade %s Sequence %d Cue 1 Thru 3", v, sAll, v, chase), me.idx) end)

    -- place, then fill
    for _, bt in ipairs(btns) do
      E.C("Store Macro %d /Overwrite", bt.M)
      E.C("Label Macro %d %s", bt.M, E.q(P .. bt.label))
      bt.idx = place(E, L, "Macro " .. bt.M, bt.col, bt.row, bt.text)
    end
    for _, bt in ipairs(btns) do
      local l, waits = bt.fill(bt)
      local clean = {}
      for i = 1, 4 do if l[i] then clean[#clean + 1] = l[i] end end
      macro(E, bt.M, P .. bt.label, clean, bt.ap)
      for i = 1, #clean do setWait(E, bt.M, i, "Follow") end
      for _, w in ipairs(waits or {}) do setWait(E, bt.M, w, "Go") end
    end
    -- the bump buttons (Temp: on while held, off with the Off time on release)
    for bi, bu in ipairs(BUMPS) do place(E, L, "Sequence " .. (s0 + bi - 1), bi - 1, R + 3, B .. bu[1], "Temp") end
    -- start: every family Off, timing 0 (groups start left out)
    for _, sq in ipairs(picks) do E.C("Goto Sequence %d Cue 1", sq) end
    for _, bt in ipairs(btns) do
      if bt.start then E.C("Go+ Macro %d", bt.M) end
    end
    lines[#lines + 1] = string.format("LOS %d: bumps Sequences %d-%d, look lists %d-%d, Macros %d-%d, MAtricks %d-%d, Preset 21.%d.",
      b, s0, s0 + #BUMPS - 1, s0 + #BUMPS, s0 + #BUMPS + NPICK - 1, m0, M - 1, x0, x0 + #MXK - 1, pre)
  end
  E.C("ClearAll")
  svar("groups", E.rangeList({table.unpack(groups)})) svar("banks", NB) svar("layout", L) svar("seq", seq0)
  svar("macro", M0) svar("ap", ap0) svar("mtx", mx0) svar("preset", pre0)
  svar("speed", o.speed or 0) svar("rate", o.rate or 0)
  table.insert(lines, 1, string.format("Layout %d: %d LOS bank(s) for %d groups.", L, NB, nG))
  lines[#lines + 1] = "Tap a group button to include it in that bank's bumps (tap again to leave it out); put the bump sequences on X-keys / executors."
  if madeP > 0 then lines[#lines + 1] = string.format("%d missing presets were made.", madeP) end
  if #foreign > 0 then
    lines[#lines + 1] = "\nPresets in use by something else (left out):"
    for i = 1, math.min(#foreign, 8) do lines[#lines + 1] = "  " .. foreign[i] end
  end
  return lines
end

local function main(displayHandle, argument)
  if not env then
    local ok, E = pcall(build)
    if not ok then return say(tostring(E)) end
    env = E
  end
  local E = env
  local groups, o = ask(E, #E.CFG.COLORS)
  if not groups then return end
  local good = {}
  for _, g in ipairs(groups) do if E.obj("Group " .. g) then good[#good + 1] = g end end
  if #good == 0 then return say("None of those groups exist yet. Store your groups first, then run " .. TITLE .. " again.") end
  if #good > MAX_GROUPS then return say("Pick up to " .. MAX_GROUPS .. " groups.") end
  if not (o.L and o.seq0 and o.M0 and o.ap0 and o.mx0 and o.pre) then
    return say("Fill in the layout, first sequence, macro, appearance, MAtricks and LOS preset numbers.")
  end
  local ok, lines, err = pcall(buildLOS, E, good, o)
  pcall(Cmd, "ClearAll")
  if not ok then return say("Stopped: " .. tostring(lines)) end
  if not lines then return say(err) end
  if #good < #groups then lines[#lines + 1] = "Skipped groups that don't exist." end
  if #E.failures > 0 then
    lines[#lines + 1] = string.format("\n%d commands failed, first: %s", #E.failures, E.failures[1])
    for _, f in ipairs(E.failures) do Printf(TITLE .. ": " .. f) end
  end
  say(table.concat(lines, "\n"))
  pcall(Cmd, "Select Layout " .. o.L)
end

return main
