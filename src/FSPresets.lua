--[[
  FSPresets.lua  -  "FS Presets": builds the FireSystem presets and nothing else
  ------------------------------------------------------------------------
  One of the single-purpose FireSystem tools. Run it (click it in the Plugins pool) and it asks
  which groups to use and which preset families to make, then stores those presets numbered from 1
  in each pool: every phaser (Dimmer FX forms, Position FX, Fly In / Out, Zoom Sine, dimmer chase
  strobes) in the All pool (21), the static ones in the encoder bar pool of their attributes
  (Dimmer 1 incl. 0-100 % and relative -100..+100 % in 10 % steps, Position 2, Gobo 3 per fixture
  type, Color 4 as normal / Pastel / Dark blocks, Beam 5 shutter strobes and prisms per fixture type,
  Focus 6 zoom steps and Focus 0-100 %). Mixed-feature static presets go in All. Bump presets are
  left to the bumps tool.
  The numbers don't depend on which families you tick, so running it again lands on the same slots.
  The show doesn't need the plugin afterwards.

  Run it again after adding fixtures to a group: with "Remake existing presets" on, every FS
  preset is stored again, so the new fixtures get their values too. A preset in those slots whose
  name doesn't start with "FS " is yours and is left alone (listed at the end).

  ONE FILE, NO OTHER PLUGIN NEEDED: plugins/FSPresets.lua is generated by tools/make_tools.py from
  this source (src/FSPresets.lua) plus a copy of the FireSystem module files, so it
  runs on its own (FireSystem doesn't have to be in the show) and never mixes with another
  FireSystem version. Edit this source or the modules, then run `python3 tools/make_tools.py`.
  The settings (prefix, pool numbers, colours, fan sizes ...) come from FireSystemConfig.lua.
--]]

local TITLE = "FS Presets"

--@INCLUDE common@
--@INCLUDE presets@

local FAMILIES = {  -- {key, label in the dialog}
  {"dim", "Dimmer FX"},
  {"col", "Colours (+ Pastel / Dark)"},
  {"pos", "Positions (pans, tilts, fans)"},
  {"pfx", "Position FX (swings, circles, Fly In / Out)"},
  {"strobe", "Strobes"},
  {"zoom", "Zoom and Focus"},
  {"gobo", "Gobos and prisms (per fixture type, from its wheels)"},
  {"beam", "Shutter, iris and frost"},
}

local function ask(E)
  local states = {}
  for _, f in ipairs(FAMILIES) do
    local v = GetVar(GlobalVars(), "FSP_" .. f[1])
    states[#states + 1] = {name = f[2], state = v ~= "0"}
  end
  states[#states + 1] = {name = "Remake existing presets", state = GetVar(GlobalVars(), "FSP_force") ~= "0"}
  local r = MessageBox({
    title = TITLE,
    message = "Groups to build the presets for (up to 20), e.g. 1 Thru 8 or 1,2,5.\n" ..
              "Presets start at 1 in each pool: phasers go in the All pool, the rest in\n" ..
              "their own pool (Dimmer, Position, Gobo, Color, Beam, Focus).",
    commands = {{value = 1, name = "Build"}, {value = 0, name = "Cancel"}},
    inputs = {{name = "Groups", value = defaultGroups(E, "FSP_groups"), whiteFilter = "0123456789 ,+-ThruTHRU"}},
    states = states,
  })
  if not r or r.result ~= 1 then return nil end
  local want = {}
  for _, f in ipairs(FAMILIES) do
    local on = r.states and r.states[f[2]]
    if on == nil then on = true end
    want[f[1]] = on and true or false
    SetVar(GlobalVars(), "FSP_" .. f[1], on and "1" or "0")
  end
  local force = r.states and r.states["Remake existing presets"]
  if force == nil then force = true end
  SetVar(GlobalVars(), "FSP_force", force and "1" or "0")
  local text = r.inputs and r.inputs["Groups"] or ""
  return parseGroups(text), want, force
end

local function main(displayHandle, argument)
  if not env then
    local ok, E = pcall(build)
    if not ok then return say(tostring(E)) end
    env = E
  end
  local E = env
  local groups, want, force = ask(E)
  if not groups then return end
  local good = {}
  for _, g in ipairs(groups) do
    if E.obj("Group " .. g) then good[#good + 1] = g end
  end
  if #good == 0 then return say("None of those groups exist yet. Store your groups first, then run " .. TITLE .. " again.") end
  if #good > MAX_GROUPS then return say("Pick up to " .. MAX_GROUPS .. " groups.") end
  SetVar(GlobalVars(), "FSP_groups", E.rangeList({table.unpack(good)}))
  want.rot = want.gobo  -- (gobo / prism spin goes with the gobos)
  local made, foreign, kept = buildPresets(E, good, want, force)
  local lines = {string.format("%d presets stored for Group %s.", made, table.concat(good, ", "))}
  if #good < #groups then lines[#lines + 1] = "Skipped groups that don't exist." end
  if kept > 0 then
    lines[#lines + 1] = string.format("%d were already there and kept (turn on \"Remake existing presets\" to store them again).", kept)
  end
  if #foreign > 0 then
    lines[#lines + 1] = "\nLeft alone (not FS presets):"
    for i = 1, math.min(#foreign, 12) do lines[#lines + 1] = "  " .. foreign[i] end
    if #foreign > 12 then lines[#lines + 1] = string.format("  ... and %d more", #foreign - 12) end
  end
  if #E.failures > 0 then
    lines[#lines + 1] = string.format("\n%d commands failed, first: %s", #E.failures, E.failures[1])
    for _, f in ipairs(E.failures) do Printf(TITLE .. ": " .. f) end
  end
  say(table.concat(lines, "\n"))
end

return main
