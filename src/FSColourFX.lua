--[[
  FSColourFX.lua  -  "FS Colour FX": builds a colour FX layout, nothing else
  ------------------------------------------------------------------------
  One of the single-purpose FireSystem tools. Run it (click it in the Plugins pool) and it asks for
  the groups and the pool numbers, then builds a layout with an ALL row and one row per group:

    [group] [Off] [Sine] [Ramp Dn] [Ramp Up] [Square] [Heart] [2-5 Steps] [STEP 1-5] [MAtricks]

  How it plays (the show doesn't need the plugin afterwards):
  - each group's STEP k colour is its own preset (Color pool, "FS CF <group> Step k");
  - a STEP button is a sequence with one empty cue per colour (15 colours x Normal / Pastel /
    Dark, each cue showing its colour; Prefer Cue Appearance): a tap opens MA's Goto list to pick
    one (Lyn 2026-11-16), and the picked cue's command copies that colour preset over the STEP
    preset, then replays the row's form; the button shows the colour in use;
  - each form button is a sequence with PhaserRecipe cues (Group + the row's MAtricks, one phaser
    step per colour step pointing at the STEP presets): cue 2 = 2 steps, cue 3 = 3 steps, and cue 1
    (the press) jumps to the row's step count through a global variable, like the position FX sizes;
  - a form switches the row's other forms off; a tap only starts it (On), and Off stops them and
    keeps Steps / STEP picks from restarting them; the forms follow a speed master (Speed 3 by default, as in FireSystem);
  - ALL buttons run the same button on every group row.

  ONE FILE, NO OTHER PLUGIN NEEDED: plugins/FSColourFX.lua is generated by tools/make_tools.py
  from this source, the shared tool code in src/lib/ and a copy of the FireSystem
  module files. Edit those, then run `python3 tools/make_tools.py`.
--]]

local TITLE = "FS Colour FX"
local TAG = "CF"       -- names: "FS CF ..." (what a rebuild may replace)
local VARP = "FSCF_"   -- this tool's global variables

--@INCLUDE common@
--@INCLUDE presets@
--@INCLUDE picker@

local NSTEP = 5                        -- STEP buttons / most colour steps (Lyn 2026-11-16: 5)
local STEP_DEFAULT = {"White", "Red", "Blue", "Green", "Magenta"}
-- the forms: {button, shape}. Heart = a fixed rainbow sine (Lyn: in the showfile the heart is a
-- preset rainbow): it ignores the STEP colours and the step count
local FORMS = { {"Sine", "sine"}, {"Ramp Dn", "down"}, {"Ramp Up", "up"}, {"Square", "square"}, {"Heart", "rainbow"} }
local RAINBOW = {"Red", "Orange", "Yellow", "Green", "Cyan", "Blue", "Violet", "Magenta"}
local MXL = mxList("Wings", "Groups", "Blocks", "Phase", "Speed")
local NMX = #MXL
local NF = #FORMS
-- macros per row: Off, 2 / 3 Steps
local MPR = 1 + (NSTEP - 1)
-- sequences per group row: the forms and the STEP pickers (ALL: the STEP pickers)
local SPR = NF + NSTEP

-- one form at n steps: {{source STEP, hard}, ...}
local function plan(shape, n)
  local out = {}
  for k = 1, n do
    out[k] = {k, shape == "square" or (shape == "down" and k == 1) or (shape == "up" and k == n)}
  end
  return out
end

-- the STEP presets (Color pool): ours when free or named "FS CF ..."
local function minePreset(E, n)
  local h = E.obj("Preset 4." .. n)
  if not h then return true end
  return tostring(E.objName(h) or ""):find("^" .. E.CFG.PREFIX .. " " .. TAG .. " ") ~= nil
end
local function freePresets(E, n, from)
  local i = from
  while i < 10000 do
    local ok = true
    for k = i, i + n - 1 do if not minePreset(E, k) then ok = false i = k + 1 break end end
    if ok then return i end
  end
  return from
end

local function ask(E, nC)
  local groups = defaultGroups(E, VARP .. "groups")
  local rows = #parseGroups(groups)
  local function def(k, kind, n, from)
    local v = tonumber(gvar(k) or "")
    return tostring(v or freeBlock(E, kind, n, from))
  end
  local nSeq = rows * SPR + NSTEP + (rows + 1) * NMX
  local nM = (rows + 1) * MPR + NF
  local r = MessageBox({
    title = TITLE,
    message = "Groups for the colour FX blocks (up to 20), e.g. 1 Thru 8 or 1,2,5. An ALL block goes on top.\n" ..
              "The numbers below are where the layout and its sequences, macros, appearances, MAtricks and\n" ..
              string.format("STEP presets go (%d sequences, %d macros, %d appearances, %d MAtricks, %d Color presets).\n",
                            nSeq, nM, 3 * nC + 5, rows, rows * NSTEP) ..
              "Speed master: the one the FX follow (0 = none).",
    commands = {{value = 1, name = "Build"}, {value = 0, name = "Cancel"}},
    states = {{name = ICON_BOX, state = gvar("icons") == "1"}},
    inputs = {
      {name = "Groups", value = groups, whiteFilter = "0123456789 ,+-ThruTHRU"},
      {name = "Layout", value = def("layout", "Layout", 1, 1), whiteFilter = "0123456789"},
      {name = "First sequence", value = def("seq", "Sequence", nSeq, 101), whiteFilter = "0123456789"},
      {name = "First macro", value = def("macro", "Macro", nM, 101), whiteFilter = "0123456789"},
      {name = "First appearance", value = def("ap", "Appearance", 3 * nC + 5, 101), whiteFilter = "0123456789"},
      {name = "First MAtricks", value = def("mtx", "MAtricks", rows, 1), whiteFilter = "0123456789"},
      {name = "First STEP preset", value = tostring(tonumber(gvar("step") or "") or freePresets(E, rows * NSTEP, 101)),
       whiteFilter = "0123456789"},
      {name = "Speed master", value = tostring(tonumber(gvar("speed") or "") or 3), whiteFilter = "0123456789"},
    },
  })
  if not r or r.result ~= 1 then return nil end
  local i = r.inputs or {}
  local function n(k) return tonumber(i[k] or "") end
  return parseGroups(i["Groups"]), {icons = (r.states or {})[ICON_BOX] and true or false, L = n("Layout"), seq0 = n("First sequence"), M0 = n("First macro"),
    ap0 = n("First appearance"), mx0 = n("First MAtricks"), st0 = n("First STEP preset"), speed = n("Speed master") or 0}
end

-- a form button: Sequence seq, cue c = c steps (cue 1 = the press, 2 steps), one PhaserRecipe line
-- each: Group g + MAtricks mtx, phaser step k at the STEP preset it shows
-- stepsOf(n) = the phaser steps at n colour steps: {{Color preset no, hard}, ...}
local function formSeq(E, seq, label, g, mtx, stepsOf, apOff, apOn, cmds)
  if E.obj("Sequence " .. seq) then E.C("Delete Sequence %d /NC", seq) end
  for cue = 1, NSTEP do
    local n = math.max(cue, 2)
    E.C("ClearAll")
    E.C("Store Sequence %d Cue %d /Overwrite", seq, cue)
    E.C("Label Sequence %d Cue %d %s", seq, cue, E.q(n .. " steps"))
    local a = string.format("Sequence %d Cue %d Part 0.1", seq, cue)
    E.C('Store Type "PhaserRecipe" %s', a)
    E.C("Assign Group %d At %s", g, a)
    E.C("Assign MAtricks %d At %s", mtx, a)
    local have = 0
    pcall(function() have = E.obj(a)[1]:Count() end)
    for k, p in ipairs(stepsOf(n)) do
      if k > have then E.C("Store %s.1.%d /NC", a, k) end
      local vs = string.format("%s.1.%d.1", a, k)
      E.C("Assign Preset 4.%d At %s", p[1], vs)
      E.C('Set %s Property "TransX" %d', vs, p[2] and 0 or 100)
    end
    E.C('Set %s Property "Enabled" "Yes"', a)
    E.C("Assign Appearance %d At Sequence %d Cue %d", apOn, seq, cue)
    cueCmd(E, seq, cue, cmds[cue])
  end
  E.C("Label Sequence %d %s", seq, E.q(label))
  setProp(E, "Sequence " .. seq, "PreferCueAppearance", "Yes")
  E.C("Assign Appearance %d At Sequence %d", apOff, seq)
end

local function buildFX(E, groups, o)
  local L, seq0, M0, ap0, mx0, st0 = o.L, o.seq0, o.M0, o.ap0, o.mx0, o.st0
  E.failures = {}
  E.CFG.GROUPS = groups
  local cols, madeP, foreign = colourPresets(E)
  local nC = #cols
  local names = {}
  for gi, g in ipairs(groups) do names[gi] = tostring(E.objName(E.obj("Group " .. g)) or ("Group " .. g)) end
  local nG = #groups
  local nSeq = nG * SPR + NSTEP + (nG + 1) * NMX
  local nM = (nG + 1) * MPR + NF
  local nAp = 3 * nC + 5
  -- refuse to overwrite anything that isn't ours
  local clash = {}
  if not mine(E, "Layout", L) then clash[#clash + 1] = "Layout " .. L end
  for k = seq0, seq0 + nSeq - 1 do if not mine(E, "Sequence", k) then clash[#clash + 1] = "Sequence " .. k end end
  for k = M0, M0 + nM - 1 do if not mine(E, "Macro", k) then clash[#clash + 1] = "Macro " .. k end end
  for k = ap0, ap0 + nAp - 1 do if not mine(E, "Appearance", k) then clash[#clash + 1] = "Appearance " .. k end end
  for k = mx0, mx0 + nG - 1 do if not mine(E, "MAtricks", k) then clash[#clash + 1] = "MAtricks " .. k end end
  for k = st0, st0 + nG * NSTEP - 1 do if not minePreset(E, k) then clash[#clash + 1] = "Preset 4." .. k end end
  if #clash > 0 then
    return nil, "These are already used by something else:\n  " .. table.concat(clash, "\n  ", 1, math.min(#clash, 10)) ..
      (#clash > 10 and "\n  ..." or "") .. "\n\nPick other numbers and run it again."
  end
  local P = E.CFG.PREFIX .. " " .. TAG .. " "
  -- appearances: per colour Normal / Pastel / Dark (the STEP cues), then the STEP button off, the
  -- forms off / on and idle / lit
  local function apC(ci, t) return ap0 + 3 * (ci - 1) + (t - 1) end
  local AP = {step = ap0 + 3 * nC, fxOff = ap0 + 3 * nC + 1, fxOn = ap0 + 3 * nC + 2, idle = ap0 + 3 * nC + 3, lit = ap0 + 3 * nC + 4}
  local function rgb255(t) return {math.floor(t[1] * 2.55 + 0.5), math.floor(t[2] * 2.55 + 0.5), math.floor(t[3] * 2.55 + 0.5)} end
  for ci, c in ipairs(cols) do
    local on = rgb255(c.rgb)
    appearance(E, apC(ci, 1), P .. c.name, on)
    appearance(E, apC(ci, 2), P .. c.name .. " Pastel", rgb255(E.tintRGBW(c.rgb, 0, 1)))
    -- (the real Dark is 35 %: on a button that reads as off, so it shows at 55 %)
    appearance(E, apC(ci, 3), P .. c.name .. " Dark", {math.floor(on[1] * .55), math.floor(on[2] * .55), math.floor(on[3] * .55)})
  end
  appearance(E, AP.step, P .. "STEP", {60, 60, 60})
  appearance(E, AP.fxOff, P .. "FX off", {64, 40, 56})
  appearance(E, AP.fxOn, P .. "FX on", {255, 90, 200})
  appearance(E, AP.idle, P .. "idle", {60, 60, 60})
  appearance(E, AP.lit, P .. "lit", {220, 220, 220})
  -- the layout: emptied and refilled on a rebuild
  if not E.obj("Layout " .. L) then E.C("Store Layout %d", L) end
  pcall(function() local lh = E.obj("Layout " .. L) for i = lh:Count(), 1, -1 do lh:Delete(i) end end)
  E.C("Label Layout %d %s", L, E.q(P .. "Colour FX"))

  -- numbering: row b = 0 (ALL) .. nG; the group rows' sequences / macros first, ALL's last
  local function stepPreset(gi, k) return st0 + (gi - 1) * NSTEP + (k - 1) end
  local function formSeqNo(gi, f) return seq0 + (gi - 1) * SPR + (f - 1) end
  local function stepSeqNo(b, k) return b == 0 and (seq0 + nG * SPR + (k - 1)) or (seq0 + (b - 1) * SPR + NF + (k - 1)) end
  local function mBase(b) return M0 + ((b == 0 and nG + 1 or b) - 1) * MPR end
  local function offM(b) return mBase(b) end
  local function stepsM(b, n) return mBase(b) + 1 + (n - 2) end                      -- n = 2 .. NSTEP
  local allFormM = M0 + (nG + 1) * MPR                                                -- + f - 1
  local function V(gi, name) return string.format("%sL%d_g%d_%s", VARP, L, gi, name) end
  local TNAME = {"", " Pastel", " Dark"}
  local function cueOf(ci, t) return (t - 1) * nC + ci end                           -- STEP cue: colour ci in tint t
  local colourNo = {}
  for ci, c in ipairs(cols) do colourNo[c.name] = ci end

  for gi = 1, nG do makeMatricks(E, mx0 + gi - 1, P .. names[gi]) end
  -- the STEP presets must exist before the forms point at them (the STEP pickers set them below)
  local function stepLabel(gi, k) return P .. names[gi] .. " Step " .. k end
  for gi = 1, nG do
    for k = 1, NSTEP do
      local ci = colourNo[STEP_DEFAULT[k]] or k
      E.C("Copy Preset 4.%d At Preset 4.%d /Overwrite", cols[ci].no[1], stepPreset(gi, k))
      E.C("Label Preset 4.%d %s", stepPreset(gi, k), E.q(stepLabel(gi, k)))
    end
  end

  -- a STEP picker: one empty cue per colour and tint, each showing its colour; cmd(ci, t) = its command
  local function stepSeq(seq, label, cmd)
    if E.obj("Sequence " .. seq) then E.C("Delete Sequence %d /NC", seq) end
    for t = 1, 3 do
      for ci, c in ipairs(cols) do
        local cue = cueOf(ci, t)
        E.C("ClearAll")
        E.C("Store Sequence %d Cue %d /Overwrite", seq, cue)
        E.C("Label Sequence %d Cue %d %s", seq, cue, E.q(c.name .. TNAME[t]))
        E.C("Assign Appearance %d At Sequence %d Cue %d", apC(ci, t), seq, cue)
        -- (and on its part: the Goto list may show the part's appearance rather than the cue's)
        E.Cany({ string.format("Assign Appearance %d At Sequence %d Cue %d Part 0", apC(ci, t), seq, cue) })
        cueCmd(E, seq, cue, cmd(ci, t))
      end
    end
    E.C("Label Sequence %d %s", seq, E.q(label))
    setProp(E, "Sequence " .. seq, "PreferCueAppearance", "Yes")
    E.C("Assign Appearance %d At Sequence %d", AP.step, seq)
  end

  local stepsCol = 2 + NF + 0.25
  local stepCol = stepsCol + (NSTEP - 1) + 0.25
  for b = 0, nG do
    local all, g = b == 0, groups[b]
    if not all then place(E, L, "Group " .. g, 0, b, names[b]) end
    -- the forms
    for f, form in ipairs(FORMS) do
      if all then
        local l = {}
        for gi = 1, nG do l[#l + 1] = string.format("Goto Sequence %d Cue 1", formSeqNo(gi, f)) end
        macro(E, allFormM + f - 1, P .. "ALL " .. form[1], l, AP.fxOn)
        place(E, L, "Macro " .. (allFormM + f - 1), 1 + f, 0, form[1])
      else
        local seq = formSeqNo(b, f)
        local others = {}
        for f2 = 1, NF do if f2 ~= f then others[#others + 1] = formSeqNo(b, f2) end end
        local keep = "Off Sequence " .. E.rangeList(others) .. "; " .. setVarCmd(E, V(b, "act"), "Goto Sequence " .. seq .. " Cue 1")
        local cmds = {string.format("Goto Sequence %d Cue $%s", seq, V(b, "steps"))}
        for cue = 2, NSTEP do cmds[cue] = keep end
        local function stepsOf(n)
          local t = {}
          if form[2] == "rainbow" then
            for _, name in ipairs(RAINBOW) do if colourNo[name] then t[#t + 1] = {cols[colourNo[name]].no[1], false} end end
          else
            for k, p in ipairs(plan(form[2], n)) do t[k] = {stepPreset(b, p[1]), p[2]} end
          end
          return t
        end
        formSeq(E, seq, P .. names[b] .. " " .. form[1], g, mx0 + b - 1, stepsOf, AP.fxOff, AP.fxOn, cmds)
        if o.speed > 0 then E.trySeqMaster(seq, "SpeedMaster", "Speed", o.speed) end
        -- On, not Toggle: a toggled-off form would leave the replay pointing at it, and Steps /
        -- STEP picks would start it again. Off stops it (and points the replay at the Off)
        place(E, L, "Sequence " .. seq, 1 + f, b, form[1], "On")
      end
    end
    -- Off: the row's forms off, and the replay pointed at that Off (Steps / STEP picks don't restart it)
    if all then
      local l = {}
      for gi = 1, nG do l[#l + 1] = "Go+ Macro " .. offM(gi) end
      macro(E, offM(0), P .. "ALL FX Off", l, AP.fxOff)
    else
      local off = string.format("Off Sequence %d Thru %d", formSeqNo(b, 1), formSeqNo(b, NF))
      macro(E, offM(b), P .. names[b] .. " FX Off", {off, setVarCmd(E, V(b, "act"), off)}, AP.fxOff)
      -- through the command line, the store its $variables read
      E.C(setVarCmd(E, V(b, "act"), off))
      E.C(setVarCmd(E, V(b, "steps"), "2"))
    end
    place(E, L, "Macro " .. offM(b), 1, b, "Off")
    -- 2 / 3 Steps: set the row's step count, light the button, replay the row's form
    local function lightSteps(l, bs, n)
      local lit, idle = {}, {}
      for _, bb in ipairs(bs) do for m = 2, NSTEP do table.insert(m == n and lit or idle, stepsM(bb, m)) end end
      l[#l + 1] = string.format("Assign Appearance %d At Macro %s", AP.lit, E.rangeList(lit))
      if #idle > 0 then l[#l + 1] = string.format("Assign Appearance %d At Macro %s", AP.idle, E.rangeList(idle)) end
    end
    for n = 2, NSTEP do
      local l = {}
      local bs = {b}
      if all then
        for gi = 1, nG do l[#l + 1] = setVarCmd(E, V(gi, "steps"), tostring(n)) bs[#bs + 1] = gi end
        lightSteps(l, bs, n)
        for gi = 1, nG do l[#l + 1] = "$" .. V(gi, "act") end
      else
        l[1] = setVarCmd(E, V(b, "steps"), tostring(n))
        lightSteps(l, bs, n)
        l[#l + 1] = "$" .. V(b, "act")
      end
      macro(E, stepsM(b, n), P .. (all and "ALL" or names[b]) .. " " .. n .. " Steps", l, n == 2 and AP.lit or AP.idle)
      place(E, L, "Macro " .. stepsM(b, n), stepsCol + n - 2, b, n .. " Steps")
    end
    -- STEP 1-3: the pickers (a tap opens the Goto list of colours)
    for k = 1, NSTEP do
      local sq = stepSeqNo(b, k)
      stepSeq(sq, P .. (all and "ALL" or names[b]) .. " Step " .. k, function(ci, t)
        if all then
          local l = {}
          for gi = 1, nG do l[#l + 1] = string.format("Goto Sequence %d Cue %d", stepSeqNo(gi, k), cueOf(ci, t)) end
          return table.concat(l, "; ")
        end
        -- copy the colour over the STEP preset (and keep its name), then replay the row's form
        return string.format('Copy Preset 4.%d At Preset 4.%d /Overwrite; Label Preset 4.%d "%s"; $%s',
          cols[ci].no[t], stepPreset(b, k), stepPreset(b, k), stepLabel(b, k), V(b, "act"))
      end)
      place(E, L, "Sequence " .. sq, stepCol + k - 1, b, "STEP " .. k, "Goto")
    end
  end
  -- start each STEP picker on its colour (White / Red / Blue), so the buttons show it
  for b = 0, nG do
    for k = 1, NSTEP do
      E.C("Goto Sequence %d Cue %d", stepSeqNo(b, k), cueOf(colourNo[STEP_DEFAULT[k]] or k, 1))
    end
  end
  -- the MAtricks buttons (lib picker) on each block's forms row
  local seq = seq0 + nG * SPR + NSTEP
  seq = mxButtons(E, {L = L, n = nG, names = names, mx0 = mx0, seq0 = seq, col = stepCol + NSTEP + 0.25,
                      row = function(r) return r end, P = P, AP = AP, list = MXL,
                      rate = function(r) local l = {} for f = 1, NF do l[f] = {formSeqNo(r, f), NSTEP} end return l end})
  E.C("ClearAll")
  svar("mtx", mx0) svar("speed", o.speed) svar("step", st0)
  svar("groups", E.rangeList({table.unpack(groups)})) svar("layout", L) svar("seq", seq0) svar("macro", M0) svar("ap", ap0)
  local lines = {string.format("Layout %d: ALL + %d group rows, %d forms x up to %d colour steps (Sequences %d-%d, " ..
    "Macros %d-%d, Appearances %d-%d, MAtricks %d-%d, STEP presets 4.%d-%d).", L, nG, NF, NSTEP, seq0, seq - 1,
    M0, M0 + nM - 1, ap0, ap0 + nAp - 1, mx0, mx0 + nG - 1, st0, st0 + nG * NSTEP - 1)}
  if o.speed > 0 then lines[#lines + 1] = string.format("The FX follow Speed master %d.", o.speed) end
  if madeP > 0 then lines[#lines + 1] = string.format("%d missing colour presets were made (Color 4.x).", madeP) end
  if #foreign > 0 then
    lines[#lines + 1] = "\nColour presets in use by something else (those buttons copy that preset):"
    for i = 1, math.min(#foreign, 8) do lines[#lines + 1] = "  " .. foreign[i] end
  end
  return lines
end

local function main(displayHandle, argument)
  if not env then
    local ok, E = pcall(build)
    if not ok then return say(tostring(E)) end
    env = E
  end
  local E = env
  local groups, o = ask(E, #E.CFG.COLORS)
  if not groups then return end
  local good = {}
  for _, g in ipairs(groups) do if E.obj("Group " .. g) then good[#good + 1] = g end end
  if #good == 0 then return say("None of those groups exist yet. Store your groups first, then run " .. TITLE .. " again.") end
  if #good > MAX_GROUPS then return say("Pick up to " .. MAX_GROUPS .. " groups.") end
  if not (o.L and o.seq0 and o.M0 and o.ap0 and o.mx0 and o.st0) then
    return say("Fill in the layout, first sequence, macro, appearance, MAtricks and STEP preset numbers.")
  end
  iconsStart(E, o.icons)
  local ok, lines, err = pcall(buildFX, E, good, o)
  local iconNote = iconsFinish(E, ok and lines ~= nil)
  if iconNote and type(lines) == "table" then lines[#lines + 1] = iconNote end
  pcall(Cmd, "ClearAll")
  if not ok then return say("Stopped: " .. tostring(lines)) end
  if not lines then return say(err) end
  if #good < #groups then lines[#lines + 1] = "Skipped groups that don't exist." end
  if #E.failures > 0 then
    lines[#lines + 1] = string.format("\n%d commands failed, first: %s", #E.failures, E.failures[1])
    for _, f in ipairs(E.failures) do Printf(TITLE .. ": " .. f) end
  end
  say(table.concat(lines, "\n"))
  pcall(Cmd, "Select Layout " .. o.L)
end

return main
