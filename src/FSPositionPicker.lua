--[[
  FSPositionPicker.lua  -  "FS Position Picker": builds a position picker layout, nothing else
  ------------------------------------------------------------------------
  One of the single-purpose FireSystem tools. Run it (click it in the Plugins pool) and it asks for
  the groups and the pool numbers, then builds a layout with an ALL row and one row per group:

    [group] [12 pans / fans] [15 tilts]
    and below, a second section:
    [group] [8 position FX] [Small / Mid / Big] [7 MAtricks]

  Built the same way as FS Colour Picker: every group button is a sequence with recipe cues
  (Group At the FS Presets preset), Prefer Cue Appearance, Off When Overridden and a Toggle action.
  Pans and tilts set only their own attribute, so a row keeps one pan and one tilt; picking another
  pan takes over from the last one. The position FX are relative phasers that run on top of the
  position. Each FX button has 4 cues: cue 1 is the press and jumps to the row's size (Small 2,
  Mid 3, Big 4) through a global variable; Small / Mid / Big at the end of the row are 4-line macros
  that set it and replay the row's running FX. ALL buttons are macros that start the same button
  on every row. Each group row has its own MAtricks pool object that all its recipe lines point at;
  the MAtricks buttons (Wings, Sym, Groups, Blocks, Phase, Fade, Delay) are cycling sequences whose
  cues set that object. The ALL row's MAtricks buttons step every row's button to the same value.
  The show doesn't need the plugin afterwards.

  The presets are FS Presets' own (Position 2.1-19, Position FX in the All pool), made here if
  they're missing, so FS Presets and the pickers can be run in any order.

  ONE FILE, NO OTHER PLUGIN NEEDED: plugins/FSPositionPicker.lua is generated by tools/make_tools.py
  from this source, the shared tool code in src/lib/ and a copy of the FireSystem
  module files. Edit those, then run `python3 tools/make_tools.py`.
--]]

local TITLE = "FS Position Picker"
local TAG = "PP"       -- names: "FS PP ..." (what a rebuild may replace)
local VARP = "FSPP_"   -- this tool's global variables

--@INCLUDE common@
--@INCLUDE presets@
--@INCLUDE picker@

local SIZES = {"Small", "Mid", "Big"}
local SIZE_TAG = {" -", "", " +"}     -- FS Presets' labels: "Pan Swing -", "Pan Swing", "Pan Swing +"
local SIZE_CUE = {2, 3, 4}             -- the FX buttons' cue per size (cue 1 = the press)
local AP_N = 6                         -- appearances: pos off / on, FX off / on, size idle / lit

-- the buttons: FS Presets' plan gives the preset numbers (made here when missing)
local function positionPresets(E)
  local made, foreign, _, recs = buildPresets(E, E.CFG.GROUPS, {pos = true, pfx = true}, false)
  local bad = {}
  for _, f in ipairs(foreign) do bad[f:match("^(Preset %d+%.%d+)")] = true end
  local at = {}  -- "pool:label" -> preset address
  for _, r in ipairs(recs) do
    if not bad[string.format("Preset %d.%d", r.pool, r.no)] then at[r.pool .. ":" .. r.label] = r.pool .. "." .. r.no end
  end
  local pans, tilts, fx = {}, {}, {}
  for _, p in ipairs(E.PANS) do
    if p[2] and at["2:" .. p[2]] then pans[#pans + 1] = {name = p[2], at = at["2:" .. p[2]]} end
  end
  for _, t in ipairs(E.TILTS) do
    if t[2] and at["2:" .. t[2]] then tilts[#tilts + 1] = {name = t[2], at = at["2:" .. t[2]], deg = t[3]} end
  end
  for _, v in ipairs(EXTRA_TILTS) do
    local name = "Tilt " .. v
    if at["2:" .. name] then tilts[#tilts + 1] = {name = name, at = at["2:" .. name], deg = v} end
  end
  table.sort(tilts, function(a, b) return a.deg < b.deg end)   -- back to front
  local ALL = 21
  local function addFx(name)
    local s = {}
    for k, tag in ipairs(SIZE_TAG) do s[k] = at[ALL .. ":" .. name .. tag] end
    if s[1] and s[2] and s[3] then fx[#fx + 1] = {name = name, at = s} end
  end
  for _, f in ipairs(E.PAN_FX) do if f[2] then addFx(f[2]) end end
  for _, f in ipairs(E.TILT_FX) do if f[2] and not f[2]:find("^Fly") then addFx(f[2]) end end
  return pans, tilts, fx, made, foreign
end

local NMX = #MX + 1  -- MAtricks buttons per row (all of them on the FX rows + the positions' own Fade)

local function ask(E, nBtn)
  local groups = defaultGroups(E, VARP .. "groups")
  local rows = #parseGroups(groups)
  local function def(k, kind, n, from)
    local v = tonumber(gvar(k) or "")
    return tostring(v or freeBlock(E, kind, n, from))
  end
  local r = MessageBox({
    title = TITLE,
    message = "Groups for the picker rows (up to 20), e.g. 1 Thru 8 or 1,2,5. An ALL row goes on top.\n" ..
              "The numbers below are where the layout, its button sequences, macros and appearances go\n" ..
              string.format("(%d sequences per group row + %d for ALL, %d macros + 3 per group row, %d appearances,\n" ..
                            "one MAtricks per group row). Speed master: the one the position FX follow (0 = none).", nBtn + NMX, NMX, nBtn + 4, AP_N),
    commands = {{value = 1, name = "Build"}, {value = 0, name = "Cancel"}},
    inputs = {
      {name = "Groups", value = groups, whiteFilter = "0123456789 ,+-ThruTHRU"},
      {name = "Layout", value = def("layout", "Layout", 1, 1), whiteFilter = "0123456789"},
      {name = "First sequence", value = def("seq", "Sequence", rows * (nBtn + NMX) + NMX, 101), whiteFilter = "0123456789"},
      {name = "First macro", value = def("macro", "Macro", nBtn + 4 * (rows + 1), 101), whiteFilter = "0123456789"},
      {name = "First appearance", value = def("ap", "Appearance", AP_N, 101), whiteFilter = "0123456789"},
      {name = "First MAtricks", value = def("mtx", "MAtricks", rows, 1), whiteFilter = "0123456789"},
      {name = "Speed master", value = tostring(tonumber(gvar("speed") or "") or 2), whiteFilter = "0123456789"},
    },
  })
  if not r or r.result ~= 1 then return nil end
  local i = r.inputs or {}
  return parseGroups(i["Groups"]), tonumber(i["Layout"] or ""), tonumber(i["First sequence"] or ""),
         tonumber(i["First macro"] or ""), tonumber(i["First appearance"] or ""), tonumber(i["First MAtricks"] or ""),
         tonumber(i["Speed master"] or "") or 0
end

local function buildPicker(E, groups, L, seq0, M0, ap0, mx0, speed)
  E.failures = {}
  E.CFG.GROUPS = groups
  local pans, tilts, fx, madeP, foreign = positionPresets(E)
  -- the columns: {kind, item, col}
  local cols, c = {}, 1
  for _, p in ipairs(pans) do cols[#cols + 1] = {kind = "pos", fam = "pan", item = p, col = c} c = c + 1 end
  c = c + 0.25
  for _, t in ipairs(tilts) do cols[#cols + 1] = {kind = "pos", fam = "tilt", item = t, col = c} c = c + 1 end
  c = c + 0.25
  -- the FX get their own section below the positions (Lyn: one long row was too wide),
  -- with Small / Mid / Big and the MAtricks buttons after them
  local FXB = #groups + 1.5  -- the FX section's ALL row
  local fadeCol = c + 0.25  -- Fade at the end of the pan / tilt rows
  c = 2  -- (column 1: the row's FX Off)
  for _, f in ipairs(fx) do cols[#cols + 1] = {kind = "fx", fam = "fx", item = f, col = c, base = FXB} c = c + 1 end
  local sizeCol = c + 0.25
  local nB = #cols
  local names = {}
  for gi, g in ipairs(groups) do names[gi] = tostring(E.objName(E.obj("Group " .. g)) or ("Group " .. g)) end
  -- refuse to overwrite anything that isn't ours
  local nM = nB + 4 * (#groups + 1)  -- (ALL buttons, Small / Mid / Big and Off per row + ALL)
  local clash = {}
  if not mine(E, "Layout", L) then clash[#clash + 1] = "Layout " .. L end
  local nSeq = #groups * nB + (#groups + 1) * NMX
  for k = seq0, seq0 + nSeq - 1 do if not mine(E, "Sequence", k) then clash[#clash + 1] = "Sequence " .. k end end
  for k = M0, M0 + nM - 1 do if not mine(E, "Macro", k) then clash[#clash + 1] = "Macro " .. k end end
  for k = ap0, ap0 + AP_N - 1 do if not mine(E, "Appearance", k) then clash[#clash + 1] = "Appearance " .. k end end
  for k = mx0, mx0 + #groups - 1 do if not mine(E, "MAtricks", k) then clash[#clash + 1] = "MAtricks " .. k end end
  if #clash > 0 then
    return nil, "These are already used by something else:\n  " .. table.concat(clash, "\n  ", 1, math.min(#clash, 10)) ..
      (#clash > 10 and "\n  ..." or "") .. "\n\nPick other numbers and run it again."
  end
  local P = E.CFG.PREFIX .. " " .. TAG .. " "
  local AP = {posOff = ap0, posOn = ap0 + 1, fxOff = ap0 + 2, fxOn = ap0 + 3, idle = ap0 + 4, lit = ap0 + 5}
  appearance(E, AP.posOff, P .. "position off", {40, 48, 64})
  appearance(E, AP.posOn, P .. "position on", {90, 150, 255})
  appearance(E, AP.fxOff, P .. "FX off", {56, 40, 64})
  appearance(E, AP.fxOn, P .. "FX on", {190, 90, 255})
  appearance(E, AP.idle, P .. "size idle", {60, 60, 60})
  appearance(E, AP.lit, P .. "size lit", {220, 220, 220})
  -- the layout: emptied and refilled on a rebuild
  if not E.obj("Layout " .. L) then E.C("Store Layout %d", L) end
  pcall(function() local lh = E.obj("Layout " .. L) for i = lh:Count(), 1, -1 do lh:Delete(i) end end)
  E.C("Label Layout %d %s", L, E.q(P .. "Position Picker"))
  local function sizeVar(gi) return string.format("%sL%d_g%d_size", VARP, L, gi) end
  local function actVar(gi) return string.format("%sL%d_g%d_act", VARP, L, gi) end
  local seq, bySeq = seq0, {}
  -- MA's Off When Overridden didn't switch the other buttons of a row off
  -- (Lyn's test 2026-11-16), so every button's cue switches off the rest of
  -- its family in that row (pans / tilts / FX) itself.
  local function offOthers(rowSeq0, me, fam)
    local t = {}
    for bi, b in ipairs(cols) do
      local s = rowSeq0 + bi - 1
      if b.fam == fam and s ~= me then t[#t + 1] = s end
    end
    return #t > 0 and ("Off Sequence " .. E.rangeList(t)) or nil
  end
  local function join(a, b) return (a and b and b ~= "") and (a .. "; " .. b) or a or b end
  for gi = 1, #groups do makeMatricks(E, mx0 + gi - 1, P .. names[gi]) end
  for gi, g in ipairs(groups) do
    local rowSeq0 = seq
    local mtx = mx0 + gi - 1
    place(E, L, "Group " .. g, 0, gi, names[gi])  -- the group itself, with its name: tap to select it
    place(E, L, "Group " .. g, 0, FXB + gi, names[gi])
    for bi, b in ipairs(cols) do
      local label = P .. names[gi] .. " " .. b.item.name
      if b.kind == "pos" then
        -- cue 1 = the look (it fades with the row's Fade); cue 2 follows once it has faded in and
        -- switches the rest of the family off then (Lyn: switching them off at once made it fade from 0)
        buttonSeq(E, seq, label, g, AP.posOff, {{b.item.at, AP.posOn, ""},
                                                {b.item.at, AP.posOn, offOthers(rowSeq0, seq, b.fam) or "", follow = true}}, mtx)
      else
        local keep = join(offOthers(rowSeq0, seq, b.fam), setVarCmd(E, actVar(gi), "Goto Sequence " .. seq .. " Cue 1"))
        buttonSeq(E, seq, label .. " FX", g, AP.fxOff, {
          {b.item.at[2], AP.fxOn, string.format("Goto Sequence %d Cue $%s", seq, sizeVar(gi))},
          {b.item.at[1], AP.fxOn, keep},
          {b.item.at[2], AP.fxOn, keep},
          {b.item.at[3], AP.fxOn, keep},
        }, mtx)
        if speed > 0 then E.trySeqMaster(seq, "SpeedMaster", "Speed", speed) end
      end
      place(E, L, "Sequence " .. seq, b.col, (b.base or 0) + gi, b.item.name, true)
      bySeq[bi] = bySeq[bi] or {}
      table.insert(bySeq[bi], seq)
      seq = seq + 1
    end
    SetVar(GlobalVars(), sizeVar(gi), tostring(SIZE_CUE[2]))
    -- no FX picked yet: replaying is harmless
    SetVar(GlobalVars(), actVar(gi), "Off Sequence " .. (seq - 1))
  end
  -- the ALL row on top: macros that start each group row's button in that column
  local M = M0
  for bi, b in ipairs(cols) do
    local l = {}
    for _, sq in ipairs(bySeq[bi] or {}) do l[#l + 1] = "Goto Sequence " .. sq .. " Cue 1" end
    macro(E, M, P .. "ALL " .. b.item.name .. (b.kind == "fx" and " FX" or ""), l, b.kind == "fx" and AP.fxOn or AP.posOn)
    place(E, L, "Macro " .. M, b.col, b.base or 0, b.item.name)
    M = M + 1
  end
  -- Small / Mid / Big per group row (4 lines) and for ALL (every row)
  local rowSize = {}
  for gi = 1, #groups do
    rowSize[gi] = {}
    for t = 1, 3 do rowSize[gi][t] = M + (gi - 1) * 3 + (t - 1) end
  end
  local allSize = {M + #groups * 3, M + #groups * 3 + 1, M + #groups * 3 + 2}
  local function lightLines(l, sets, t)
    local lit, idle = {}, {}
    for _, ms in ipairs(sets) do
      for k = 1, 3 do table.insert(k == t and lit or idle, ms[k]) end
    end
    l[#l + 1] = string.format("Assign Appearance %d At Macro %s", AP.lit, E.rangeList(lit))
    l[#l + 1] = string.format("Assign Appearance %d At Macro %s", AP.idle, E.rangeList(idle))
    return l
  end
  for gi = 1, #groups do
    for t = 1, 3 do
      local l = {setVarCmd(E, sizeVar(gi), tostring(SIZE_CUE[t]))}
      lightLines(l, {rowSize[gi]}, t)
      l[#l + 1] = "$" .. actVar(gi)
      macro(E, rowSize[gi][t], P .. names[gi] .. " FX " .. SIZES[t], l, t == 2 and AP.lit or AP.idle)
      place(E, L, "Macro " .. rowSize[gi][t], sizeCol + t - 1, FXB + gi, SIZES[t])
    end
  end
  for t = 1, 3 do
    local l = {}
    for gi = 1, #groups do l[#l + 1] = setVarCmd(E, sizeVar(gi), tostring(SIZE_CUE[t])) end
    local sets = {allSize}
    for gi = 1, #groups do sets[#sets + 1] = rowSize[gi] end
    lightLines(l, sets, t)
    for gi = 1, #groups do l[#l + 1] = "$" .. actVar(gi) end
    macro(E, allSize[t], P .. "ALL FX " .. SIZES[t], l, t == 2 and AP.lit or AP.idle)
    place(E, L, "Macro " .. allSize[t], sizeCol + t - 1, FXB, SIZES[t])
  end
  -- FX Off at the start of each FX row (and ALL): switches the row's FX off and points its replay
  -- variable at that Off, so Small / Mid / Big don't start an FX again (Lyn 2026-11-16)
  local offM = allSize[3] + 1
  local fxSeqs = {}
  for bi, b in ipairs(cols) do if b.fam == "fx" then for gi, sq in ipairs(bySeq[bi]) do
    fxSeqs[gi] = fxSeqs[gi] or {}
    table.insert(fxSeqs[gi], sq)
  end end end
  local allOff = {}
  for gi = 1, #groups do
    local off = "Off Sequence " .. E.rangeList({table.unpack(fxSeqs[gi] or {})})
    macro(E, offM + gi - 1, P .. names[gi] .. " FX Off", {off, setVarCmd(E, actVar(gi), off)}, AP.fxOff)
    place(E, L, "Macro " .. (offM + gi - 1), 1, FXB + gi, "Off")
    allOff[#allOff + 1] = "Go+ Macro " .. (offM + gi - 1)
  end
  local allOffM = offM + #groups
  macro(E, allOffM, P .. "ALL FX Off", allOff, AP.fxOff)
  place(E, L, "Macro " .. allOffM, 1, FXB, "Off")
  -- the MAtricks buttons (lib picker): after Small / Mid / Big on the FX rows
  seq = mxButtons(E, {L = L, n = #groups, names = names, mx0 = mx0, seq0 = seq, col = sizeCol + 3.25,
                      row = function(r) return FXB + r end, P = P, AP = AP,
                      list = mxList("Wings", "Sym", "Groups", "Blocks", "Phase", "Fade", "Delay", "Speed"),
                      rate = function(r) local l = {} for _, sq in ipairs(fxSeqs[r] or {}) do l[#l + 1] = {sq, 4} end return l end})
  -- and Fade at the end of the pan / tilt rows (Lyn: a fade for the position changes, separate
  -- from the FX one): the cue fade of the row's pan / tilt buttons
  local posSeqs = {}
  for gi = 1, #groups do
    local t = {}
    for bi, b in ipairs(cols) do if b.kind == "pos" then t[#t + 1] = bySeq[bi][gi] end end
    posSeqs[gi] = E.rangeList(t)
  end
  seq = mxButtons(E, {L = L, n = #groups, names = names, mx0 = mx0, seq0 = seq, col = fadeCol,
                      row = function(r) return r end, P = P, AP = AP, list = mxList("Fade"),
                      cueFade = function(row) return {posSeqs[row]} end})
  E.C("ClearAll")
  svar("mtx", mx0) svar("speed", speed)
  svar("groups", E.rangeList({table.unpack(groups)})) svar("layout", L) svar("seq", seq0) svar("macro", M0) svar("ap", ap0)
  local lines = {string.format("Layout %d: ALL + %d group rows x (%d pans, %d tilts, %d FX) + Small / Mid / Big " ..
    "+ MAtricks (Sequences %d-%d, Macros %d-%d, Appearances %d-%d, MAtricks %d-%d).", L, #groups, #pans, #tilts, #fx,
    seq0, seq - 1, M0, allOffM, ap0, ap0 + AP_N - 1, mx0, mx0 + #groups - 1)}
  if madeP > 0 then lines[#lines + 1] = string.format("%d missing position presets were made.", madeP) end
  if #foreign > 0 then
    lines[#lines + 1] = "\nSkipped buttons whose preset slot holds something else:"
    for i = 1, math.min(#foreign, 8) do lines[#lines + 1] = "  " .. foreign[i] end
  end
  return lines
end

local function main(displayHandle, argument)
  if not env then
    local ok, E = pcall(build)
    if not ok then return say(tostring(E)) end
    env = E
  end
  local E = env
  -- (12 pans + 15 tilts + 8 FX: the count for the dialog; the build counts what it really finds)
  local groups, L, seq0, M0, ap0, mx0, speed = ask(E, 35)
  if not groups then return end
  local good = {}
  for _, g in ipairs(groups) do if E.obj("Group " .. g) then good[#good + 1] = g end end
  if #good == 0 then return say("None of those groups exist yet. Store your groups first, then run " .. TITLE .. " again.") end
  if #good > MAX_GROUPS then return say("Pick up to " .. MAX_GROUPS .. " groups.") end
  if not (L and seq0 and M0 and ap0 and mx0) then return say("Fill in the layout, first sequence, macro, appearance and MAtricks numbers.") end
  local ok, lines, err = pcall(buildPicker, E, good, L, seq0, M0, ap0, mx0, speed)
  pcall(Cmd, "ClearAll")
  if not ok then return say("Stopped: " .. tostring(lines)) end
  if not lines then return say(err) end
  if #good < #groups then lines[#lines + 1] = "Skipped groups that don't exist." end
  if #E.failures > 0 then
    lines[#lines + 1] = string.format("\n%d commands failed, first: %s", #E.failures, E.failures[1])
    for _, f in ipairs(E.failures) do Printf(TITLE .. ": " .. f) end
  end
  say(table.concat(lines, "\n"))
  pcall(Cmd, "Select Layout " .. L)
end

return rerunnable(main)
