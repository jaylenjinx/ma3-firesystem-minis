--[[
  FSColourPicker.lua  -  "FS Colour Picker": builds a colour picker layout, nothing else
  ------------------------------------------------------------------------
  One of the single-purpose FireSystem tools. Run it (click it in the Plugins pool) and it asks for
  the groups and the pool numbers, then builds a layout with one row per group (plus an ALL row on
  top) and one button per colour. The show doesn't need the plugin afterwards. An ALL button is a
  macro that fires that colour's button on every group row (Go+ each sequence), so the group rows
  show what's on.

  Each button is a sequence (Lyn's way): its cue 1 holds a recipe line, Group <g> At the colour
  preset, so editing the group or the preset changes the button too. The sequence carries the
  dim "off" appearance and its cue 1 the bright "on" one, with Prefer Cue Appearance, so a button
  lights while its sequence runs. Off When Overridden makes a row behave like radio buttons: the
  next colour on that group takes over and the old one goes off.

  Each button sequence has 4 cues: cue 1 is the press (its command jumps to the row's tint cue via a
  global variable), cues 2 / 3 / 4 are Pastel / Dark / Normal, each with its own swatch. A button
  toggles (a second tap switches it off). Normal / Pastel / Dark at the end of each row (and of the
  ALL row) are short macros: set the row's tint variable, light the tint button, and replay the
  row's last colour (each tint cue keeps "Goto Sequence <n> Cue 1" in a second variable).

  The colour presets are FS Presets' own (Color 4.1-15, made here if they're missing), so FS
  Presets and FS Colour Picker can be run in either order.

  ONE FILE, NO OTHER PLUGIN NEEDED: plugins/FSColourPicker.lua is generated by tools/make_tools.py
  from this source, the shared tool code in src/lib/ and a copy of the FireSystem
  module files. Edit those, then run `python3 tools/make_tools.py`.
--]]

local TITLE = "FS Colour Picker"
local TAG = "CP"  -- names: "FS CP ..." (what a rebuild may replace)
local VARP = "FSC_"  -- this tool's global variables

--@INCLUDE common@
--@INCLUDE presets@

local OFF_DIM = 0.25        -- the off appearance: the colour at 25 %
local TINTS = {"Normal", "Pastel", "Dark"}

--@INCLUDE picker@

local function ask(E, nCols)
  local groups = defaultGroups(E, "FSC_groups")
  local rows = #parseGroups(groups)
  local function def(k, kind, n, from)
    local v = tonumber(gvar(k) or "")
    return tostring(v or freeBlock(E, kind, n, from))
  end
  local r = MessageBox({
    title = TITLE,
    message = "Groups for the picker rows (up to 20), e.g. 1 Thru 8 or 1,2,5. An ALL row goes on top.\n" ..
              "The numbers below are where the layout, its button sequences, macros and appearances go\n" ..
              string.format("(%d sequences per group row + 1, %d macros + 3 per group row, %d appearances, one MAtricks per group row).",
                            nCols + 1, nCols + 3, 4 * nCols + 2),
    commands = {{value = 1, name = "Build"}, {value = 0, name = "Cancel"}},
    inputs = {
      {name = "Groups", value = groups, whiteFilter = "0123456789 ,+-ThruTHRU"},
      {name = "Layout", value = def("layout", "Layout", 1, 1), whiteFilter = "0123456789"},
      {name = "First sequence", value = def("seq", "Sequence", rows * (nCols + 1) + 1, 101), whiteFilter = "0123456789"},
      {name = "First macro", value = def("macro", "Macro", nCols + 3 * (rows + 1), 101), whiteFilter = "0123456789"},
      {name = "First appearance", value = def("ap", "Appearance", 4 * nCols + 2, 101), whiteFilter = "0123456789"},
      {name = "First MAtricks", value = def("mtx", "MAtricks", rows, 1), whiteFilter = "0123456789"},
    },
  })
  if not r or r.result ~= 1 then return nil end
  local i = r.inputs or {}
  return parseGroups(i["Groups"]), tonumber(i["Layout"] or ""), tonumber(i["First sequence"] or ""),
         tonumber(i["First macro"] or ""), tonumber(i["First appearance"] or ""), tonumber(i["First MAtricks"] or "")
end


local function buildPicker(E, groups, L, seq0, M0, ap0, mx0)
  E.failures = {}
  E.CFG.GROUPS = groups
  local cols, madeP, foreign = colourPresets(E)
  local nC = #cols
  local names = {}
  for gi, g in ipairs(groups) do names[gi] = tostring(E.objName(E.obj("Group " .. g)) or ("Group " .. g)) end
  -- refuse to overwrite anything that isn't ours
  local clash = {}
  if not mine(E, "Layout", L) then clash[#clash + 1] = "Layout " .. L end
  for k = seq0, seq0 + #groups * (nC + 1) do if not mine(E, "Sequence", k) then clash[#clash + 1] = "Sequence " .. k end end
  for k = M0, M0 + nC + 3 * (#groups + 1) - 1 do if not mine(E, "Macro", k) then clash[#clash + 1] = "Macro " .. k end end
  for k = ap0, ap0 + 4 * nC + 1 do if not mine(E, "Appearance", k) then clash[#clash + 1] = "Appearance " .. k end end
  for k = mx0, mx0 + #groups - 1 do if not mine(E, "MAtricks", k) then clash[#clash + 1] = "MAtricks " .. k end end
  if #clash > 0 then
    return nil, "These are already used by something else:\n  " .. table.concat(clash, "\n  ", 1, math.min(#clash, 10)) ..
      (#clash > 10 and "\n  ..." or "") .. "\n\nPick other numbers and run it again."
  end
  local P = E.CFG.PREFIX .. " " .. TAG .. " "
  -- appearances: per colour off, on (Normal), on (Pastel), on (Dark); then the tint buttons idle / lit
  local function apC(ci, k) return ap0 + 4 * (ci - 1) + k end  -- k: 0 off, 1-3 on in tint 1-3
  local apIdle, apLit = ap0 + 4 * nC, ap0 + 4 * nC + 1
  for ci, c in ipairs(cols) do
    local function rgb255(t) return {math.floor(t[1] * 2.55 + 0.5), math.floor(t[2] * 2.55 + 0.5), math.floor(t[3] * 2.55 + 0.5)} end
    local on = rgb255(c.rgb)
    appearance(E, apC(ci, 0), P .. c.name .. " off", {math.floor(on[1] * OFF_DIM), math.floor(on[2] * OFF_DIM), math.floor(on[3] * OFF_DIM)})
    appearance(E, apC(ci, 1), P .. c.name .. " on", on)
    appearance(E, apC(ci, 2), P .. c.name .. " Pastel on", rgb255(E.tintRGBW(c.rgb, 0, 1)))
    -- (the real Dark is 35 %: on a button that reads as off, so the swatch shows it at 55 %)
    appearance(E, apC(ci, 3), P .. c.name .. " Dark on", {math.floor(on[1] * .55), math.floor(on[2] * .55), math.floor(on[3] * .55)})
  end
  appearance(E, apIdle, P .. "tint idle", {60, 60, 60})
  appearance(E, apLit, P .. "tint lit", {220, 220, 220})
  -- the layout: emptied and refilled on a rebuild
  if not E.obj("Layout " .. L) then E.C("Store Layout %d", L) end
  pcall(function() local lh = E.obj("Layout " .. L) for i = lh:Count(), 1, -1 do lh:Delete(i) end end)
  E.C("Label Layout %d %s", L, E.q(P .. "Colour Picker"))
  -- per group row: the tint (the cue number a press jumps to: 4 Normal, 2 Pastel, 3 Dark) and a
  -- variable holding the command that replays the row's colour (its last pick)
  local TINT_CUE = {4, 2, 3}
  local function tintVar(gi) return string.format("FSC_L%d_g%d_tint", L, gi) end
  local function actVar(gi) return string.format("FSC_L%d_g%d_act", L, gi) end
  -- each row's own MAtricks (for its Fade button): every recipe line of the row points at it
  for gi = 1, #groups do makeMatricks(E, mx0 + gi - 1, P .. names[gi]) end
  local seq, bySeq = seq0, {}
  for gi, g in ipairs(groups) do
    place(E, L, "Group " .. g, 0, gi, names[gi])  -- the group itself, with its name: tap to select it
    for ci, c in ipairs(cols) do
      if not c.foreign then
        local keep = setVarCmd(E, actVar(gi), "Goto Sequence " .. seq .. " Cue 1")
        buttonSeq(E, seq, P .. names[gi] .. " " .. c.name, g, apC(ci, 0), {
          {"4." .. c.no[1], apC(ci, 1), string.format("Goto Sequence %d Cue $%s", seq, tintVar(gi))},
          {"4." .. c.no[2], apC(ci, 2), keep},
          {"4." .. c.no[3], apC(ci, 3), keep},
          {"4." .. c.no[1], apC(ci, 1), keep},
        }, mx0 + gi - 1)
        place(E, L, "Sequence " .. seq, ci, gi, nil, true)
        bySeq[ci] = bySeq[ci] or {}
        table.insert(bySeq[ci], seq)
      end
      seq = seq + 1
    end
    SetVar(GlobalVars(), tintVar(gi), "4")
    -- no colour picked yet: replaying is harmless
    SetVar(GlobalVars(), actVar(gi), "Off Sequence " .. (seq - 1))
  end
  -- the ALL row on top: macros that start each group row's button of that colour (in its tint)
  local M = M0
  for ci, c in ipairs(cols) do
    if bySeq[ci] then
      local l = {}
      for _, sq in ipairs(bySeq[ci]) do l[#l + 1] = "Goto Sequence " .. sq .. " Cue 1" end
      macro(E, M, P .. "ALL " .. c.name, l, apC(ci, 1))
      place(E, L, "Macro " .. M, ci, 0, c.name)
    end
    M = M + 1
  end
  -- Normal / Pastel / Dark per group row: set the row's tint, light the tint button, replay the
  -- row's colour (4 lines). The ALL row's set every row's tint, light every tint button (2 lines)
  -- and replay every row
  local tintCol = nC + 1.25
  local rowTint = {}
  for gi = 1, #groups do
    rowTint[gi] = {}
    for t = 1, 3 do rowTint[gi][t] = M + (gi - 1) * 3 + (t - 1) end
  end
  local allTint = {M + #groups * 3, M + #groups * 3 + 1, M + #groups * 3 + 2}
  -- two lines light a set of tint buttons: lit = tint t's, idle = the others (lists of rows of 3)
  local function lightLines(l, sets, t)
    local lit, idle = {}, {}
    for _, ms in ipairs(sets) do
      for k = 1, 3 do table.insert(k == t and lit or idle, ms[k]) end
    end
    l[#l + 1] = string.format("Assign Appearance %d At Macro %s", apLit, E.rangeList(lit))
    l[#l + 1] = string.format("Assign Appearance %d At Macro %s", apIdle, E.rangeList(idle))
    return l
  end
  for gi = 1, #groups do
    for t = 1, 3 do
      local l = {setVarCmd(E, tintVar(gi), tostring(TINT_CUE[t]))}
      lightLines(l, {rowTint[gi]}, t)
      l[#l + 1] = "$" .. actVar(gi)
      macro(E, rowTint[gi][t], P .. names[gi] .. " " .. TINTS[t], l, t == 1 and apLit or apIdle)
      place(E, L, "Macro " .. rowTint[gi][t], tintCol + t - 1, gi, TINTS[t])
    end
  end
  for t = 1, 3 do
    local l = {}
    for gi = 1, #groups do l[#l + 1] = setVarCmd(E, tintVar(gi), tostring(TINT_CUE[t])) end
    local sets = {allTint}
    for gi = 1, #groups do sets[#sets + 1] = rowTint[gi] end
    lightLines(l, sets, t)
    for gi = 1, #groups do l[#l + 1] = "$" .. actVar(gi) end
    macro(E, allTint[t], P .. "ALL " .. TINTS[t], l, t == 1 and apLit or apIdle)
    place(E, L, "Macro " .. allTint[t], tintCol + t - 1, 0, TINTS[t])
  end
  local lastM = allTint[3]
  -- Fade (lib picker MAtricks button) after Normal / Pastel / Dark: the colour changes fade
  seq = mxButtons(E, {L = L, n = #groups, names = names, mx0 = mx0, seq0 = seq, col = tintCol + 3.25,
                      row = function(r) return r end, P = P, AP = {idle = apIdle, lit = apLit}, list = mxList("Fade")})
  E.C("ClearAll")
  svar("mtx", mx0)
  svar("groups", E.rangeList({table.unpack(groups)})) svar("layout", L) svar("seq", seq0) svar("macro", M0) svar("ap", ap0)
  local lines = {string.format("Layout %d: ALL + %d group rows x %d colours + Normal / Pastel / Dark + Fade (Sequences %d-%d, Macros %d-%d, Appearances %d-%d, MAtricks %d-%d).",
    L, #groups, nC, seq0, seq - 1, M0, lastM, ap0, apLit, mx0, mx0 + #groups - 1)}
  if madeP > 0 then lines[#lines + 1] = string.format("%d missing colour presets were made (Color 4.x).", madeP) end
  if #foreign > 0 then
    lines[#lines + 1] = "\nSkipped colours whose preset slot holds something else:"
    for i = 1, math.min(#foreign, 8) do lines[#lines + 1] = "  " .. foreign[i] end
  end
  return lines
end

local function main(displayHandle, argument)
  if not env then
    local ok, E = pcall(build)
    if not ok then return say(tostring(E)) end
    env = E
  end
  local E = env
  local groups, L, seq0, M0, ap0, mx0 = ask(E, #E.CFG.COLORS)
  if not groups then return end
  local good = {}
  for _, g in ipairs(groups) do if E.obj("Group " .. g) then good[#good + 1] = g end end
  if #good == 0 then return say("None of those groups exist yet. Store your groups first, then run " .. TITLE .. " again.") end
  if #good > MAX_GROUPS then return say("Pick up to " .. MAX_GROUPS .. " groups.") end
  if not (L and seq0 and M0 and ap0 and mx0) then return say("Fill in the layout, first sequence, macro, appearance and MAtricks numbers.") end
  local ok, lines, err = pcall(buildPicker, E, good, L, seq0, M0, ap0, mx0)
  pcall(Cmd, "ClearAll")
  if not ok then return say("Stopped: " .. tostring(lines)) end
  if not lines then return say(err) end
  if #good < #groups then lines[#lines + 1] = "Skipped groups that don't exist." end
  if #E.failures > 0 then
    lines[#lines + 1] = string.format("\n%d commands failed, first: %s", #E.failures, E.failures[1])
    for _, f in ipairs(E.failures) do Printf(TITLE .. ": " .. f) end
  end
  say(table.concat(lines, "\n"))
  pcall(Cmd, "Select Layout " .. L)
end

return rerunnable(main)
