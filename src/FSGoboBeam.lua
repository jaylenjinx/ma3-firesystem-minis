--[[
  FSGoboBeam.lua  -  "FS Gobo & Beam": builds a gobo / prism / zoom / focus picker layout, nothing else
  ------------------------------------------------------------------------
  One of the single-purpose FireSystem tools. Run it (click it in the Plugins pool) and it asks for
  the groups and the pool numbers, then builds a layout with an ALL row and one row per group:

    [group] [Gobo 1] [Gobo Spin] [Gobo 2] [Prism] [Prism Spin] [Shutter] [Iris] [Frost] [Zoom] [Focus] [Fade]

  Each picker is ONE button (Lyn 2026-11-16, as the Colour FX STEP pickers): a sequence with a cue
  per choice, and a tap opens MA's Goto list to pick one (turn on "Cue Appearance" in the list's
  title bar to see the cues coloured). Cue 1 is Off (the sequence switches itself off); every other
  cue is a recipe line: Group + the row's MAtricks At the FS Presets preset. The button shows what
  is picked. The gobo / prism / shutter choices come from the group's own fixture type (its wheels
  and shutter channel), so a group with no gobo wheel gets no gobo button. Shutter = Open, Strobe,
  Pulse, Random (the ones the profile has); Iris and Frost = 0-100 % in steps of 10. The ALL row has
  Iris, Frost, Zoom and Focus (every group gets the same choice) and the Fade button; gobos, prisms
  and shutters differ per fixture type, so they have none.
  Gobo Spin / Prism Spin pick Stop, CW 1-3 or CCW 1-3 (the speeds come from the fixture profile, as
  FireSystem's rotate button). Each row has one MAtricks button, Fade (Lyn 2026-11-16: only Fade
  here), on the row's own MAtricks object: the changes fade in over 1 / 3 / 5 s.
  The show doesn't need the plugin afterwards.

  The presets are FS Presets' own (Gobo 3.x, Beam 5.x and their spin per fixture type, Focus 6.x, Zoom Sine in
  the All pool), made here if they're missing, so FS Presets and the pickers can be run in any order.

  ONE FILE, NO OTHER PLUGIN NEEDED: plugins/FSGoboBeam.lua is generated by tools/make_tools.py
  from this source, the shared tool code in src/lib/ and a copy of the FireSystem
  module files. Edit those, then run `python3 tools/make_tools.py`.
--]]

local TITLE = "FS Gobo & Beam"
local TAG = "GB"       -- names: "FS GB ..." (what a rebuild may replace)
local VARP = "FSGB_"   -- this tool's global variables

--@INCLUDE common@
--@INCLUDE presets@
--@INCLUDE picker@

-- the pickers: {button text, short text for the pick}; group rows have all, ALL has Zoom / Focus
local PICKS = { {"Gobo 1", "G1"}, {"Gobo Spin", "Spin"}, {"Gobo 2", "G2"}, {"Prism", "Prism"}, {"Prism Spin", "Spin"},
                {"Shutter", "Shutter"}, {"Iris", ""}, {"Frost", ""}, {"Zoom", ""}, {"Focus", ""} }
local WHEEL_PICK = {gobo1 = 1, gobo1rot = 2, gobo2 = 3, prism = 4, prismrot = 5, shutter = 6}
local IRIS, FROST, ZOOM, FOCUS = 7, 8, 9, 10
local NP = #PICKS
local ALL_PICKS = {IRIS, FROST, ZOOM, FOCUS}
local MXL = mxList("Fade")   -- (Lyn 2026-11-16: only Fade here)
local NMX = #MXL
local AP_N = 4   -- appearances: picker off / on, MAtricks idle / lit

-- the choices per picker: FS Presets' plan gives the preset numbers (made here when missing).
-- Returns choices(gi, p) -> {{name, at = "pool.no"}, ...}
local function beamPresets(E, groups)
  local made, foreign, _, recs = buildPresets(E, groups, {gobo = true, zoom = true, rot = true, beam = true}, false)
  local bad = {}
  for _, f in ipairs(foreign) do bad[f:match("^(Preset %d+%.%d+)")] = true end
  local zoom, focus, iris, frost, typed = {}, {}, {}, {}, {}
  for _, r in ipairs(recs) do
    local at = r.pool .. "." .. r.no
    if not bad["Preset " .. at] then
      if r.wheel == "iris" or r.wheel == "frost" then
        table.insert(r.wheel == "iris" and iris or frost, {name = r.label, at = at})
      elseif r.fam == "zoom" then
        table.insert(r.label:find("^Focus") and focus or zoom, {name = r.label, at = at})
      elseif (r.fam == "gobo" or r.fam == "rot" or r.fam == "beam") and r.groups then
        local p = WHEEL_PICK[r.wheel]
        if p then
          for _, g in ipairs(r.groups) do
            local k = g .. ":" .. p
            typed[k] = typed[k] or {}
            table.insert(typed[k], {name = PICKS[p][2] .. " " .. r.slot, at = at})
          end
        end
      end
    end
  end
  local function choices(g, p)
    if p == IRIS then return iris end
    if p == FROST then return frost end
    if p == ZOOM then return zoom end
    if p == FOCUS then return focus end
    return typed[tostring(g) .. ":" .. p] or {}
  end
  return choices, made, foreign
end

local function ask(E)
  local groups = defaultGroups(E, VARP .. "groups")
  local rows = #parseGroups(groups)
  local function def(k, kind, n, from)
    local v = tonumber(gvar(k) or "")
    return tostring(v or freeBlock(E, kind, n, from))
  end
  local nSeq = rows * NP + #ALL_PICKS + (rows + 1) * NMX
  local r = MessageBox({
    title = TITLE,
    message = "Groups for the gobo / beam rows (up to 20), e.g. 1 Thru 8 or 1,2,5. An ALL row goes on top.\n" ..
              "The numbers below are where the layout and its sequences, appearances and MAtricks go\n" ..
              string.format("(%d sequences, %d appearances, %d MAtricks).", nSeq, AP_N, rows),
    commands = {{value = 1, name = "Build"}, {value = 0, name = "Cancel"}},
    states = {{name = ICON_BOX, state = gvar("icons") == "1"}},
    inputs = {
      {name = "Groups", value = groups, whiteFilter = "0123456789 ,+-ThruTHRU"},
      {name = "Layout", value = def("layout", "Layout", 1, 1), whiteFilter = "0123456789"},
      {name = "First sequence", value = def("seq", "Sequence", nSeq, 101), whiteFilter = "0123456789"},
      {name = "First appearance", value = def("ap", "Appearance", AP_N, 101), whiteFilter = "0123456789"},
      {name = "First MAtricks", value = def("mtx", "MAtricks", rows, 1), whiteFilter = "0123456789"},
    },
  })
  if not r or r.result ~= 1 then return nil end
  local i = r.inputs or {}
  local function n(k) return tonumber(i[k] or "") end
  return parseGroups(i["Groups"]), {icons = (r.states or {})[ICON_BOX] and true or false, L = n("Layout"), seq0 = n("First sequence"), ap0 = n("First appearance"),
    mx0 = n("First MAtricks")}
end

-- a picker: Sequence seq, cue 1 = Off (cmd offCmd), cue k + 1 = choice k as a recipe line (Group g
-- + MAtricks mtx At its preset; g = nil: an empty cue, the ALL pickers'); cmd(k) = cue k's command
-- (the caller has made the sequence fresh and placed it: deleting it here would take it off the layout)
local function pickSeq(E, seq, label, g, mtx, list, AP, cmd)
  for k = 1, #list + 1 do
    local c = list[k - 1]
    E.C("ClearAll")
    E.C("Store Sequence %d Cue %d /Overwrite", seq, k)
    E.C("Label Sequence %d Cue %d %s", seq, k, E.q(c and c.name or "Off"))
    if c and g then
      local a = string.format("Sequence %d Cue %d Part 0.1", seq, k)
      E.C('Store Type "StandardRecipe" %s', a)
      E.C("Assign Group %d At %s", g, a)
      E.C("Assign Preset %s At %s", c.at, a)
      E.C("Assign MAtricks %d At %s", mtx, a)
      E.C('Set %s Property "Enabled" "Yes"', a)
    end
    E.C("Assign Appearance %d At Sequence %d Cue %d", c and AP.on or AP.off, seq, k)
    E.Cany({ string.format("Assign Appearance %d At Sequence %d Cue %d Part 0", c and AP.on or AP.off, seq, k) })
    cueCmd(E, seq, k, cmd(k))
  end
  E.C("Label Sequence %d %s", seq, E.q(label))
  setProp(E, "Sequence " .. seq, "PreferCueAppearance", "Yes")
  E.C("Assign Appearance %d At Sequence %d", AP.off, seq)
end

local function buildGB(E, groups, o)
  local L, seq0, ap0, mx0 = o.L, o.seq0, o.ap0, o.mx0
  E.failures = {}
  E.CFG.GROUPS = groups
  local choices, madeP, foreign = beamPresets(E, groups)
  local names = {}
  for gi, g in ipairs(groups) do names[gi] = tostring(E.objName(E.obj("Group " .. g)) or ("Group " .. g)) end
  local nG = #groups
  local nSeq = nG * NP + #ALL_PICKS + (nG + 1) * NMX
  -- refuse to overwrite anything that isn't ours
  local clash = {}
  if not mine(E, "Layout", L) then clash[#clash + 1] = "Layout " .. L end
  for k = seq0, seq0 + nSeq - 1 do if not mine(E, "Sequence", k) then clash[#clash + 1] = "Sequence " .. k end end
  for k = ap0, ap0 + AP_N - 1 do if not mine(E, "Appearance", k) then clash[#clash + 1] = "Appearance " .. k end end
  for k = mx0, mx0 + nG - 1 do if not mine(E, "MAtricks", k) then clash[#clash + 1] = "MAtricks " .. k end end
  if #clash > 0 then
    return nil, "These are already used by something else:\n  " .. table.concat(clash, "\n  ", 1, math.min(#clash, 10)) ..
      (#clash > 10 and "\n  ..." or "") .. "\n\nPick other numbers and run it again."
  end
  local P = E.CFG.PREFIX .. " " .. TAG .. " "
  local AP = {off = ap0, on = ap0 + 1, idle = ap0 + 2, lit = ap0 + 3}
  appearance(E, AP.off, P .. "off", {40, 56, 72})
  appearance(E, AP.on, P .. "on", {90, 200, 255})
  appearance(E, AP.idle, P .. "idle", {60, 60, 60})
  appearance(E, AP.lit, P .. "lit", {220, 220, 220})
  if not E.obj("Layout " .. L) then E.C("Store Layout %d", L) end
  pcall(function() local lh = E.obj("Layout " .. L) for i = lh:Count(), 1, -1 do lh:Delete(i) end end)
  E.C("Label Layout %d %s", L, E.q(P .. "Gobo & Beam"))
  for gi = 1, nG do makeMatricks(E, mx0 + gi - 1, P .. names[gi]) end

  -- numbering: the group rows' pickers, then ALL's (Zoom, Focus), then the MAtricks buttons
  local function seqNo(b, p)
    if b > 0 then return seq0 + (b - 1) * NP + (p - 1) end
    for j, q in ipairs(ALL_PICKS) do if q == p then return seq0 + nG * NP + (j - 1) end end
  end
  local function textCmd(idx, text)
    return idx and string.format('Set Layout %d.%d Property "CustomTextText" %s', L, idx, E.q(text)) or nil
  end
  local function join(...) local t = {} for _, s in ipairs({...}) do if s and s ~= "" then t[#t + 1] = s end end return table.concat(t, "; ") end
  local made, skipped = 0, 0
  -- (the ALL pickers send every row's picker to the same cue: Zoom / Focus lists are the same on every row)
  for b = 0, nG do
    local all, g = b == 0, groups[b]
    if not all then place(E, L, "Group " .. g, 0, b, names[b]) end
    for p = 1, NP do
      local isAll = false
      for _, q in ipairs(ALL_PICKS) do if q == p then isAll = true end end
      if not all or isAll then
        local list = choices(all and groups[1] or g, p)
        if #list == 0 then
          skipped = skipped + 1
        else
          local sq = seqNo(b, p)
          -- the button first (its element number goes into the cue commands)
          local idx
          if E.obj("Sequence " .. sq) then E.C("Delete Sequence %d /NC", sq) end
          E.C("Store Sequence %d Cue 1 /Overwrite", sq)
          idx = place(E, L, "Sequence " .. sq, p, b, PICKS[p][1], "Goto")
          pickSeq(E, sq, P .. (all and "ALL" or names[b]) .. " " .. PICKS[p][1], (not all) and g or nil, mx0 + (b > 0 and b or 1) - 1,
            list, AP, function(k)
              local text = textCmd(idx, k == 1 and PICKS[p][1] or list[k - 1].name)
              if all then
                local l = {}
                for gi = 1, nG do l[#l + 1] = string.format("Goto Sequence %d Cue %d", seqNo(gi, p), k) end
                if k == 1 then l[#l + 1] = "Off Sequence " .. sq end
                return join(table.concat(l, "; "), text)
              end
              return join(k == 1 and ("Off Sequence " .. sq) or nil, text)
            end)
          made = made + 1
        end
      end
    end
  end
  -- the pickers start off
  for b = 0, nG do for p = 1, NP do
    local sq = seqNo(b, p)
    if sq and E.obj("Sequence " .. sq) then E.C("Off Sequence %d", sq) end
  end end
  -- the MAtricks buttons (lib picker)
  local seq = seq0 + nG * NP + #ALL_PICKS
  seq = mxButtons(E, {L = L, n = nG, names = names, mx0 = mx0, seq0 = seq, col = NP + 1.25,
                      row = function(r) return r end, P = P, AP = AP, list = MXL})
  E.C("ClearAll")
  svar("mtx", mx0) svar("groups", E.rangeList({table.unpack(groups)})) svar("layout", L) svar("seq", seq0) svar("ap", ap0)
  local lines = {string.format("Layout %d: ALL + %d group rows, %d pickers (Sequences %d-%d, Appearances %d-%d, MAtricks %d-%d).",
    L, nG, made, seq0, seq - 1, ap0, ap0 + AP_N - 1, mx0, mx0 + nG - 1),
    "Tap a picker to choose from its list (turn on Cue Appearance in the list's title bar to see them coloured)."}
  if skipped > 0 then lines[#lines + 1] = string.format("%d buttons left out: those groups' fixtures have no such wheel.", skipped) end
  if madeP > 0 then lines[#lines + 1] = string.format("%d missing presets were made.", madeP) end
  if #foreign > 0 then
    lines[#lines + 1] = "\nPresets in use by something else (left out of the lists):"
    for i = 1, math.min(#foreign, 8) do lines[#lines + 1] = "  " .. foreign[i] end
  end
  return lines
end

local function main(displayHandle, argument)
  if not env then
    local ok, E = pcall(build)
    if not ok then return say(tostring(E)) end
    env = E
  end
  local E = env
  local groups, o = ask(E)
  if not groups then return end
  local good = {}
  for _, g in ipairs(groups) do if E.obj("Group " .. g) then good[#good + 1] = g end end
  if #good == 0 then return say("None of those groups exist yet. Store your groups first, then run " .. TITLE .. " again.") end
  if #good > MAX_GROUPS then return say("Pick up to " .. MAX_GROUPS .. " groups.") end
  if not (o.L and o.seq0 and o.ap0 and o.mx0) then
    return say("Fill in the layout, first sequence, appearance and MAtricks numbers.")
  end
  iconsStart(E, o.icons)
  local ok, lines, err = pcall(buildGB, E, good, o)
  local iconNote = iconsFinish(E, ok and lines ~= nil)
  if iconNote and type(lines) == "table" then lines[#lines + 1] = iconNote end
  pcall(Cmd, "ClearAll")
  if not ok then return say("Stopped: " .. tostring(lines)) end
  if not lines then return say(err) end
  if #good < #groups then lines[#lines + 1] = "Skipped groups that don't exist." end
  if #E.failures > 0 then
    lines[#lines + 1] = string.format("\n%d commands failed, first: %s", #E.failures, E.failures[1])
    for _, f in ipairs(E.failures) do Printf(TITLE .. ": " .. f) end
  end
  say(table.concat(lines, "\n"))
  pcall(Cmd, "Select Layout " .. o.L)
end

return main
