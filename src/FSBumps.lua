--[[
  FSBumps.lua  -  "FS Bumps": bump, strobe and X-Key keys per group, like FireSystem's Bump page
  ------------------------------------------------------------------------
  One of the single-purpose FireSystem tools. Run it (click it in the Plugins pool) and it asks for
  the groups (up to 8) and the pool numbers, then builds a layout with an ALL row and one row per group:

    [group] [Bump] [Steps] [Strobe] [Rnd] [X-Key]   [Dim] [Color] [Gobo] [Prism] [Iris] [Shutter] [Zoom] [Pos]
            [Edit Step] [Step Count] [Hold] [Master]   [Part] [Fade] [Delay] [Wings] [Out]
            [X-Key pattern] [X-Key form]

  The keys (Temp: on while held; Steps is Go+):
  - Bump plays the row's bump look: one recipe line (the group At its own bump preset, an All-pool
    preset "FS BS Bump <group>" with a line per look family). The look pickers (Dim ... Pos) are Goto
    lists: picking an entry points that family's line of the preset at an FS Presets preset (Off
    empties it), so the key plays the new look straight away, even while held. Gobo / Prism /
    Shutter list the group's own fixture type's slots. The row's MAtricks (Part = All / Odd / Even /
    Left / Right / thirds, Delay, Wings) sit on the bump's line; Fade = the bump's fade in, Out = its
    release (OffCue) fade;
  - Steps (Go+): each press plays the row's next step (up to 3, Step Count), as FireSystem's Go+
    bumps: a step is its own sequence (cue 1 = the step's preset, which also says which step comes
    next; cue 2 follows after Hold and switches the step off over Out), so fast hits overlap. Edit
    Step picks which step's preset the look pickers change (step 1 = the Bump key's look). Master
    puts a group of your choice at Full with the bump and every step (e.g. the main fixtures of
    pixel cells), through a "Master" recipe line;
  - Strobe / Rnd: the group at Full with its strobe / random strobe (FS Presets' per-group strobe
    presets, from the fixture profile's shutter; LED fixtures get a dimmer chase);
  - X-Key: the group's dimmer chase (an FS Presets Dimmer FX form, Square 1 at first) with its own
    MAtricks, whose pattern (In, Random, Out, Odd/Even, Right, Blocks, Left, All) is picked with the
    X-Key pattern list; X-Key form picks the chase's shape. The chases follow a speed master;
  - the ALL row: Bump All / Strobe All / Rnd All / X-Key All play every row's key at once, and its
    pickers set every row.
  The show doesn't need the plugin afterwards.

  ONE FILE, NO OTHER PLUGIN NEEDED: plugins/FSBumps.lua is generated by tools/make_tools.py from this
  source, the shared tool code in src/lib/ and a copy of the FireSystem module files.
--]]

local TITLE = "FS Bumps"
local TAG = "BS"       -- names: "FS BS ..." (what a rebuild may replace)
local VARP = "FSBS_"   -- this tool's global variables

--@INCLUDE common@
--@INCLUDE presets@
--@INCLUDE picker@

-- the keys: {button text, kind}
local KEYS = { {"Bump", "bump"}, {"Steps", "steps"}, {"Strobe", "strobe"}, {"Rnd", "rnd"}, {"X-Key", "xk"} }
local J_BUMP, J_STEPS, J_XK = 1, 2, 5
-- the bump look families: {line name in the bump preset, button text}
local FAMS = { {"Dimmer", "Dim"}, {"Color", "Color"}, {"Gobo", "Gobo"}, {"Prism", "Prism"},
               {"Iris", "Iris"}, {"Shutter", "Shutter"}, {"Zoom", "Zoom"}, {"Position", "Pos"} }
-- Part: which part of the group the bump lights (X MAtricks; Left / Right = the group's halves)
local PARTS = { {"All"}, {"Odd", 2, 1}, {"Even", 2, 2}, {"Left", 2, 1, true}, {"Right", 2, 2, true},
                {"1/3", 3, 1}, {"2/3", 3, 2}, {"3/3", 3, 3} }
local OUTS = {0, 0.5, 1, 2}     -- release fades
local HOLDS = {0.2, 0.5, 1, 2}  -- how long a Go+ step stays on before it releases itself
local NSTEP = 3                 -- Go+ steps per group
local STRIDE = 8                -- bump presets: step k of group gi = first + (k - 1) * 8 + gi - 1
-- per row: the keys, the 8 look pickers, Part, X-Key pattern, X-Key form, Out, Edit Step, Step
-- Count, Master, Hold, then the 3 step sequences (played by the Steps key, not on the layout)
local J0 = #KEYS + #FAMS
local J_PART, J_PAT, J_FORM, J_OUT = J0 + 1, J0 + 2, J0 + 3, J0 + 4
local J_EDIT, J_CNT, J_MST, J_HOLD = J0 + 5, J0 + 6, J0 + 7, J0 + 8
local J_STEP1 = J0 + 9   -- J_STEP1 .. J_STEP1 + NSTEP - 1
local NPR = J0 + 8 + NSTEP
local MXL = mxList("Fade", "Delay", "Wings")
local MXV = {Fade = {"Off", 0.2, 0.5, 1}, Delay = {"Off", 0.25, 0.5, 1}, Wings = {"Off", 2, 4}}
local NMX = #MXL
local AP_N = 7   -- appearances (+ one per colour): key, strobe key, picker off / on, idle, lit, X-Key
local COL = {keys = 1, looks = 6.25, edit = 14.5, cnt = 15.5, hold = 16.5, mst = 17.5, part = 18.75, mx = 19.75,
             out = 22.75, pat = 24, form = 25}

local function minePreset(E, no)
  local h = E.obj("Preset 21." .. no)
  if not h then return true end
  return tostring(E.objName(h) or ""):find("^" .. E.CFG.PREFIX .. " " .. TAG .. " ") ~= nil
end

local function ask(E, nC)
  local groups = defaultGroups(E, VARP .. "groups")
  local rows = #parseGroups(groups)
  local function def(k, kind, n, from)
    local v = tonumber(gvar(k) or "")
    return tostring(v or freeBlock(E, kind, n, from))
  end
  local nSeq = (rows + 1) * (NPR + NMX)
  local pre = tonumber(gvar("preset") or "")
  if not pre then pre = 911 while pre < 9970 and not (minePreset(E, pre) and minePreset(E, pre + NSTEP * STRIDE - 1)) do pre = pre + 1 end end
  local r = MessageBox({
    title = TITLE,
    message = "Groups for the bump rows (up to 8), e.g. 1 Thru 8 or 1,2,5. An ALL row goes on top.\n" ..
              "The numbers below are where the layout, its sequences, appearances, MAtricks and the bump presets\n" ..
              string.format("(All pool, 3 steps per group) go: %d sequences, %d appearances, %d MAtricks.\n", nSeq, AP_N + nC, 2 * rows) ..
              "Speed master: the one the X-Key chases follow (0 = none).",
    commands = {{value = 1, name = "Build"}, {value = 0, name = "Cancel"}},
    inputs = {
      {name = "Groups", value = groups, whiteFilter = "0123456789 ,+-ThruTHRU"},
      {name = "Layout", value = def("layout", "Layout", 1, 1), whiteFilter = "0123456789"},
      {name = "First sequence", value = def("seq", "Sequence", nSeq, 101), whiteFilter = "0123456789"},
      {name = "First appearance", value = def("ap", "Appearance", AP_N + nC, 101), whiteFilter = "0123456789"},
      {name = "First MAtricks", value = def("mtx", "MAtricks", 2 * rows, 1), whiteFilter = "0123456789"},
      {name = "First bump preset (All pool 21)", value = tostring(pre), whiteFilter = "0123456789"},
      {name = "Speed master", value = tostring(tonumber(gvar("speed") or "") or 4), whiteFilter = "0123456789"},
    },
  })
  if not r or r.result ~= 1 then return nil end
  local i = r.inputs or {}
  local function n(k) return tonumber(i[k] or "") end
  return parseGroups(i["Groups"]), {L = n("Layout"), seq0 = n("First sequence"), ap0 = n("First appearance"),
    mx0 = n("First MAtricks"), pre = n("First bump preset (All pool 21)"), speed = n("Speed master") or 0}
end

-- the presets: FS Presets' plan (made here when missing). Returns
--   looks(g, fam) -> {{name, at}, ...}, keyAt(gi, kind) -> {{group, at}, ...}, forms, cols, made, foreign
local function bumpPresets(E, groups, names)
  local made, foreign, _, recs = buildPresets(E, groups,
    {dim = true, pos = true, col = true, zoom = true, gobo = true, beam = true, strobe = true}, false)
  local bad = {}
  for _, f in ipairs(foreign) do bad[f:match("^(Preset %d+%.%d+)")] = true end
  local at, typed = {}, {}
  local list = {Dimmer = {}, Iris = {}, Zoom = {}, Position = {}}
  local TYPED = {gobo1 = "Gobo", prism = "Prism", shutter = "Shutter"}
  for _, r in ipairs(recs) do
    local a = r.pool .. "." .. r.no
    if not bad["Preset " .. a] then
      at[r.pool .. ":" .. r.label] = a
      if r.fam == "dim" and r.pool == 1 and r.label:match("^%d+%%$") then table.insert(list.Dimmer, {name = r.label, at = a})
      elseif r.wheel == "iris" then table.insert(list.Iris, {name = r.label, at = a})
      elseif r.fam == "zoom" and not r.label:find("^Focus") then table.insert(list.Zoom, {name = r.label, at = a})
      elseif r.fam == "pos" and r.pool == 2 then table.insert(list.Position, {name = r.label, at = a})
      elseif r.groups and TYPED[r.wheel] then
        for _, g in ipairs(r.groups) do
          local k = g .. ":" .. TYPED[r.wheel]
          typed[k] = typed[k] or {}
          table.insert(typed[k], {name = r.slot, at = a})
        end
      end
    end
  end
  local cols = {}
  for _, c in ipairs(E.CFG.COLORS) do
    if at["4:" .. c[1]] then cols[#cols + 1] = {name = c[1], at = at["4:" .. c[1]], rgb = c[3]} end
  end
  local function looks(g, fam)
    if fam == "Color" then return cols end
    return list[fam] or typed[tostring(g) .. ":" .. fam] or {}
  end
  -- the strobe keys' lines: the group at Full, its own strobe preset (else the shared one); pixel
  -- cells whose shutter is on their main fixtures: those strobe (at Full) instead
  local function strobeAt(gi, kind)
    local own = at["21:" .. (kind == "strobe" and "Strobe " or "Rnd ") .. names[gi]]
             or at["5:" .. (kind == "strobe" and "Strobe " or "Rnd ") .. names[gi]]
    local shared = at["21:" .. (kind == "strobe" and "Strobe" or "Rnd Strobe")] or at["5:" .. (kind == "strobe" and "Strobe" or "Rnd Strobe")]
    local l = typed[tostring(groups[gi]) .. ":Shutter"] or {}
    local ty
    for _, x in ipairs(l) do if x.name == (kind == "strobe" and "Strobe" or "Random") then ty = x.at end end
    return own or ty or shared
  end
  local full = at["1:100%"]
  local function keyAt(gi, kind)
    local g, l = groups[gi], {}
    local sel
    pcall(function() sel = tonumber((E.BM.shutter(g).sel or ""):match("^Group (%d+)$")) end)
    if full then l[#l + 1] = {g, full} end
    if sel and full then l[#l + 1] = {sel, full} end
    local s = strobeAt(gi, kind)
    if s then l[#l + 1] = {sel or g, s} end
    return l
  end
  -- the X-Key chase forms (Dimmer FX in the All pool, the main plugin's page order)
  local forms = {}
  for _, i in ipairs(E.DIM_FORMS.order) do
    local f = E.DIM_FORMS[i]
    if f[3] ~= "full" and f[3] ~= "half" and f[3] ~= "fan" and at["21:" .. f[2]] then
      forms[#forms + 1] = {name = f[2], at = at["21:" .. f[2]]}
    end
  end
  return looks, keyAt, forms, cols, made, foreign
end

-- how many fixtures group g has (for Left / Right: half of them)
local function groupSize(E, g)
  local n = 0
  pcall(function()
    Cmd("ClearSelection") Cmd("Group " .. g)
    local fi = SelectionFirst()
    while fi do n = n + 1 fi = SelectionNext(fi) end
    Cmd("ClearSelection")
  end)
  return math.max(n, 2)
end

-- a key: Sequence seq, cue 1 = recipe lines {{group or nil, "pool.no", MAtricks or nil, name = line name}, ...}
local function keySeq(E, seq, label, lines, ap)
  if E.obj("Sequence " .. seq) then E.C("Delete Sequence %d /NC", seq) end
  E.C("ClearAll")
  E.C("Store Sequence %d Cue 1 /Overwrite", seq)
  for i, l in ipairs(lines) do
    local a = string.format("Sequence %d Cue 1 Part 0.%d", seq, i)
    E.C('Store Type "StandardRecipe" %s', a)
    if l[1] then E.C("Assign Group %d At %s", l[1], a) end
    E.C("Assign Preset %s At %s", l[2], a)
    if l[3] then E.C("Assign MAtricks %d At %s", l[3], a) end
    if l.name then E.C('Set %s Property "Name" "%s"', a, l.name) end
    E.C('Set %s Property "Enabled" "Yes"', a)
  end
  E.C("Label Sequence %d %s", seq, E.q(label))
  setProp(E, "Sequence " .. seq, "OffWhenOverridden", "Yes")
  E.C("Assign Appearance %d At Sequence %d", ap, seq)
end

-- a Goto list: Sequence seq with an empty cue per item {name, ap, cmd} (the sequence is made fresh
-- and placed by the caller: deleting it here would take it off the layout)
local function listSeq(E, seq, label, items, apSeq)
  for k, it in ipairs(items) do
    E.C("ClearAll")
    E.C("Store Sequence %d Cue %d /Overwrite", seq, k)
    E.C("Label Sequence %d Cue %d %s", seq, k, E.q(it.name))
    E.C("Assign Appearance %d At Sequence %d Cue %d", it.ap, seq, k)
    E.Cany({ string.format("Assign Appearance %d At Sequence %d Cue %d Part 0", it.ap, seq, k) })
    cueCmd(E, seq, k, it.cmd)
  end
  E.C("Label Sequence %d %s", seq, E.q(label))
  setProp(E, "Sequence " .. seq, "PreferCueAppearance", "Yes")
  E.C("Assign Appearance %d At Sequence %d", apSeq, seq)
end

local function buildBumps(E, groups, o)
  local L, seq0, ap0, mx0, pre0 = o.L, o.seq0, o.ap0, o.mx0, o.pre
  E.failures = {}
  E.CFG.GROUPS = groups
  local nG = #groups
  local names = {}
  for gi, g in ipairs(groups) do names[gi] = tostring(E.objName(E.obj("Group " .. g)) or ("G" .. gi)) end
  local looks, keyAt, forms, cols, madeP, foreign = bumpPresets(E, groups, names)
  local nC = #cols
  local nSeq = (nG + 1) * (NPR + NMX)
  -- refuse to overwrite anything that isn't ours
  local clash = {}
  if not mine(E, "Layout", L) then clash[#clash + 1] = "Layout " .. L end
  for k = seq0, seq0 + nSeq - 1 do if not mine(E, "Sequence", k) then clash[#clash + 1] = "Sequence " .. k end end
  for k = ap0, ap0 + AP_N + nC - 1 do if not mine(E, "Appearance", k) then clash[#clash + 1] = "Appearance " .. k end end
  for k = mx0, mx0 + 2 * nG - 1 do if not mine(E, "MAtricks", k) then clash[#clash + 1] = "MAtricks " .. k end end
  for k = 1, NSTEP do for gi = 1, nG do
    local no = pre0 + (k - 1) * STRIDE + gi - 1
    if not minePreset(E, no) then clash[#clash + 1] = "Preset 21." .. no end
  end end
  if #clash > 0 then
    return nil, "These are already used by something else:\n  " .. table.concat(clash, "\n  ", 1, math.min(#clash, 10)) ..
      (#clash > 10 and "\n  ..." or "") .. "\n\nPick other numbers and run it again."
  end
  local P = E.CFG.PREFIX .. " " .. TAG .. " "
  local AP = {key = ap0, strobe = ap0 + 1, off = ap0 + 2, on = ap0 + 3, idle = ap0 + 4, lit = ap0 + 5, xk = ap0 + 6}
  appearance(E, AP.key, P .. "bump key", {200, 60, 40})
  appearance(E, AP.strobe, P .. "strobe key", {230, 230, 230})
  appearance(E, AP.off, P .. "picker off", {40, 56, 72})
  appearance(E, AP.on, P .. "picker on", {90, 200, 255})
  appearance(E, AP.idle, P .. "idle", {60, 60, 60})
  appearance(E, AP.lit, P .. "lit", {220, 220, 220})
  appearance(E, AP.xk, P .. "X-Key", {255, 140, 40})
  for ci, c in ipairs(cols) do
    c.ap = ap0 + AP_N + ci - 1
    appearance(E, c.ap, P .. c.name, {math.floor(c.rgb[1] * 2.55 + .5), math.floor(c.rgb[2] * 2.55 + .5), math.floor(c.rgb[3] * 2.55 + .5)})
  end
  if not E.obj("Layout " .. L) then E.C("Store Layout %d", L) end
  pcall(function() local lh = E.obj("Layout " .. L) for i = lh:Count(), 1, -1 do lh:Delete(i) end end)
  E.C("Label Layout %d %s", L, E.q(P .. "Bumps"))
  local function bmx(gi) return mx0 + gi - 1 end        -- the bump's MAtricks
  local function xmx(gi) return mx0 + nG + gi - 1 end   -- the X-Key's MAtricks
  for gi = 1, nG do
    makeMatricks(E, bmx(gi), P .. names[gi] .. " Bump")
    makeMatricks(E, xmx(gi), P .. names[gi] .. " X-Key")
  end
  local function seqNo(b, j) return seq0 + b * NPR + (j - 1) end   -- b = 0: ALL
  local function pre(gi, k) return pre0 + ((k or 1) - 1) * STRIDE + gi - 1 end
  local function stepSeq(gi, k) return seqNo(gi, J_STEP1 + k - 1) end
  local function V(k, gi) return VARP .. k .. gi end   -- a row's variable: FSBS_e1, FSBS_next1, ...
  local function textCmd(idx, text)
    return idx and string.format('Set Layout %d.%d Property "CustomTextText" %s', L, idx, E.q(text)) or nil
  end
  local function join(...) local t = {} for _, s in ipairs({...}) do if s and s ~= "" then t[#t + 1] = s end end return table.concat(t, "; ") end

  -- the bump presets, one per step (step 1 is also the Bump key's look): a recipe line per look
  -- family (values set by the pickers, which edit the step picked with Edit Step)
  local full = looks(groups[1], "Dimmer")
  for _, x in ipairs(full) do if x.name == "100%" then full.at = x.at end end
  for gi, g in ipairs(groups) do
    for st = 1, NSTEP do
      local no = pre(gi, st)
      E.C("ClearAll")
      if E.obj("Preset 21." .. no) then E.C("Delete Preset 21.%d /NC", no) end
      E.C("Store Preset 21.%d /Overwrite", no)
      E.C("Label Preset 21.%d %s", no, E.q(P .. "Bump " .. names[gi] .. (st > 1 and (" Step " .. st) or "")))
      for k, f in ipairs(FAMS) do
        local a = string.format("Preset 21.%d.%d", no, k)
        E.C('Store Type "StandardRecipe" %s', a)
        E.C("Assign Group %d At %s", g, a)
        E.C('Set %s Property "Name" "%s"', a, f[1])
      end
      -- steps 2 and 3 start at Full too (step 1 gets it from its Dim picker)
      if st > 1 and full.at then E.C('Assign Preset %s At Preset 21.%d."Dimmer"*', full.at, no) end
    end
    SetVar(GlobalVars(), V("e", gi), tostring(pre(gi, 1)))
  end
  -- the Master line (a group of your choice at Full, picked with Master: empty at first)
  local function masterLine() return full.at and {nil, full.at, nil, name = "Master"} or nil end

  -- the Go+ steps: step k plays its preset, sets which step comes next, and after Hold releases
  -- itself (cue 2 switches it off, over Out)
  for gi, g in ipairs(groups) do
    for st = 1, NSTEP do
      local ss = stepSeq(gi, st)
      keySeq(E, ss, P .. names[gi] .. " Step " .. st, {{g, "21." .. pre(gi, st), bmx(gi)}, masterLine()}, AP.key)
      cueCmd(E, ss, 1, string.format('SetGlobalVariable "%s" $%s', V("next", gi), V("after" .. st .. "_", gi)))
      E.C("Store Sequence %d Cue 2 /Overwrite", ss)
      E.Cany({ string.format('Set Sequence %d Cue 2 Property "TrigType" "Follow"', ss),
               string.format('Set Sequence %d Cue 2 Property "Trig" "Follow"', ss) })
      E.Cany({ string.format('Set Sequence %d Cue 2 Part 0 Property "CueInDelay" 0.5', ss) })
      cueCmd(E, ss, 2, "Off Sequence " .. ss)
    end
    -- 1 step at first: step 1 is followed by step 1
    SetVar(GlobalVars(), V("next", gi), tostring(stepSeq(gi, 1)))
    for st = 1, NSTEP do SetVar(GlobalVars(), V("after" .. st .. "_", gi), tostring(stepSeq(gi, 1))) end
  end

  -- the keys (Temp)
  local KEY_AP = {bump = AP.key, steps = AP.key, strobe = AP.strobe, rnd = AP.strobe, xk = AP.xk}
  local function keyLines(gi, kind)
    if kind == "bump" then return {{groups[gi], "21." .. pre(gi), bmx(gi)}} end
    if kind == "steps" then return {} end
    if kind == "xk" then
      return forms[1] and {{groups[gi], (forms.default or forms[1]).at, xmx(gi)}} or {}
    end
    return keyAt(gi, kind)
  end
  for _, f in ipairs(forms) do if f.name == "Square 1" then forms.default = f end end
  local missing = {}
  for b = 0, nG do
    if b > 0 then place(E, L, "Group " .. groups[b], 0, b, names[b]) end
    for j, k in ipairs(KEYS) do
     if k[2] == "steps" then
      -- Steps (Go+): an empty cue that switches the row's steps off and plays the next one; then
      -- it switches itself off, so the next press starts it again
      local sq = seqNo(b, j)
      keySeq(E, sq, P .. (b == 0 and "ALL" or names[b]) .. " " .. k[1], {}, AP.key)
      local l = {}
      if b == 0 then
        for gi = 1, nG do l[#l + 1] = "Go+ Sequence " .. seqNo(gi, j) end
      else
        l[1] = string.format("Off Sequence %d Thru %d", stepSeq(b, 1), stepSeq(b, NSTEP))
        l[2] = string.format("Goto Sequence $%s Cue 1", V("next", b))
      end
      l[#l + 1] = "Off Sequence " .. sq
      cueCmd(E, sq, 1, table.concat(l, "; "))
      place(E, L, "Sequence " .. sq, COL.keys + j - 1, b, b == 0 and (k[1] .. " All") or k[1], "Go+")
     else
      local lines = {}
      if b == 0 then
        for gi = 1, nG do for _, l in ipairs(keyLines(gi, k[2])) do lines[#lines + 1] = l end end
      else
        lines = keyLines(b, k[2])
        if k[2] == "bump" then lines[#lines + 1] = masterLine() end
      end
      local sq = seqNo(b, j)
      if #lines == 0 then
        missing[#missing + 1] = (b == 0 and "ALL" or names[b]) .. " " .. k[1]
        if E.obj("Sequence " .. sq) then E.C("Delete Sequence %d /NC", sq) end
      else
        keySeq(E, sq, P .. (b == 0 and "ALL" or names[b]) .. " " .. k[1], lines, KEY_AP[k[2]])
        if k[2] == "xk" and o.speed > 0 then E.trySeqMaster(sq, "SpeedMaster", "Speed", o.speed) end
        place(E, L, "Sequence " .. sq, COL.keys + j - 1, b, b == 0 and (k[1] .. " All") or k[1], "Temp")
      end
     end
    end
  end

  -- a Goto list button: made fresh and placed first (its element number goes into the cue
  -- commands); items(idx) -> {{name, ap, cmd}, ...}
  local function listBtn(b, j, col, text, label, items, startCue)
    local sq = seqNo(b, j)
    if E.obj("Sequence " .. sq) then E.C("Delete Sequence %d /NC", sq) end
    E.C("Store Sequence %d Cue 1 /Overwrite", sq)
    local idx = place(E, L, "Sequence " .. sq, col, b, text, "Goto")
    local it = items(idx)
    listSeq(E, sq, P .. (b == 0 and "ALL" or names[b]) .. " " .. label, it, AP.off)
    return sq, it
  end
  -- every row's list in column j goes to the cue named `name` (the ALL row)
  local rowNames = {}   -- [j][b] = {name -> cue}
  local function gotoRows(j, name)
    local l = {}
    for gi = 1, nG do
      local c = rowNames[j] and rowNames[j][gi] and rowNames[j][gi][name]
      if c then l[#l + 1] = string.format("Goto Sequence %d Cue %d", seqNo(gi, j), c) end
    end
    return table.concat(l, "; ")
  end
  local function remember(j, b, items)
    rowNames[j] = rowNames[j] or {}
    local t = {}
    for k, it in ipairs(items) do t[it.name] = t[it.name] or k end
    rowNames[j][b] = t
  end

  -- a picked entry's button text: "Dim 50%", "Gobo Dots"; "Iris 30%" / "Zoom Wide" as they are
  local function pickText(f, name)
    if name:find("^" .. f[2] .. " ") or name:find("^" .. f[1] .. " ") then return name end
    return f[2] .. " " .. name
  end
  -- the look pickers: cue 1 = Off (that family's line emptied), then the choices
  local starts = {}   -- {seq, cue}: the cue each list starts on
  local skipped = 0
  for fi, f in ipairs(FAMS) do
    local j = #KEYS + fi
    local col = COL.looks + fi - 1
    local union, seen = {}, {}
    for gi, g in ipairs(groups) do
      local list = looks(g, f[1])
      if #list > 0 then  -- (no such wheel on that group's fixtures: no button)
        local line = string.format('Preset 21.$%s."%s"*', V("e", gi), f[1])
        local sq, items = listBtn(gi, j, col, f[2], f[2], function(idx)
          local it = {{name = "Off", ap = AP.off, cmd = join(string.format('Set %s Property "Values" ""', line), textCmd(idx, f[2]))}}
          for _, c in ipairs(list) do
            it[#it + 1] = {name = c.name, ap = c.ap or AP.on, cmd = join(string.format("Assign Preset %s At %s", c.at, line),
                                                                         textCmd(idx, pickText(f, c.name)))}
          end
          return it
        end)
        remember(j, gi, items)
        local start = 1
        if f[1] == "Dimmer" then for k, it in ipairs(items) do if it.name == "100%" then start = k end end end
        starts[#starts + 1] = {sq, start}
        for _, c in ipairs(list) do if not seen[c.name] then seen[c.name] = true union[#union + 1] = c end end
      else
        skipped = skipped + 1
        if E.obj("Sequence " .. seqNo(gi, j)) then E.C("Delete Sequence %d /NC", seqNo(gi, j)) end
      end
    end
    -- ALL: every row to the entry with that name (rows without it keep theirs)
    if #union == 0 then
      if E.obj("Sequence " .. seqNo(0, j)) then E.C("Delete Sequence %d /NC", seqNo(0, j)) end
    else listBtn(0, j, col, f[2], f[2], function(idx)
      local it = {{name = "Off", ap = AP.off, cmd = join(gotoRows(j, "Off"), textCmd(idx, f[2]))}}
      for _, c in ipairs(union) do
        it[#it + 1] = {name = c.name, ap = c.ap or AP.on, cmd = join(gotoRows(j, c.name), textCmd(idx, pickText(f, c.name)))}
      end
      return it
    end) end
  end

  -- the group rows first, ALL last (its cues go to the rows' cues)
  local ROWS_THEN_ALL = {}
  for b = 1, nG do ROWS_THEN_ALL[b] = b end
  ROWS_THEN_ALL[nG + 1] = 0
  -- Part: which part of the group the bump lights (the bump's MAtricks)
  for _, b in ipairs(ROWS_THEN_ALL) do
    local half = b > 0 and math.ceil(groupSize(E, groups[b]) / 2) or nil
    local sq, items = listBtn(b, J_PART, COL.part, "Part All", "Part", function(idx)
      local it = {}
      for _, p in ipairs(PARTS) do
        local cmd
        if b == 0 then
          cmd = gotoRows(J_PART, p[1])
        else
          local function v(x) return x and E.q(tostring(x)) or '"None"' end
          cmd = string.format('Set MAtricks %d Property "XBlock" %s "XGroup" %s "X" %s', bmx(b), v(p[4] and half or nil), v(p[2]), v(p[3]))
        end
        it[#it + 1] = {name = p[1], ap = p[2] and AP.on or AP.off, cmd = join(cmd, textCmd(idx, "Part " .. p[1]))}
      end
      return it
    end)
    if b > 0 then remember(J_PART, b, items) starts[#starts + 1] = {sq, 1} end
  end

  -- X-Key pattern (the X-Key's MAtricks, as FireSystem's X-Keys) and form (the chase's preset)
  local PAT = {
    All = {}, In = {ph = {0, 360}, w = 2}, Random = {ph = {0, 360}, shuf = 1}, Out = {ph = {360, 0}, w = 2},
    ["Odd/Even"] = {ph = {0, 180}, grp = 2}, Right = {ph = {0, 360}}, Blocks = {ph = {0, 360}, blk = 2}, Left = {ph = {360, 0}},
  }
  for _, b in ipairs(ROWS_THEN_ALL) do
    local sq, items = listBtn(b, J_PAT, COL.pat, "Pattern", "X-Key Pattern", function(idx)
      local it = {}
      for _, xp in ipairs(E.XK_PATTERNS) do
        local name, p = xp[2], PAT[xp[2]] or {}
        local cmd
        if b == 0 then
          cmd = gotoRows(J_PAT, name)
        else
          local function v(x) return x and E.q(tostring(x)) or '"None"' end
          cmd = string.format('Set MAtricks %d Property "PhaseFromX" %s "PhaseToX" %s "XWings" %s "XShuffle" %s "XGroup" %s "XBlock" %s',
            xmx(b), v(p.ph and p.ph[1]), v(p.ph and p.ph[2]), v(p.w), v(p.shuf), v(p.grp), v(p.blk))
        end
        it[#it + 1] = {name = name, ap = AP.xk, cmd = join(cmd, textCmd(idx, "X " .. name))}
      end
      return it
    end)
    if b > 0 then
      remember(J_PAT, b, items)
      local start = 1
      for k, it in ipairs(items) do if it.name == "Left" then start = k end end  -- FireSystem's default
      starts[#starts + 1] = {sq, start}
    end
    if #forms > 0 then
      local sq2, items2 = listBtn(b, J_FORM, COL.form, "Form", "X-Key Form", function(idx)
        local it = {}
        for _, f in ipairs(forms) do
          local cmd
          if b == 0 then cmd = gotoRows(J_FORM, f.name)
          elseif E.obj("Sequence " .. seqNo(b, J_XK)) then
            cmd = string.format("Assign Preset %s At Sequence %d Cue 1 Part 0.1", f.at, seqNo(b, J_XK))
          end
          it[#it + 1] = {name = f.name, ap = AP.xk, cmd = join(cmd, textCmd(idx, f.name))}
        end
        return it
      end)
      if b > 0 then
        remember(J_FORM, b, items2)
        local start = 1
        for k, it in ipairs(items2) do if it.name == (forms.default or forms[1]).name then start = k end end
        starts[#starts + 1] = {sq2, start}
      end
    end
  end

  -- Out: the bump's release fade (its OffCue); Bump All takes the one set last
  local bumpAll = E.obj("Sequence " .. seqNo(0, J_BUMP)) and seqNo(0, J_BUMP)
  -- the sequences a row's Fade / Out apply to: its Bump key, its steps (and Bump All, which takes
  -- the one set last)
  local function bumpSeqs(r)
    local t = {seqNo(r, J_BUMP)}
    for st = 1, NSTEP do t[#t + 1] = stepSeq(r, st) end
    t[#t + 1] = bumpAll
    return t
  end
  for b = 0, nG do
    local sq = seqNo(b, J_OUT)
    local steps = {}
    for k, v in ipairs(OUTS) do steps[k] = {"Out " .. v .. "s", k == 1 and AP.idle or AP.lit} end
    cycleSeq(E, sq, P .. (b == 0 and "ALL" or names[b]) .. " Out", steps)
    local idx = place(E, L, "Sequence " .. sq, COL.out, b, "Out 0s")
    for k, v in ipairs(OUTS) do
      local l = {}
      if b == 0 then
        for gi = 1, nG do l[#l + 1] = string.format("Goto Sequence %d Cue %d", seqNo(gi, J_OUT), k) end
      else
        for _, s in ipairs(bumpSeqs(b)) do
          if s and E.obj("Sequence " .. s) then
            l[#l + 1] = string.format('Set Sequence %d Cue "OffCue" Part 0 Property "CueInFade" %s', s, tostring(v))
          end
        end
      end
      l[#l + 1] = textCmd(idx, "Out " .. v .. "s")
      cueCmd(E, sq, k, join(table.unpack(l)))
    end
    if b > 0 then starts[#starts + 1] = {sq, 1} end
  end

  -- the Go+ step settings: Edit Step (which step the look pickers change), Step Count (how many
  -- steps the Steps key goes through), Hold (how long a step stays on), Master (a group of your
  -- choice at Full with the bump and every step, e.g. the main fixtures of pixel cells)
  local showGroups = {}
  for n = 1, 999 do
    local h = E.obj("Group " .. n)
    if h then showGroups[#showGroups + 1] = {no = n, name = tostring(E.objName(h) or ("Group " .. n))} end
    if #showGroups >= 60 then break end
  end
  for _, b in ipairs(ROWS_THEN_ALL) do
    local function rowOrAll(j, name, cmd) return b == 0 and gotoRows(j, name) or cmd end
    local sq, items = listBtn(b, J_EDIT, COL.edit, "Edit Step 1", "Edit Step", function(idx)
      local it = {}
      for st = 1, NSTEP do
        local name = "Step " .. st
        it[st] = {name = name, ap = AP.on, cmd = join(rowOrAll(J_EDIT, name,
          b > 0 and string.format('SetGlobalVariable "%s" "%d"', V("e", b), pre(b, st))), textCmd(idx, "Edit " .. name))}
      end
      return it
    end)
    if b > 0 then remember(J_EDIT, b, items) starts[#starts + 1] = {sq, 1} end
    sq, items = listBtn(b, J_CNT, COL.cnt, "1 Step", "Step Count", function(idx)
      local it = {}
      for n = 1, NSTEP do
        local name = n == 1 and "1 Step" or (n .. " Steps")
        local cmd
        if b > 0 then
          local l = {string.format('SetGlobalVariable "%s" "%d"', V("next", b), stepSeq(b, 1))}
          for st = 1, NSTEP do
            l[#l + 1] = string.format('SetGlobalVariable "%s" "%d"', V("after" .. st .. "_", b), stepSeq(b, st < n and st + 1 or 1))
          end
          cmd = table.concat(l, "; ")
        end
        it[n] = {name = name, ap = AP.on, cmd = join(rowOrAll(J_CNT, name, cmd), textCmd(idx, name))}
      end
      return it
    end)
    if b > 0 then remember(J_CNT, b, items) starts[#starts + 1] = {sq, 1} end
    -- Hold: cue 2 of each step waits this long
    sq = seqNo(b, J_HOLD)
    local steps = {}
    for k, v in ipairs(HOLDS) do steps[k] = {"Hold " .. v .. "s", AP.lit} end
    cycleSeq(E, sq, P .. (b == 0 and "ALL" or names[b]) .. " Hold", steps)
    local hidx = place(E, L, "Sequence " .. sq, COL.hold, b, "Hold 0.5s")
    for k, v in ipairs(HOLDS) do
      local l = {}
      if b == 0 then
        for gi = 1, nG do l[#l + 1] = string.format("Goto Sequence %d Cue %d", seqNo(gi, J_HOLD), k) end
      else
        for st = 1, NSTEP do l[#l + 1] = string.format('Set Sequence %d Cue 2 Part 0 Property "CueInDelay" %s', stepSeq(b, st), tostring(v)) end
      end
      l[#l + 1] = textCmd(hidx, "Hold " .. v .. "s")
      cueCmd(E, sq, k, join(table.unpack(l)))
    end
    if b > 0 then starts[#starts + 1] = {sq, 2} end
    -- Master (group rows only)
    if b > 0 and full.at then
      local seqs = {seqNo(b, J_BUMP)}
      for st = 1, NSTEP do seqs[#seqs + 1] = stepSeq(b, st) end
      sq, items = listBtn(b, J_MST, COL.mst, "Master", "Master", function(idx)
        local off = {}
        for _, x in ipairs(seqs) do off[#off + 1] = string.format('Set Sequence %d Cue 1 Part 0."Master" Property "Selection" ""', x) end
        local it = {{name = "Off", ap = AP.off, cmd = join(table.concat(off, "; "), textCmd(idx, "Master"))}}
        for _, sg in ipairs(showGroups) do
          local l = {}
          for _, x in ipairs(seqs) do l[#l + 1] = string.format('Assign Group %d At Sequence %d Cue 1 Part 0."Master"', sg.no, x) end
          it[#it + 1] = {name = sg.name, ap = AP.on, cmd = join(table.concat(l, "; "), textCmd(idx, "Master " .. sg.name))}
        end
        return it
      end)
      starts[#starts + 1] = {sq, 1}
    elseif E.obj("Sequence " .. seqNo(b, J_MST)) then
      E.C("Delete Sequence %d /NC", seqNo(b, J_MST))
    end
  end

  -- Fade / Delay / Wings (lib picker): Fade = the bump's cue fade, Delay / Wings on its MAtricks
  local seq = seq0 + (nG + 1) * NPR
  seq = mxButtons(E, {L = L, n = nG, names = names, mx0 = mx0, seq0 = seq, col = COL.mx,
                      row = function(r) return r end, P = P, AP = AP, list = MXL, vals = MXV,
                      cueFade = function(r)
                        local t = {}
                        for _, s in ipairs(bumpSeqs(r)) do if s and E.obj("Sequence " .. s) then t[#t + 1] = tostring(s) end end
                        return t
                      end})

  -- start: Dim 100 %, the rest Off, Part All, X-Key Left / Square 1, Out 0 (the lists' own cues
  -- set it), then the lists go off (they show their text; the values stay)
  for _, s in ipairs(starts) do E.C("Goto Sequence %d Cue %d", s[1], s[2]) end
  for b = 0, nG do
    for _, j in ipairs({J_PART, J_PAT, J_FORM, J_EDIT, J_CNT, J_MST}) do
      if E.obj("Sequence " .. seqNo(b, j)) then E.C("Off Sequence %d", seqNo(b, j)) end
    end
    for fi = 1, #FAMS do if E.obj("Sequence " .. seqNo(b, #KEYS + fi)) then E.C("Off Sequence %d", seqNo(b, #KEYS + fi)) end end
  end
  E.C("ClearAll")
  svar("groups", E.rangeList({table.unpack(groups)})) svar("layout", L) svar("seq", seq0) svar("ap", ap0)
  svar("mtx", mx0) svar("preset", pre0) svar("speed", o.speed)
  local lines = {string.format("Layout %d: ALL + %d group rows (Sequences %d-%d, Appearances %d-%d, MAtricks %d-%d, bump Presets 21.%d-%d).",
    L, nG, seq0, seq - 1, ap0, ap0 + AP_N + nC - 1, mx0, mx0 + 2 * nG - 1, pre0, pre(nG, NSTEP)),
    "Bump / Strobe / Rnd / X-Key are Temp keys (on while held), Steps is Go+ (each press plays the next step):",
    "put the sequences on executors or X-keys as you like.",
    "Tap a picker to choose from its list; the bump plays the new look straight away."}
  if o.speed > 0 then lines[#lines + 1] = string.format("The X-Key chases follow Speed master %d.", o.speed) end
  if skipped > 0 then lines[#lines + 1] = string.format("%d pickers left out: those groups' fixtures have no such wheel.", skipped) end
  if #missing > 0 then lines[#lines + 1] = "Left out (no presets for them): " .. table.concat(missing, ", ") end
  if madeP > 0 then lines[#lines + 1] = string.format("%d missing presets were made.", madeP) end
  if #foreign > 0 then
    lines[#lines + 1] = "\nPresets in use by something else (left out of the lists):"
    for i = 1, math.min(#foreign, 8) do lines[#lines + 1] = "  " .. foreign[i] end
  end
  return lines
end

local function main(displayHandle, argument)
  if not env then
    local ok, E = pcall(build)
    if not ok then return say(tostring(E)) end
    env = E
  end
  local E = env
  local groups, o = ask(E, #E.CFG.COLORS)
  if not groups then return end
  local good = {}
  for _, g in ipairs(groups) do if E.obj("Group " .. g) then good[#good + 1] = g end end
  if #good == 0 then return say("None of those groups exist yet. Store your groups first, then run " .. TITLE .. " again.") end
  if #good > 8 then return say("Pick up to 8 groups.") end
  if not (o.L and o.seq0 and o.ap0 and o.mx0 and o.pre) then
    return say("Fill in the layout, first sequence, appearance, MAtricks and bump preset numbers.")
  end
  local ok, lines, err = pcall(buildBumps, E, good, o)
  pcall(Cmd, "ClearAll")
  if not ok then return say("Stopped: " .. tostring(lines)) end
  if not lines then return say(err) end
  if #good < #groups then lines[#lines + 1] = "Skipped groups that don't exist." end
  if #E.failures > 0 then
    lines[#lines + 1] = string.format("\n%d commands failed, first: %s", #E.failures, E.failures[1])
    for _, f in ipairs(E.failures) do Printf(TITLE .. ": " .. f) end
  end
  say(table.concat(lines, "\n"))
  pcall(Cmd, "Select Layout " .. o.L)
end

return main
