#!/usr/bin/env python3
"""Builds the tool plugins (plugins/FS<Tool>.lua) as ONE self-contained file each.

Each tool's source is src/FS<Tool>.lua. `--@INCLUDE name@` lines pull in shared tool code from
src/lib/name.lua, and the `--@MODULES@` line is replaced with this repo's copy of the FireSystem
module files (firesystem/FireSystem<Module>.lua, see tools/sync_firesystem.py), each one as
`MODS.<Name> = function(_ENV) ... end`, so a tool needs no other plugin in the show.
It also writes the version in VERSION into every plugins/FS*.xml.

    python3 tools/make_tools.py          # writes plugins/FS*.lua (and the XML versions)
    python3 tools/make_tools.py --check  # fails if a generated file is out of date
"""
import glob, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODULES = ["Config", "Core", "Art", "Looks", "State", "Fire", "Bumps", "Layouts", "Actions",
           "Setup", "Views", "Home", "Timecode", "TCEditor", "Commands"]


def module_body(name):
    path = os.path.join(ROOT, "firesystem", "FireSystem%s.lua" % name)
    text = open(path, encoding="utf-8").read()
    head = "M.%s = function(_ENV)" % name
    i = text.find(head)
    if i < 0:
        sys.exit("%s: no '%s' line" % (path, head))
    body = text[i + len(head):]
    return "-- ==== FireSystem%s.lua (copied by tools/make_tools.py) ====\nMODS.%s = function(_ENV)%s" % (name, name, body.rstrip() + "\n")


def include(m):
    path = os.path.join(ROOT, "src", "lib", m.group(1) + ".lua")
    return open(path, encoding="utf-8").read().rstrip() + "\n"


def build(src):
    text = open(src, encoding="utf-8").read()
    # shared tool code: --@INCLUDE name@ -> src/lib/name.lua (before the modules go in)
    text = re.sub(r"^--@INCLUDE (\w+)@$", include, text, flags=re.M)
    if "--@MODULES@" not in text:
        sys.exit("%s: no --@MODULES@ line" % src)
    mods = "\n".join(module_body(n) for n in MODULES)
    name = os.path.basename(src)
    banner = ("-- GENERATED by tools/make_tools.py from src/%s and firesystem/FireSystem<Module>.lua.\n"
              "-- Don't edit this file: edit those, then run `python3 tools/make_tools.py`.\n" % name)
    return banner + text.replace("--@MODULES@", mods, 1)


def version():
    v = open(os.path.join(ROOT, "VERSION"), encoding="utf-8").read().strip()
    if not re.fullmatch(r"\d+\.\d+\.\d+", v):
        sys.exit("VERSION must look like 1.2.0, got %r" % v)
    return v


def outputs():
    """(path, new text) for every generated file."""
    out = []
    for src in sorted(glob.glob(os.path.join(ROOT, "src", "FS*.lua"))):  # (src/lib isn't matched)
        name = os.path.basename(src)
        out.append((os.path.join(ROOT, "plugins", name), build(src)))
        xml = os.path.join(ROOT, "plugins", name[:-4] + ".xml")
        if not os.path.exists(xml):
            sys.exit("%s has no plugins/%s" % (name, os.path.basename(xml)))
        text = open(xml, encoding="utf-8").read()
        out.append((xml, re.sub(r'(<Plugin [^>]*Version=")[^"]*"', r'\g<1>%s"' % version(), text)))
    return out


def main():
    check = "--check" in sys.argv
    stale = []
    for path, new in outputs():
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old == new:
            continue
        if check:
            stale.append(os.path.relpath(path, ROOT))
        else:
            open(path, "w", encoding="utf-8").write(new)
            print("wrote", os.path.relpath(path, ROOT))
    if stale:
        sys.exit("out of date (run python3 tools/make_tools.py): " + ", ".join(stale))


if __name__ == "__main__":
    main()
